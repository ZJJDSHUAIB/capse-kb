# -*- coding: utf-8 -*-
"""核判断词 —— 期望答案里的那些【判断】：判分现在一条都没在看。

═══ 为什么要有这一个 ═══
    实测:题15/19/21 的期望答案里写着「并列」,而系统答的是「排名第7 vs 第8」
    (ROW_NUMBER 随手编的序号)—— ★ 判分给了【满分】。
    查了判分提示词,原因很明确:
        「除了数字和专名,标准答案里【别的话】——背景说明、补充形容、
          【结论的展开】——系统回答里【没有也不算错】。」
    ★ 那是当年【故意】划出去的一条线:为了不误伤
      (题52 答全了问题,却因为少一句"经过13年发展"被判错)。
    ★★ 所以「并列」不是"大家都忘了",是【落在了一条有意划出的线外面】。

═══ ★★★ 而「并列」和"背景说明"不一样 ═══
    背景说明 :「经过13年发展」   → 库里没有这个数,谁也没法核 → 不该判
    判断词   :「并列」           → ★ 能核:两家得分是不是同一个数
    → 所以它们该分开:能核的收回来,不能核的继续放过。

═══ 这个工具干什么 —— ★ 只查,不改 ═══
    扫全部题,把【期望答案里出现的判断词】列出来,并标注:
        · 能不能对着库核
        · 核出来的结果和期望答案说的【一不一致】
    ⚠ 它【不改编分】—— 按 评估基线.md 的冻结声明,改判分口径要单独一轮。
      这一步只是把"漏了几条、漏在哪几道"查出来。
"""
import io
import re
import sqlite3
import sys
from pathlib import Path

#  ══════════════════════════════════════════════════════════════════
#  判断词表 —— ★ 每一条都配一个【拿什么核】
#
#  ⚠ 分两类,而分类的判据是【能不能对着库算出来】:
#      【能核】库里有一个数或一个关系能把它验掉
#      【不能核】库里没有对应的东西 —— 那是写答案的人加的说明
#  ★ 这个分类【不是审美】:能核的该进要件,不能核的继续放过。
#  ══════════════════════════════════════════════════════════════════
判断词 = [
    # (名字, 正则, 能不能核, 怎么核)
    ("并列/持平", r"并列|持平|相同|一样", True,
     "查这几家的综合得分是不是同一个数"),
    ("谁更高", r"更高|高于|更高|分高|优于", True,
     "查两边的综合得分谁大"),
    ("谁更低", r"更低|低于|不如|较差", True,
     "查两边的综合得分谁小"),
    ("升/降", r"上升|下降|涨|降了|升了", True,
     "查同一机场两期的得分变化方向"),
    ("第一/最末", r"第一|最末|最后一名", True,
     "查该期得分最高/最低的是谁(而并列时要报几家)"),
    ("最多/最少", r"最多|最少|最大|最小|最高|最低|最弱|最强", True,
     "查那一列指标里的极值"),
    # ── 下面这些【不能核】── 库里没有对应的东西
    ("口径说明", r"口径|标准不同|不可比|数据量", False,
     "库里没有这个概念 —— 那是写答案的人加的提醒"),
    ("背景说明", r"经过.*年|成立于|发展", False,
     "库里没有这句,也没必要有"),
]


def 找判断词(文):
    出 = []
    for 名, 式, 能核, 怎么核 in 判断词:
        if re.search(式, str(文 or "")):
            出.append((名, 能核, 怎么核))
    return 出


def 能从问题里抽实体吗(con, q):
    """★ 这一题能不能【对着库核】—— 前提是问题里点得出实体。

    ⚠ 一个判断词"能核",和"这一题能核"是两件事:
      「并列」能核,但得先知道【谁和谁】并列 —— 那个从问题里抽。
      抽不出实体(比如"哪些机场并列"这种没点名的),这一题就核不了。
    ★ 这是【能算的】,所以不猜:抽不出来就说抽不出来。
    """
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    try:
        from route import load_airports, find_airports, find_periods
        ap = load_airports(con)
        场 = find_airports(con, q, ap)
        期 = find_periods(con, q).get("值") or []
        return len(场) >= 2 or len(期) >= 2, len(场), len(期)
    except Exception as e:
        return None, f"抽实体没跑成({type(e).__name__})", None


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--全文", action="store_true", help="把期望答案整条打出来")
    args = ap.parse_args()

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from check_eval import read_rows, EVAL_IN
    from paths import DB

    con = sqlite3.connect(DB)
    rows = [r for r in read_rows(EVAL_IN) if r["问题"]]

    print("=" * 78)
    print("  期望答案里的【判断】—— 判分现在一条都没在看")
    print("=" * 78)

    有判断, 没判断 = [], []
    for r in rows:
        词 = 找判断词(r.get("期望答案"))
        (有判断 if 词 else 没判断).append((r, 词))

    print(f"\n  问 {len(rows)} 道:")
    print(f"    期望答案里带【判断】的   {len(有判断):>2} 道")
    print(f"    只是陈述(数字+专名)的    {len(没判断):>2} 道")
    print("  ★ 判分只看数字和专名 → 上面那 %d 道里的判断,【一条都没被检查】"
          % len(有判断))

    #  ★ 按【能不能核】分 —— 那才是"该不该收回来"的依据
    能核的, 不能核的 = [], []
    for r, 词 in 有判断:
        _能 = [w for w in 词 if w[1]]
        (能核的 if _能 else 不能核的).append((r, _能))

    print(f"\n  ★★ 而它们该分开 —— 判据是【能不能对着库算出来】:")
    print(f"    能核的(库里有东西能验)   {len(能核的):>2} 道  ← 该收进要件")
    print(f"    不能核的(库里没有)       {len(不能核的):>2} 道  ← 继续放过,别误伤")

    print(f"\n{'─' * 78}")
    print("  ★★★ 能核的那些 —— 题号 / 问题 / 期望答案 / 命中哪个判断")
    print(f"{'─' * 78}")
    for r, 词 in 能核的:
        _能, 场数, 期数 = 能从问题里抽实体吗(con, r["问题"])
        #  ⚠⚠⚠ 2026-10-01:这里原来打的是「✅ 抽得出实体 / ⚠ 抽不出实体」——
        #     ★ 而那个判据【写窄了】,被题80~85 照出来:
        #       「兰州中川国际机场2025Q4哪一项指标最弱」只需要【一个机场】,
        #       而我那条判据只认"问题里有两个同类实体" → 判它"核不了"。
        #     ★★ 而"核不了"是我下的【结论】—— 结论下错了,读的人就跟着错。
        #     ★★★ 改成【只报事实】:这题抽到了几个机场、几期。
        #          "够不够核"由读的人对着上面那句「怎么核」自己看。
        #          ★ 工具该报事实,判断留给读的人 —— 那才是这把尺子该在的位置。
        标 = f"抽到 机场{场数}个 / 期次{期数}期" if _能 is not None else str(场数)
        print(f"\n  题{r['题号']:>2} [{r['类别']}] {标}")
        print(f"     问题:{r['问题']}")
        print(f"     期望:{str(r['期望答案'])[:96]}")
        print(f"     判断:{'、'.join(w[0] for w in 词)}")
        for 名, _c, 怎么核 in 词:
            print(f"       · {名} → 怎么核:{怎么核}")

    print(f"\n{'─' * 78}")
    print(f"  ★★ 不能核的 {len(不能核的)} 道 —— 它们现在被判分【故意放过】,而那是对的")
    print(f"{'─' * 78}")
    for r, 词 in 不能核的[:6]:
        print(f"  题{r['题号']:>2} [{r['类别']}] {'、'.join(w[0] for w in 词)}"
              f"  |  {str(r['期望答案'])[:52]}")
    if len(不能核的) > 6:
        print(f"  … 还有 {len(不能核的) - 6} 道")
    return 0


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    sys.exit(main())
