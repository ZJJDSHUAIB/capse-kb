# -*- coding: utf-8 -*-
"""核判断词 —— 期望答案里的那些【判断】：判分现在一条都没在看。

═══ 为什么要有这一个 ═══
    实测:题15/19/21 的期望答案里写着「并列」,而系统答的是「排名第7 vs 第8」
    (ROW_NUMBER 随手编的序号)—— ★ 判分给了【满分】。
    查了判分提示词,原因很明确:
        「除了数字和专名,标准答案里【别的话】——背景说明、补充形容、
          【结论的展开】——系统回答里【没有也不算错】。」
    ★ 那是当年【故意】划出去的一条线:为了不误伤
      (题52 答全了问题,却因为少一句"经过13年发展"被判错)。
    ★★ 所以「并列」不是"大家都忘了",是【落在了一条有意划出的线外面】。

═══ ★★★ 而「并列」和"背景说明"不一样 ═══
    背景说明 :「经过13年发展」   → 库里没有这个数,谁也没法核 → 不该判
    判断词   :「并列」           → ★ 能核:两家得分是不是同一个数
    → 所以它们该分开:能核的收回来,不能核的继续放过。

═══ 这个工具干什么 —— ★ 只查,不改 ═══
    扫全部题,把【期望答案里出现的判断词】列出来,并标注:
        · 能不能对着库核
        · 核出来的结果和期望答案说的【一不一致】
    ⚠ 它【不改编分】—— 按 评估基线.md 的冻结声明,改判分口径要单独一轮。
      这一步只是把"漏了几条、漏在哪几道"查出来。
"""
import io
import re
import sqlite3
import sys
from pathlib import Path

#  ══════════════════════════════════════════════════════════════════
#  判断词表 —— ★ 每一条都配一个【拿什么核】
#
#  ⚠ 分两类,而分类的判据是【能不能对着库算出来】:
#      【能核】库里有一个数或一个关系能把它验掉
#      【不能核】库里没有对应的东西 —— 那是写答案的人加的说明
#  ★ 这个分类【不是审美】:能核的该进要件,不能核的继续放过。
#  ══════════════════════════════════════════════════════════════════
判断词 = [
    # (名字, 正则, 能不能核, 怎么核)
    ("并列/持平", r"并列|持平|相同|一样", True,
     "查这几家的综合得分是不是同一个数"),
    ("谁更高", r"更高|高于|更高|分高|优于", True,
     "查两边的综合得分谁大"),
    ("谁更低", r"更低|低于|不如|较差", True,
     "查两边的综合得分谁小"),
    ("升/降", r"上升|下降|涨|降了|升了", True,
     "查同一机场两期的得分变化方向"),
    ("第一/最末", r"第一|最末|最后一名", True,
     "查该期得分最高/最低的是谁(而并列时要报几家)"),
    ("最多/最少", r"最多|最少|最大|最小|最高|最低|最弱|最强", True,
     "查那一列指标里的极值"),
    # ── 下面这些【不能核】── 库里没有对应的东西
    ("口径说明", r"口径|标准不同|不可比|数据量", False,
     "库里没有这个概念 —— 那是写答案的人加的提醒"),
    ("背景说明", r"经过.*年|成立于|发展", False,
     "库里没有这句,也没必要有"),
]


def 找判断词(文):
    出 = []
    for 名, 式, 能核, 怎么核 in 判断词:
        if re.search(式, str(文 or "")):
            出.append((名, 能核, 怎么核))
    return 出


def 能从问题里抽实体吗(con, q):
    """★ 这一题能不能【对着库核】—— 前提是问题里点得出实体。

    ⚠ 一个判断词"能核",和"这一题能核"是两件事:
      「并列」能核,但得先知道【谁和谁】并列 —— 那个从问题里抽。
      抽不出实体(比如"哪些机场并列"这种没点名的),这一题就核不了。
    ★ 这是【能算的】,所以不猜:抽不出来就说抽不出来。
    """
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    try:
        from route import load_airports, find_airports, find_periods
        ap = load_airports(con)
        场 = find_airports(con, q, ap)
        期 = find_periods(con, q).get("值") or []
        return len(场) >= 2 or len(期) >= 2, len(场), len(期)
    except Exception as e:
        return None, f"抽实体没跑成({type(e).__name__})", None


def _期次们(con, 文):
    """从一段话里抽期次 —— ★ 复用 route.find_periods,不另写一份。"""
    try:
        from route import find_periods
        return sorted(set(find_periods(con, 文).get("值") or []))
    except Exception:
        return []


def 验期望(con, row):
    """核这一题的【期望答案】和库对不对得上。

    ★★★ 先核最硬的一层:期望答案里写的那些【数】,和库里的一不一样。
        因为数要是不对,判断必然不对 —— 那是所有判断的地基。
    → 返回 (核过的, 没核的, 题的原因)

    ══════════════════════════════════════════════════════════════════
    ⚠⚠⚠ 2026-10-01:第一版报出 10 道"不一致",而【那 10 道全是假阳性】
    ══════════════════════════════════════════════════════════════════
    【症状 —— 跑出来是这样】
        题80~87  期望说 2025.0 · 库里是 4.1     ← 那个 2025 是从「2025Q4」里抓的
        题56     期望说 2.88  · 库里是 4.1     ← 2.88 是【指标分】,不是综合得分
        题66     期望说 39.0  · 库里是 4.09    ← 39 是【名次】
    【★★ 根因 —— 而它正是这个项目一路在打的那个病】
        我拿【名字后面的第一个数】当成了【综合得分】。
        而那个位置上可能是:期次 / 名次 / 指标分 / 综合得分。
        ★★ 「同一个位置上的一个数,有多个身份」—— 我写验具的时候又踩了一次。
        ★★★ 而假阳性的代价是真金白银的:它会让【好题看起来像错题】。
    【★ 修法 —— 核之前先判"那个数是什么量";判不出来就不核】
        ① 4 位数字(19xx/20xx) → 那是期次,跳过,取下一个数
        ② 那个数前面一小段里有「第」「排名」 → 那是名次,不核
        ③ 期望答案里出现了【指标名】 → 那个数是指标分,这一题不核
           (指标分要查【指标得分】表,而这张验具只核【综合得分】)
      ⚠ 这三条【不是我想出来的,是被假阳性逼出来的】——
        每一条都对应上面那三类错里的一个。
    """
    q = str(row.get("问题") or "")
    期望 = str(row.get("期望答案") or "")
    期 = _期次们(con, q)
    if len(期) != 1:
        return [], [], (f"问题里有 {len(期)} 个期次"
                        + (f"({','.join(期)})" if 期 else "") + " —— 不许猜")

    from route import load_airports, load_indicators
    #  ③ 出现了指标名 → 那个数是指标分,这张验具核不了
    #  ⚠⚠ 2026-10-01 修:第一版只扫【期望答案】—— 于是题56 漏了:
    #     「哪个机场2025Q4【航班不正常保障】最差」指标名在【问题】里,
    #     而期望答案只写「兰州中川国际机场：2.88(最低)」→ 判它不一致。
    #  ★ 又一次"只改一半":同一个判断(这段文字在说哪个量),
    #    我只在【一个地方】找了它的证据(期望答案),而它在【另一个地方】(问题)。
    #  → 两处都扫。宁可判成"核不了",也不要报一个假的"不一致"。
    文 = 期望 + " " + q
    try:
        指标们 = [i for i in (load_indicators(con) or []) if i and len(i) >= 3]
    except Exception:
        指标们 = []
    撞上的指标 = [i for i in 指标们 if i in 文]
    if 撞上的指标:
        return [], [], (f"问题或期望里点名了指标({撞上的指标[0]})—— "
                        f"那个数是指标分,不是综合得分,这张验具核不了")

    名们 = sorted(set(load_airports(con).values()), key=len, reverse=True)
    期次 = 期[0]
    核过, 没核 = [], []
    #  ★ 长名优先匹配,免得「上海浦东国际机场」被短名截掉一半
    位 = []
    for 名 in 名们:
        i = 期望.find(名)
        while i != -1:
            位.append((i, 名))
            i = 期望.find(名, i + len(名))
    位.sort()
    for i, 名 in 位:
        后 = 期望[i + len(名): i + len(名) + 20]
        #  ① 跳过 4 位年份(那是期次)
        后 = re.sub(r'(19|20)\d{2}Q?\d?', ' ', 后)
        m = re.search(r'(\d+(?:\.\d+)?)', 后)
        if not m:
            没核.append((名, "名字后面没跟数"))
            continue
        #  ② 那个数前面有「第/排名」→ 是名次,不核
        前文 = 后[:m.start()]
        if re.search(r'第|排名|名', 前文) or re.search(r'第|排名|名', 期望[max(0, i - 6):i]):
            没核.append((名, f"紧跟的数({m.group(1)})前面有「第/排名」,像是名次"))
            continue
        说 = float(m.group(1))
        行 = con.execute("SELECT 得分 FROM 综合得分 WHERE 期次=? AND 机场=?",
                         (期次, 名)).fetchone()
        if not 行:
            没核.append((名, f"库里 {期次} 没有这家"))
            continue
        真 = float(行[0])
        核过.append((名, 说, 真, abs(说 - 真) < 1e-9))
    #  ⚠ 同一个机场在一句话里出现两次(「虹桥 4.25 高于 浦东 4.23；虹桥排第3」)
    #     → 会报两条一样的。去重:★ 同一家、同一个数,只算一次。
    去重 = []
    for x in 核过:
        if (x[0], x[1]) not in {(y[0], y[1]) for y in 去重}:
            去重.append(x)
    return 去重, 没核, ""


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--全文", action="store_true", help="把期望答案整条打出来")
    ap.add_argument("--验", action="store_true",
                    help="★ 逐条核:期望答案里写的数,和库里对不对得上")
    args = ap.parse_args()

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from check_eval import read_rows, EVAL_IN
    from paths import DB

    con = sqlite3.connect(DB)
    rows = [r for r in read_rows(EVAL_IN) if r["问题"]]

    print("=" * 78)
    print("  期望答案里的【判断】—— 判分现在一条都没在看")
    print("=" * 78)

    有判断, 没判断 = [], []
    for r in rows:
        词 = 找判断词(r.get("期望答案"))
        (有判断 if 词 else 没判断).append((r, 词))

    print(f"\n  问 {len(rows)} 道:")
    print(f"    期望答案里带【判断】的   {len(有判断):>2} 道")
    print(f"    只是陈述(数字+专名)的    {len(没判断):>2} 道")
    print("  ★ 判分只看数字和专名 → 上面那 %d 道里的判断,【一条都没被检查】"
          % len(有判断))

    #  ★ 按【能不能核】分 —— 那才是"该不该收回来"的依据
    能核的, 不能核的 = [], []
    for r, 词 in 有判断:
        _能 = [w for w in 词 if w[1]]
        (能核的 if _能 else 不能核的).append((r, _能))

    print(f"\n  ★★ 而它们该分开 —— 判据是【能不能对着库算出来】:")
    print(f"    能核的(库里有东西能验)   {len(能核的):>2} 道  ← 该收进要件")
    print(f"    不能核的(库里没有)       {len(不能核的):>2} 道  ← 继续放过,别误伤")

    print(f"\n{'─' * 78}")
    print("  ★★★ 能核的那些 —— 题号 / 问题 / 期望答案 / 命中哪个判断")
    print(f"{'─' * 78}")
    for r, 词 in 能核的:
        _能, 场数, 期数 = 能从问题里抽实体吗(con, r["问题"])
        #  ⚠⚠⚠ 2026-10-01:这里原来打的是「✅ 抽得出实体 / ⚠ 抽不出实体」——
        #     ★ 而那个判据【写窄了】,被题80~85 照出来:
        #       「兰州中川国际机场2025Q4哪一项指标最弱」只需要【一个机场】,
        #       而我那条判据只认"问题里有两个同类实体" → 判它"核不了"。
        #     ★★ 而"核不了"是我下的【结论】—— 结论下错了,读的人就跟着错。
        #     ★★★ 改成【只报事实】:这题抽到了几个机场、几期。
        #          "够不够核"由读的人对着上面那句「怎么核」自己看。
        #          ★ 工具该报事实,判断留给读的人 —— 那才是这把尺子该在的位置。
        标 = f"抽到 机场{场数}个 / 期次{期数}期" if _能 is not None else str(场数)
        print(f"\n  题{r['题号']:>2} [{r['类别']}] {标}")
        print(f"     问题:{r['问题']}")
        print(f"     期望:{str(r['期望答案'])[:96]}")
        print(f"     判断:{'、'.join(w[0] for w in 词)}")
        for 名, _c, 怎么核 in 词:
            print(f"       · {名} → 怎么核:{怎么核}")

    #  ══════════════════════════════════════════════════════════════════
    #  ★★★★★ 2026-10-01:--验 —— 把期望答案说的，拿库核一遍
    #  ══════════════════════════════════════════════════════════════════
    if getattr(args, "验", False):
        print(f"\n\n{'=' * 78}")
        print("  ★ 核【期望答案】自己 —— 它说的数,和库对不对得上")
        print("  ⚠ 这是最硬的一层:数要是不对,判断必然不对")
        print("=" * 78)
        不一致, 核过几道, 放弃 = [], 0, []
        for r, _词 in 有判断:
            核过, 没核, 原因 = 验期望(con, r)
            if 原因:
                放弃.append((r, 原因))
                continue
            坏 = [x for x in 核过 if not x[3]]
            if 坏:
                不一致.append((r, 坏, 没核))
            核过几道 += 1

        print(f"\n  带判断的 {len(有判断)} 道里:")
        print(f"    ✅ 核过的        {核过几道:>2} 道")
        print(f"    ⚠ 核不了的      {len(放弃):>2} 道  ← 全列在下面,不蒙")
        print(f"    ★★ 核出【不一致】 {len(不一致):>2} 道")

        if 不一致:
            print(f"\n{'─' * 78}")
            print("  ★★★ 期望答案和库【对不上】的那些 —— 题号 / 问题 / 期望 / 库里")
            print(f"{'─' * 78}")
            for r, 坏, _n in 不一致:
                print(f"\n  题{r['题号']} [{r['类别']}] {r['问题']}")
                print(f"     期望:{str(r['期望答案'])[:100]}")
                for 名, 说, 真, _ok in 坏:
                    print(f"     ❌ {名}:期望说 {说} · 库里是 {真}")

        if 放弃:
            print(f"\n{'─' * 78}")
            print("  ⚠ 核不了的这些 —— 如实列出来,【不猜】")
            print(f"{'─' * 78}")
            for r, 原因 in 放弃:
                print(f"  题{r['题号']:>2} [{r['类别']}] {原因}")
                print(f"        {str(r['问题'])[:60]}")
        return 0

    print(f"\n{'─' * 78}")
    print(f"  ★★ 不能核的 {len(不能核的)} 道 —— 它们现在被判分【故意放过】,而那是对的")
    print(f"{'─' * 78}")
    for r, 词 in 不能核的[:6]:
        print(f"  题{r['题号']:>2} [{r['类别']}] {'、'.join(w[0] for w in 词)}"
              f"  |  {str(r['期望答案'])[:52]}")
    if len(不能核的) > 6:
        print(f"  … 还有 {len(不能核的) - 6} 道")
    return 0


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    sys.exit(main())
