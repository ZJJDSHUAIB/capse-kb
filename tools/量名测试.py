# -*- coding: utf-8 -*-
r"""
第 20 课后半的尺子 —— 「用户说的话,问的是不是【档位平均】」这一层,该怎么换。

═══ ★★★ 靶子不是"认得出更多说法" ═══
    第一版以为毛病是"词表太短"(只认"平均""均值")→ 换成向量就行。
    量下来不是:真值是【三态】,而现有判据只有两态。

        是    「上海浦东2025Q4和同档平均比怎么样」
        含糊  「浦东2025Q4跟它那一档的普遍水平比呢」  ← 该反问
        否    「浦东2025Q4综合得分是多少」

    ★★ 所以"句子里有没有平均两个字"这个判据,【接口上就不可能对】——
       它给不出"含糊"。换成向量也一样,除非那一层能说"含糊"。

═══ 三种做法跑同一批句子 ═══
    A 现有正则   两态 → ★ "含糊"那一组【必然错】(接口决定的,不用猜)
    B 向量       问句 vs 四句典型问法,取最近的
    C 改写       让大模型从四句里选,选不出就说"含糊"

═══ 报 3×3 对照,不是一个总分 ═══
    ★ 因为代价不一样:"是"答错是拒答(看得见),"含糊"答错是静默作答(看不出来)。

=== 怎么用 ===
    python tools/量名测试.py             # 三种都跑
    python tools/量名测试.py --只A        # 快,不加载模型不调大模型
"""
import sys, io, argparse, sqlite3
from pathlib import Path
from collections import Counter

sys.path.insert(0, str(Path(__file__).parent))
from paths import DB, DOCS

#  ★ 测试集和真值都从 说法测试集 拿 —— 不在这里另抄一份。
#    抄一份的话,改了那张表这把尺子就【悄悄量错】,而且不报错。
from 说法测试 import 读测试集, 分组

该答档均, 该反问 = "档均", "反问"
是, 含糊, 否 = "是", "含糊", "否"

#  ★ 候选量和"典型问法" —— 起草在 docs/量名表.md,这里只是它的镜像。
#    ⚠ 两处都写 = 迟早不一致。★ 所以这里【从 md 读】,不硬编码。
量名表 = DOCS / "量名表.md"


def 读候选():
    """从 量名表.md 的表格里读 (量的名字, 典型问法)。"""
    行 = []
    for ln in 量名表.read_text(encoding="utf-8").splitlines():
        if not ln.startswith("|"):
            continue
        c = [x.strip().strip("`").strip() for x in ln.strip("|").split("|")]
        if len(c) < 2 or c[0].startswith("量") or set(c[0]) <= set("- "):
            continue
        if c[0] in ("档位平均", "综合得分", "档位", "排名"):
            行.append((c[0], c[1]))
    return 行


def 真值(r):
    if r["问的是"] == 该答档均:
        return 是
    if r["问的是"] == 该反问:
        return 含糊
    return 否


#  ══════════════════════════════════════════════════════════════════
#  A 现有正则 —— 两态
# ══════════════════════════════════════════════════════════════════
def 跑A(行):
    from ask import _问的是平均
    return [(r, 真值(r), (是 if _问的是平均(r["说法"]) else 否), "两态,给不出含糊") for r in 行]


#  ══════════════════════════════════════════════════════════════════
#  B 向量 —— 问句 vs 四句典型问法
#
#  ★ 三态怎么给:top1 是「档位平均」→ 是;不是但它咬得很近 → 含糊。
#  ⚠ "咬得很近"那个阈值【要量】—— 所以这里不预设,把 margin 全报出来。
# ══════════════════════════════════════════════════════════════════
def 跑B(行, 候选):
    from vector_search import model
    import numpy as np
    名 = [c[0] for c in 候选]
    V = model().encode([c[1] for c in 候选], normalize_embeddings=True, show_progress_bar=False)
    Q = model().encode([r["说法"] for r in 行], normalize_embeddings=True, show_progress_bar=False)
    S = Q @ V.T                       # 归一化之后点积就是余弦
    出 = []
    for i, r in enumerate(行):
        order = np.argsort(-S[i])
        top1, top2 = int(order[0]), int(order[1])
        名1, 名2 = 名[top1], 名[top2]
        m = float(S[i][top1] - S[i][top2])
        判 = 是 if 名1 == "档位平均" else 否
        出.append((r, 真值(r), 判, f"top1={名1}({S[i][top1]:.3f}) top2={名2}({S[i][top2]:.3f}) 差{m:.3f}"))
    return 出


#  ══════════════════════════════════════════════════════════════════
#  C 改写 —— 让大模型从四句里选,选不出就说"含糊"
#  ★ 这就是用户说的"向量解决不了就让大模型判"那一层。
#  ⚠ 它给的答案【必须回清单里验】—— 不在清单里的,算"含糊",不许它自创。
# ══════════════════════════════════════════════════════════════════
提示词 = """用户在问下面【四件事】里的哪一件?

{清单}

【用户这一句】
{问}

★ 只回答一行,三种里挑一种:
   · 清单里的编号(1~4)—— 如果这一句【明确】在问那一件
   · 「说不清」—— 如果这一句【没说清是哪个】,或者问的是清单里没有的东西

⚠ 别猜。拿不准就写「说不清」—— 写「说不清」不算错,猜错了才算。"""


def C判一句(说法, 清单, 候选):
    """让大模型选一次。★ 不在清单里的答案 → 算「含糊」,不许它自创。"""
    from llm import chat
    try:
        a = chat(提示词.format(清单=清单, 问=说法), max_tokens=20).strip()
    except Exception as e:
        return 含糊, f"X {type(e).__name__}"
    选 = None
    for i, (n, _) in enumerate(候选, 1):
        if str(i) in a and n in a:
            选 = n
            break
    if 选 is None:
        for i, (n, _) in enumerate(候选, 1):
            if a.startswith(str(i)) or f"编号{i}" in a:
                选 = n
                break
    return (含糊 if 选 is None else (是 if 选 == "档位平均" else 否)), f"答:{a[:30]}"


def 跑C(行, 候选):
    清单 = "\n".join(f"  {i}. {n} —— 例如「{t}」" for i, (n, t) in enumerate(候选, 1))
    return [(r, 真值(r), *C判一句(r["说法"], 清单, 候选)) for r in 行]


#  ══════════════════════════════════════════════════════════════════
#  D 字面优先 + 语义兜底  ← ★★★ 这一条是从 B 的死法里看出来的
#
#  【B 死在哪 —— 而它指向一条路】
#      「浦东这季度综合得分是多少」
#      ★ 句子里【原样出现了】库里的字段名「综合得分」四个字,
#        而向量的 top1 是「档位平均」(0.563 vs 0.562,差 0.001)—— 它没认出来。
#      ★★ 也就是说:【用户和库里共用了同一批字的时候,向量是绕远路。】
#
#  【★ 而这正是今天上午机场那一半量出来的同一条】
#      机场名:用户说的字 ⊂ 库里的名字（浦东 ⊂ 上海浦东国际机场）→ 子串就够
#      量名:  用户说的字 = 库里的字段名（"综合得分" 原样出现）→ ★ 也该先子串
#      ★★★ 一个结构,两处用 —— 这就是「接线」而不是「再补一条」。
#
#  【★ 而两边都"算不出"的那部分,才是语义该管的】
#      「同档平均」「均值」「普遍水平」—— 库里没有这几个字 → 子串命中不了
#      → 才轮到 C(改写)
#
#  ★ 于是这条路的形状是【能算的算,算不出的问】—— 这个项目一路的判据。
# ══════════════════════════════════════════════════════════════════
def 库里量名(con):
    """★ 从【库】里拿量的名字 —— 不是我编的清单。"""
    名 = {"综合得分": 否, "得分": 否, "档位": 否, "排名": 否, "行业平均": 是,
          "样本量": 否, "机场数": 否, "一级指标数": 否, "二级指标数": 否}
    for (t,) in con.execute("SELECT DISTINCT 指标 FROM 指标得分"):
        名[t] = 否
    return 名


def 跑D(行, 候选, con):
    清单 = "\n".join(f"  {i}. {n} —— 例如「{t}」" for i, (n, t) in enumerate(候选, 1))
    量 = 库里量名(con)
    出 = []
    for r in 行:
        命中 = [k for k in 量 if k in r["说法"]]
        if 命中:
            k = max(命中, key=len)          # 长的优先（「综合得分」别被「得分」抢）
            判 = 量[k]
            出.append((r, 真值(r), 判, f"★ 字面命中库里的「{k}」→ 直接判，没问大模型"))
        else:
            判, 注 = C判一句(r["说法"], 清单, 候选)
            出.append((r, 真值(r), 判, f"字面没命中 → 才问改写；{注}"))
    return 出


def 报(标题, 出):
    print(f"\n{'=' * 78}\n  {标题}\n{'=' * 78}")
    表 = Counter()
    for r, 该, 判, 注 in 出:
        表[(该, 判)] += 1
        #  ⚠⚠ 第一版这里把"判=否"也标成了「静默」—— 而判=否只是【不走那条分支】,
        #     它后面可能拒答、可能判不出 —— 那都是【出声】。
        #     ★ 实测:第 7、8 句判=否,而全链里它们是"判不出"(出声)的。
        #     ★★ 又一处:尺子把"这一层说了什么"当成了"用户最后得到什么"。
        #     所以这里只报【这一层会把下游带去走哪条路】,不替下游下结论。
        if 该 == 判:
            mark = "✅"
        elif 判 == 是:
            mark = "🔇 会走去答档位平均"       # ★ 这一格才有静默作答的风险
        elif 判 == 含糊:
            mark = "⚠ 会要求澄清(过保守)"
        else:
            mark = "❌ 不走这条分支(后面多半出声)"
        print(f"  {mark} {r['号']:>2}. [该:{该:<2}] 判:{判:<2}  {r['说法'][:34]}")
        print(f"        {注}")
    print(f"\n  {'':>8}{'判=是':>8}{'判=含糊':>9}{'判=否':>8}")
    for 该 in (是, 含糊, 否):
        行s = f"  {'该=' + 该:>8}"
        for 判 in (是, 含糊, 否):
            行s += f"{表.get((该,判),0):>8}"
        print(行s)
    对 = sum(v for (a, b), v in 表.items() if a == b)
    总 = sum(表.values())
    print(f"  三态全对:{对}/{总}")
    return 对, 总


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--只A", action="store_true")
    a = ap.parse_args()
    行 = 读测试集()
    候选 = 读候选()

    print("=" * 78)
    print("  第 20 课后半 · 尺子:「这句话问的是不是【档位平均】」")
    print(f"  {len(行)} 句 · 三态真值(是 6 / 含糊 3 / 否 5)")
    print("=" * 78)
    print(f"  候选量(从 docs/量名表.md 读):{', '.join(n for n, _ in 候选)}")

    结果 = []
    结果.append(("A 现有正则(两态)", 跑A(行)))
    if not a.只A:
        结果.append(("B 向量(问句 vs 典型问法)", 跑B(行, 候选)))
        结果.append(("C 改写(大模型从清单里选)", 跑C(行, 候选)))
        结果.append(("D 字面优先 + 语义兜底", 跑D(行, 候选, sqlite3.connect(DB))))

    分 = []
    for 标题, 出 in 结果:
        分.append((标题, *报(标题, 出)))

    print("\n" + "=" * 78)
    print("  三个做法,三态全对:")
    for 标题, 对, 总 in 分:
        print(f"    {标题:<26} {对}/{总}")
    print("=" * 78)
    print("""
  ★ 这三行【不能合并成一个总分】—— 代价不一样:
     把"是"判错   → 拒答(看得见,难看但不骗人)
     ★ 把"含糊"判错 → 【静默作答】(用户看不出来) ← 这一格才是这一课的靶子
  ★★ 看表的时候先看【该=含糊】那一行 —— 那一行右边两格就是"静默作答"的次数。
  ⚠ 而 A 在那一行【必然做错】:它的接口只有两态。那不是它没调好,是它给不出。""")


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    main()
