# -*- coding: utf-8 -*-
r"""
记忆的【四种动作】—— 第 23 课。

═══ 为什么要有它（用户给的建议里那一条）═══
    会话记忆原来那六个字段,说的全是【这一轮问什么】(期次/机场/指标…)——
    ★ 而用户还会说【他自己在意什么】:
        「我关注趋势」          → 记下来
        「现在更关注趋势了」     → 改掉旧的
        「以后不用重点看排名了」 → 删掉
        「今天挺冷」            → ★ 不理
    ★★ 而【这个位置原来没有】—— 所以他说的那些话,系统听完就忘了。

═══ ★★★ 形状是【照抄现有的那个】,不是新发明 ═══
    项目里 context_resolver.解析指代 已经是这个形状:
        LLM 出 JSON patch → ★ 一律过代码校验 → 不合格就不认
    ★ 而它的 action 已经有四个(fill/update/ignore/clarify)。
    ★★ 所以这一层【不是新做一套】,是把同一套【用在偏好上】。

═══ 四种动作,而【两种要用代码查】 ═══
    insert  —— 加一条新的       ⚠ 键不能是空的、不能已经在里面
    update  —— 改一条已有的     ⚠ 键【必须已经在里面】(不然那是 insert)
    delete  —— 删一条           ⚠ 键【必须已经在里面】(不在就没什么可删)
    ignore  —— 不动             ★ 闲聊走这条

    ★★ 为什么这两条"必须在里面"要查:
       模型说"删掉排名",而它【从来没记过排名】——
       那是【它记错了】,不是用户说错了。不查就变成一次静默的假动作。

=== 怎么用 ===
    python tools/记忆动作.py                      # 跑内置的那四句
    python tools/记忆动作.py "我关注趋势"
"""
import sys, io, re, json, argparse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

动作们 = ("insert", "update", "delete", "ignore")

提示词 = """你在维护一个民航数据问答系统的【用户偏好表】。

【现在记着的偏好】
{现偏好}

【用户这一句】
{当前}

★ 判断这一句有没有【在说他自己在意什么】,然后挑一个动作:

  insert  —— 他在说一个新的在意点（表里没有）
  update  —— ★★ 他在【把一条换成另一条】（"现在更关注趋势了" =
              旧的那条不要了、换成"趋势"）—— ⚠ 这时【两个键都要填】:
              「键」= 要被换掉的那条（必须在表里）· 「新键」= 换成的那个
  delete  —— 他说【以后不要】某个已经记着的（"以后不用看排名了"）
  ignore  —— ★ 他没在说偏好（普通提问、闲聊、寒暄）—— 挑这个

★★★ 而「update」这一个动作【最容易判错】—— 实测踩到:
    用户说"现在更关注趋势了",而表里记着"排名"。
    ★ 模型给了 {{"动作":"update","键":"排名"}} —— 意思是"把排名改成趋势",
      而按那个形状落下去,结果是【排名还在、趋势没加上】✗
    ★★ 所以 update 【必须带两个键】:换掉谁、换成谁。只有一个键的,那是 delete。

★★ 三条硬规矩:
  · 键就用【他自己的说法】,不要替他改写、不要归并近义词 ——
    这张表是"记下来",不是"理解"。
  · update 和 delete 的「键」【必须在上面那张表里】——
    记都没记过的东西,换不了也删不掉。不在里面就用 insert。
  · 拿不准就 ignore —— ★ 记错一条,比漏记一条坏:
    漏记用户会再说一遍,记错他【看不出来】。

只输出 JSON,不要任何别的字:
{{"动作": "insert 或 update 或 delete 或 ignore",
  "键": "用户的那个说法（insert 时是要加的;update/delete 时是表里已有的那条;ignore 时填空）",
  "新键": "只有 update 才填 —— 换成的那一条;别的动作填空字符串",
  "说明": "一句话说清你为什么这么判"}}"""


def 判动作(当前, 现偏好=None):
    """让模型判四种动作。★ 它给的【一律过校验】。"""
    from llm import chat
    try:
        #  ⚠⚠ 2026-09-23 修:给模型看的那一份【只给键的列表】。
        #    第一版直接 json.dumps 了整张表,于是它看到的是 {"排名": {}} ——
        #    ★★ 而那个空 {} 是【内部记的"动作/轮次"】,
        #       模型把它读成了"排名这一条是空的、没记过" ✗
        #    症状:「以后不用重点看排名了」被判 ignore,理由是"没有可删的" ——
        #          ★ 而表里【明明有排名】。
        #    ★★★ 又一次「同一个字段有两个身份」:同一个 {} ,
        #        在内部是记录,给模型看却变成了"空的"。
        键们 = list((现偏好 or {}).keys())
        现有 = ("表里现在记着:\n" + "\n".join(f"  · {k}" for k in 键们)) if 键们 else "（现在什么都没记）"
        原始 = chat(提示词.format(现偏好=现有, 当前=当前), max_tokens=150).strip()
    except Exception as e:
        return {"动作": "ignore", "键": "", "说明": f"★ 没跑成({type(e).__name__})—— 不动它"}
    m = re.search(r'\{.*\}', 原始, re.S)
    if not m:
        return {"动作": "ignore", "键": "", "说明": f"★ 它没给 JSON:{原始[:80]}"}
    try:
        p = json.loads(m.group(0))
    except Exception as e:
        return {"动作": "ignore", "键": "", "说明": f"★ JSON 解析不了:{e}"}

    a = str(p.get("动作") or "").strip()
    k = str(p.get("键") or "").strip()
    k2 = str(p.get("新键") or "").strip()          # ★ 只有 update 用
    说 = str(p.get("说明") or "")
    已有 = set(现偏好 or {})

    #  ═══ ★★★ 校验:四条,每条都能查 ═══
    if a not in 动作们:
        return {"动作": "ignore", "键": "", "说明": f"★ 它给的动作「{a}」不在四种里"}
    if a == "ignore":
        return {"动作": "ignore", "键": "", "说明": 说}
    if not k:
        return {"动作": "ignore", "键": "", "说明": "★ 说了要做动作,而没给键"}
    if a in ("update", "delete") and k not in 已有:
        #  ★ 这一条最要紧 —— 见文件开头那段。
        #    模型说"删掉排名",而【从来没记过排名】→ 那是它记错了。
        #    硬做下去就是【一次静默的假动作】:表没变,而它以为变了。
        return {"动作": "ignore", "键": k,
                "说明": f"★ 它说要 {a}「{k}」,而表里【没有这一条】—— 不认,不假装做了"}
    if a == "update":
        #  ⚠⚠ 2026-09-23 修:「update」必须带【两个键】—— 换掉谁、换成谁。
        #    实测踩到:用户说"现在更关注趋势了",表里记着"排名",
        #    ★ 模型给了 {"动作":"update","键":"排名"} —— 而落下去的结果是
        #      【排名还在、趋势没加上】✗ 因为一个键的 update 画不出"换成什么"。
        #    ★★ 所以:只有一个键的,那是 delete,不是 update。
        if not k2:
            return {"动作": "delete", "键": k,
                    "说明": f"★ 它说要 update「{k}」而没给新键 —— "
                            f"没有「换成什么」,那就只是【删掉】"}
        if k2 in 已有:
            return {"动作": "ignore", "键": k2,
                    "说明": f"★ 它要把「{k}」换成「{k2}」,而「{k2}」【已经在表里】"
                            f" —— 那只要删「{k}」就够,不该两条并存"}
        return {"动作": "update", "键": k, "新键": k2, "说明": 说}
    if a == "insert" and k in 已有:
        #  ⚠⚠ 2026-09-23 修:第一版这里返回 ignore —— 而那是【丢了一个对的判断】。
        #    模型说 insert,而那一条【已经有了】;它想说的其实是"记下这个"——
        #    ★★ 而【记下一个已经有的】,在语义上就是 update。
        #    ★★★ 所以【代码把它纠正过来】,而不是丢掉:
        #        丢弃 = 用户说了一句、系统当没听见;纠正 = 它本来就是这个意思。
        #    ★ 而那正是这条链的分工:模型判"要动哪一条",代码判"那算哪种动"。
        return {"动作": "update", "键": k,
                "说明": f"★ 它说要 insert「{k}」,而已经有了 → 按 update 处理"}
    return {"动作": a, "键": k, "说明": 说}


def 应用(会话, r):
    """★ 把动作落到会话的偏好表上 —— 返回要不要写进说明。"""
    a, k = r["动作"], r["键"]
    if a == "ignore":
        return None
    if a == "delete":
        会话.偏好.pop(k, None)
        return f"★ 偏好:删掉了「{k}」"
    if a == "insert":
        会话.偏好[k] = {"动作": "insert", "轮次": 会话.轮次}
        return f"★ 偏好:记下了「{k}」"
    if a == "update":
        #  ★ update = 把旧的换掉 → 【删掉旧的、加上新的】,两步都要做。
        _新 = r.get("新键") or ""
        会话.偏好.pop(k, None)
        if _新:
            会话.偏好[_新] = {"动作": "update", "轮次": 会话.轮次}
            return f"★ 偏好:把「{k}」换成了「{_新}」"
        return f"★ 偏好:更新了「{k}」"
    return None


#  ══════════════════════════════════════════════════════════════════
#  自检:四句,把四种动作【各走一遍】
#  ★ 而且带一个反向:那一句闲聊【必须】判 ignore
# ══════════════════════════════════════════════════════════════════
用例 = [
    ("我一般关注趋势，排行看看就行", "insert", {}, "第一次说 → 该 insert"),
    ("现在更关注趋势了", "update", {"趋势": {}}, "★ 改已有的 → 该 update"),
    ("以后不用重点看排名了", "delete", {"排名": {}}, "★ 删已有的 → 该 delete"),
    ("今天挺冷", "ignore", {}, "★ 闲聊 → 该 ignore"),
]

#  ⚠⚠⚠ 已知边界（单独放,因为它【没有正确答案】—— 那正是它值得留着的原因）
#     「以后别再看排名了」,而表里【从没记过排名】。
#     ★ 实测:模型判了 insert,键="排名",理由"表达一个新的在意点"。
#     ★★ 而那个答案【不好】—— 它记下的是「排名」,而用户说的是【别再看排名】;
#        以后系统会以为"用户关注排名"。
#     ★★★ 而它也不是简单的 delete:表里没有这一条,删不了。
#     ★★★★ 所以这句的正确行为【四种动作都接不住】——
#          要么 ignore(当没听见),要么记一条【否定式】的偏好(那要改数据结构)。
#     ★ 用户 2026-09-23 的判断:「任何人都可能会问,所以加」——
#       而这一格说明:【加是加了,而"否定一个没记过的东西"这条还没通】。
#     ⚠ 所以它【不计分】,只是摆在这儿,让下一个人知道边界在哪。
边界用例 = [
    ("以后别再看排名了", {}, "★ 没记过却说不要 → 现在的四个动作都不对"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("句子", nargs="*")
    a = ap.parse_args()
    if a.句子:
        现 = {}
        for q in a.句子:
            r = 判动作(q, 现)
            print(f"  {q}\n     → {r['动作']}  键={r['键']!r}\n        {r['说明'][:80]}")
            if r["动作"] == "insert":
                现[r["键"]] = {}
            elif r["动作"] == "delete":
                现.pop(r["键"], None)
        return

    print("=" * 78)
    print("  记忆的四种动作 —— insert / update / delete / ignore")
    print("=" * 78)
    对 = 0
    for q, 该, 现, 说明 in 用例:
        r = 判动作(q, 现)
        ok = (r["动作"] == 该)
        对 += ok
        print(f"\n  {'✅' if ok else '❌'} {q}")
        print(f"     ({说明})")
        print(f"     ★ 判成 {r['动作']:<7} 键={r['键']!r}   {'✅ 和期望一致' if ok else f'❌ 期望 {该}'}")
        print(f"       {r['说明'][:90]}")
    print("\n" + "=" * 78)
    print(f"  四种动作各一遍:{对}/{len(用例)}")
    #  ★ 边界那条:跑出来看看,但【不计分】—— 因为它没有正确答案
    for q, 现, 说明 in 边界用例:
        r = 判动作(q, 现)
        print(f"\n  ⚠ 边界（不计分）:{q}")
        print(f"     ({说明})")
        print(f"     ★ 它判成 {r['动作']:<7} 键={r['键']!r}")
        print(f"       {r['说明'][:90]}")
    print("=" * 78)
    print("""
  ★ 前四句是【四种动作各一遍】,最后一句是【反向】——
     "从没记过排名,却说删排名"该被【代码拦下】,而不是假装删了。
  ★★ 而它为什么必须拦:模型记错了一条,表里没变,而它以为变了 ——
     那就是【一次静默的假动作】。""")


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    main()
