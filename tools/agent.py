        #    判据在 干活成了没() 里,不在这儿另写。
        成了 = 干活成了没(结果)
        结局 = "答" if 成了 is not False else "答不出"
        if 成了 is False:
            说明 = list(说明) + [
                "★ 选了干活那一步,而它【没拿到东西】—— 所以这一轮【没答上来】。"
                "下面那个空结果就是它的原话。"]
        记录 = {"问": q, "结局": 结局, "选中": 选中, "结果": 结果,
                "参数": (期次, 机场, 指标), "说明": 说明, "重做过": 重做过}
        self.历史.append(记录)
        return 记录


