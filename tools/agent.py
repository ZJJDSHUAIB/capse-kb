        #    ★ 所以【切段(能算) + 每段问模型"这段的意思答案里有吗"(算不出的部分)】
        #
        #  ⚠ 只在【切出来不止一段】时才跑 —— 那是能算的,省掉单句问话的那一次调用。
        #  ★ 一句话里漏了的那件要说出来 —— ★★ 见 补漏() 那段注释:
