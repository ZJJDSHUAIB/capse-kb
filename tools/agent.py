# -*- coding: utf-8 -*-
r"""
第 17 课 · 一个能【连续问】的最小 Agent —— 把工具层和记忆层接起来。

═══ 接之前是什么样 ═══
    两层【并排站着】,各自都能跑,但没连:

        工具层   run_tools(con, q)          —— 无状态:模型选 → 抽参数 → 干活
        记忆层   会话.用(q, 结果, 选中)      —— 有状态:决定这一轮该用谁

    ★ 后果:记忆层算出「该用借来的浦东」,而【没人拿这个决定去重新干活】——
      因为第一遍干活时,参数里【还没有浦东】。
    ★★ 所以「那全年呢」那类追问,记忆说"我接住了",而答案仍然是错的。

═══ ★★★ 接法:两遍 ═══
    第一遍:模型选 + 抽参数  →  得到【这一轮自己抽到了什么】
    记忆层:决定【这一轮实际该用谁】(可能借了上一轮的)
            ↓
    ★ 如果借了 → 第二遍:拿【补好的参数】重做"干活"那一步

    ⚠ 为什么要两遍,而不是"先问记忆再调工具":
      因为记忆要判断【这一轮抽到了什么】,那个判断【必须等抽完才知道】。
      而"借还是不借"又决定【干活用什么参数】—— 所以顺序只能是这个。

═══ ⚠ 这个 Agent 不做什么 ═══
    · 它【不自主决定下一步】—— 每一步做什么还是模型按牌子选,
      而"该不该重做"是【代码按规则判的】。
    · 它【不跨会话持久化】—— 关掉就没了。那是另一件事(存盘)。
"""
import sys, io
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))


class 智能体:
    """一个会话里能连续问的东西。★ 每次问都走:选工具 → 记忆 → (必要时)重做。"""

    def __init__(self, con, 让模型选=True):
        from agent_memory import 会话
        self.con = con
        self.会话 = 会话(con)          # ★ 传 con:记忆要问库"哪些字段不分机场"
        self.让模型选 = 让模型选
        self.历史 = []          # 只留给人看,不参与判断

    def 问(self, q):
        """问一句。返回一个字典 —— 三种结局:反问 / 答了 / 出错。"""
        from agent_tools import run_tools, 干活类

        #  ── 第一遍:抽参数(先不用干活,因为参数可能不全)──
        #  ★ 把【记忆里上次说的期次】当参照传下去 ——
        #    「去年」「上一期」这些说法都是【相对于参照点】的:
        #      上文说过 2024 → "去年" = 2023(而不是 2025)
        #      上文说过 2024Q2 → "上一期" = 2024Q1
        #    ⚠ 参照【只从记忆里拿】,不从这一句自己抽的期次拿 ——
        #      因为这一句可能自己就写了期次,那它就不需要参照了。
        #
        #  ⚠⚠⚠ 2026-09-22 实测踩到:参照必须【在这里取一次,之后全程用它】。
        #     第一版每次用到时都写 `self.会话.期次`,而那个字段【会被中途更新】:
        #        问「那上一期呢」:
        #          第一遍  参照=2024Q1 → 推出 2023Q3 ✅
        #          会话.用() 把 self.期次 更新成了 2023Q3
        #          重做那遍 参照=【2023Q3】→ 推"上一期" → 2022 没有 → 空 ❌
        #        ★ 于是【后面那一遍把前面那遍的好结果覆盖成了空】。
        #     ★★ 根因:同一个字段,读的时间点不同,值就不同 —— 又一个"一个量两个身份"。
        #        修法:这一轮开始时取一次,后面全用这个局部变量。
        参照 = self.会话.期次 or None
        结果, 选中 = run_tools(self.con, q, 让模型选=self.让模型选,
                                参照期次=参照)

        #  ── 记忆层:决定【这一轮实际该用谁】──
        (期次, 机场, 指标), 说明, 反问, 补过, 继承的动作 = self.会话.用(q, 结果, 选中)

        #  ═══ ★★★ 动作继承的应用 ═══
        #  会话判出"该沿用上一轮的动作"之后,【真的去调它】。
        #  ★ 为什么要有这一步:第一遍调工具时,模型【没选干活类】——
        #    所以那一遍【没有干活的结果】。沿用动作意味着【要补做一次】。
        补做过 = False
        if 继承的动作:
            补做, _ = run_tools(self.con, q, 让模型选=False,
                                覆盖参数=(期次, 机场, 指标),
                                参照期次=参照,
                                只要这些=继承的动作)
            for k, v in 补做.items():
                结果[k] = v
            补做过 = True
            #  ⚠ 这里【不再设 补过 = True】——
            #    第一版设了,于是下面"重做"那一段【也跑】,两段各调一遍工具。
            #    ★ 实测后果:重做那遍漏传参照期次,把第一遍的好结果覆盖成了空值。
            #    ★★ 而更根本的是:【两段的目的重叠了】——
            #       补做是"把缺的动作补上",重做是"拿补好的参数重跑一遍",
            #       而补做用的【已经】是补好的参数。所以一个够了。

        #  ═══ ★★★ 规则判不出(要反问)→ 【才】交给大模型再试一次 ═══
        #  【为什么放在这儿,而不是一开始就问大模型】
        #      规则快、确定、不花钱。判得出就不该问。
        #      ★ 而规则判成"反问"的那一刻,正是它【自己承认判不出】——
        #        那就是该换人试的信号。
        #
        #  【顺序:规则 → 大模型 → 校验。三层不能反】
        #      大模型给的东西【一律过 context_resolver.校验()】——
        #      它编的机场/期次/指标,库里查不到就不认。
        #      ★★ 那是这个项目的命根子:大模型会编,而编出来的格式正常、看着也对,
        #         那正是"静默失败"。所以校验不能是"看看像不像",必须查库。
        大模型补的 = None
        if 反问:
            from context_resolver import 解析指代
            #  ★ 把规则【已经知道的事】递进去 —— 包括"有歧义"那种。
            #    实测:「那上海呢」规则报了"上海对应两家,是哪一家?",
            #    而没递过去时大模型自己挑了一家 —— 挑错了校验也拦不住(两家都在库里)。
            patch = 解析指代(self.con, q, self.历史,
                             {"期次": self.会话.期次, "机场": self.会话.机场,
                              "指标": self.会话.指标},
                             已知约束=反问)
            if patch and not patch.get("_走兜底"):
                补期次 = patch.get("期次") or []
                补机场 = patch.get("机场") or None
                补指标 = patch.get("指标") or None
                if patch.get("action") in ("fill", "update") and (补期次 or 补机场 or 补指标):
                    #  ★ 它补出了东西,而且【过了校验】(没走兜底就是过了)
                    期次, 机场, 指标 = 补期次 or 期次, 补机场 or 机场, 补指标 or 指标
                    补过 = True
                    大模型补的 = patch
                    说明 = list(说明) + [
                        f"★ 规则判不出,问了大模型 —— 它说:{patch.get('说明', '')[:80]}",
                        f"★ 补出来的值【过了代码校验】(机场/期次/指标 都在库里)"]
                else:
                    大模型补的 = patch       # clarify 或 ignore —— 它也不确定
            else:
                大模型补的 = patch           # 失败,走兜底

        if 反问 and 大模型补的 is None:
            记录 = {"问": q, "结局": "反问", "反问": 反问}
            self.历史.append(记录)
            return 记录
        if 反问 and 大模型补的 is not None and not 补过:
            #  ★ 规则说"不明确",大模型也说"clarify"或它没跑成 ——
            #    那就是【真的不明确】,该反问,不该猜。
            原因 = (大模型补的.get("说明") or 大模型补的.get("_失败")
                    or "补不出来") if isinstance(大模型补的, dict) else "补不出来"
            记录 = {"问": q, "结局": "反问",
                    "反问": 反问 + f"\n      (★ 我还问了一次大模型,它也说:{str(原因)[:60]})"}
            self.历史.append(记录)
            return 记录

        #  ── ★ 如果记忆补过参数 → 拿补好的【重做一遍干活那一步】──
        #  为什么必须重做:第一遍干活时用的参数里【没有借来的那个】,
        #  所以那一次的结果是【用不全的参数】做出来的 —— 不能用。
        重做过 = False
        if 补过 and not 补做过 and any(名 in 选中 for 名 in 干活类):
            #  ⚠⚠ 2026-09-22 实测踩到:这里【漏传了参照期次】——
            #     于是重做那一遍里,「推期次」拿到 参照=None,
            #     算出空值,【把第一遍推出来的好结果覆盖掉了】。
            #     症状:问「那上一期呢」,第一遍推出 2023Q3 ✅,
            #           重做那遍推成空 ❌ —— 最后看到的是空的。
            #  ★ 根因:我给继承动作加了 `补过 = True`,于是【重做这一段也跑了】,
            #    两段各调一遍工具,而后一段漏了个参数。
            #  ★★ 教训:加了新的调用路径之后,【老的调用路径要重新看一遍** ——
            #     它的前提变了(原来它只在"借参数"时跑,现在还会在"继承动作"时跑)。
            结果, 选中 = run_tools(self.con, q, 让模型选=self.让模型选,
                                    覆盖参数=(期次, 机场, 指标),
                                    参照期次=参照)
            重做过 = True
            说明.append("★ 记忆补了参数,所以【干活那一步重做了一遍】")

        #  ═══ ★★★ 查原文取回来的原文 → 交给生成层【筛出用户要的那句】 ═══
        #  【为什么要这一步 —— 张君杰定的】
        #      他说:「取回来后不能全文回答吧?要筛选出用户想要的内容」
        #      ★ 对。而"取回来就交出去"正是第 10 课治过的病:「只会搬书」
        #        (题52 的答案从 1390 字压到 12 字)。
        #      ★★ 所以分工是:工具负责【取回来】,生成层负责【说成人话】。
        #         而生成层(gen_answer)第 10 课就有了,只是 agent 这条路【没接上】。
        #
        #  ⚠ 只在查原文时走这一步:查表取回来的本来就是【已经算好的数】,
        #    不需要再"说成话" —— 多一道反而可能把数说错。
        if "查原文" in 结果 and 结果["查原文"]["值"]:
            try:
                from ask import gen_answer
                hs = [h for h in 结果["查原文"]["值"] if h.get("文本")]
                if hs:
                    说成人话 = gen_answer(q, hs)
                    结果["查原文"]["值"] = [说成人话]
                    结果["查原文"]["怎么定的"] += ";★ 交给了生成层,筛出回答了问题的部分"
                    说明 = list(说明) + ["★ 检索取回的是原文,已交给生成层筛出答案那一段"]
            except Exception as e:
                #  ★ 生成层失败【不吞掉】—— 留着原文,并说清为什么没筛
                结果["查原文"]["怎么定的"] += (
                    f";⚠ 生成层没跑成({type(e).__name__}),所以下面是原文未筛")

        记录 = {"问": q, "结局": "答", "选中": 选中, "结果": 结果,
                "参数": (期次, 机场, 指标), "说明": 说明, "重做过": 重做过}
        self.历史.append(记录)
        return 记录


