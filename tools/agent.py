#  自检:一段【真的对话】走一遍 —— 看第二句起能不能接住
#  ★ 用例就是实测里出过问题的那几句,不是编的。
# ══════════════════════════════════════════════════════════════════
对话 = [
    #  ═══ ★★★ 前两句是【专门为了走到"重做"那条分支】造的 ═══
    #  【为什么原来那 5 句走不到】
    #      借参数的那一轮(「那全年呢」)模型只选了「推期次」——
    #      ★ 它【没选干活类】,所以没有"第二次干活",重做那条分支【永远不触发】。
    #  【要走到它,第二句得同时满足两个条件】
    #      ① 自己抽不到机场(才会去借)
    #      ② 而且要【选查表】(才有"干活那一步"可以重做)
    #  ⚠ 第一版我造的「那 2024Q2 呢」不满足② —— 它没说"得分",模型认不出要查表。
    "2023Q3 上海浦东国际机场综合得分是多少",   # ① 自己抽全 → 查表
    "那 2024Q2 的得分呢",                  # ② 抽不到机场 → 借浦东 → 查表 → ★ 该重做

    #  下面几句验别的档
    "那合肥呢",                     # ① 合肥覆盖浦东
    "2025Q4 的样本量是多少",         # ④ 独立一问,不指代(★ 但这一句现在会污染,见报告)
    "那上海呢",                     # ③ 城市名有歧义 → 该反问
]


# ══════════════════════════════════════════════════════════════════
#  ★★★ 造两个"大模型出问题"的病例 —— 对应 GPT 方案的 Case 6 / Case 7
#
#  【为什么要造】这个项目的规矩:判据"从来不响"有两个可能 ——
#      甲 系统真的不出那个错
#      乙 判据坏了,出了也不响
#    ★ 不造一个假病例,这两种【分不出来】。
#
#  造法:把 llm.chat 换成假的。★ 而它可行,是因为解析指代里
#        `from llm import chat` 是【函数内导入】—— 换掉 llm.chat 就换掉了它。
# ══════════════════════════════════════════════════════════════════
def 造病例(名字, 真chat):
    """返回 (假的 chat 函数, 说明)。

    ⚠⚠ 2026-09-22 第一版踩到:假 chat 把【所有】调用都拦了 ——
       连"选工具"那一步也拦,于是铺垫那一句直接崩(TimeoutError)。
    ★ 而我要造的病例【只针对"指代解析"那一层】。
    ★★ 所以假 chat 先看 prompt 是不是指代解析的,不是就【放给真的】。
       判据用的是提示词里那句独特的开头 —— 那是个"能算"的判断。
    """
    import json as _j

    def _是指代解析(prompt):
        #  ★ 用提示词里那句独特的话当指纹 —— 别用"action"这种可能出现的词
        return "你在帮一个民航数据问答系统【解析指代】" in prompt

    if 名字 == "超时":
        def 假(prompt, **kw):
            if _是指代解析(prompt):
                raise TimeoutError("假装连不上")
            return 真chat(prompt, **kw)
        return 假, "让【指代解析那一层】超时 —— 看走不走规则兜底"
    if 名字 == "编造":
        def 假(prompt, **kw):
            if not _是指代解析(prompt):
                return 真chat(prompt, **kw)
            #  ★ 编一个【库里没有】的机场 —— 格式完全正常,看着很合理
            return _j.dumps({"action": "fill", "期次": ["2025Q4"],
                             "机场": "桂林两江国际机场",
                             "把握": "确定", "说明": "从上一轮补的"},
                            ensure_ascii=False)
        return 假, "让大模型【编一个不存在的机场】—— 看校验拦不拦"
    if 名字 == "编期次":
        def 假(prompt, **kw):
            if not _是指代解析(prompt):
                return 真chat(prompt, **kw)
            return _j.dumps({"action": "fill", "期次": ["2022Q3"],
                             "机场": "上海浦东国际机场",
                             "把握": "确定", "说明": "从上一轮补的"},
                            ensure_ascii=False)
        return 假, "让大模型【编一个不存在的期次】—— 看校验拦不拦"
    if 名字 == "补对了":
        def 假(prompt, **kw):
            if not _是指代解析(prompt):
                return 真chat(prompt, **kw)
            #  ★ 这个值是【合法的】—— 库里真有,而且组合也对(2025Q4 有浦东)
            #    看系统采不采用。★ 它是上面三个病例的【反方向】。
            return _j.dumps({"action": "fill", "期次": ["2025Q4"],
                             "机场": "上海浦东国际机场",
                             "把握": "确定", "说明": "从上一轮补的期次"},
                            ensure_ascii=False)
        return 假, "让大模型补一个【合法的】值 —— 看系统采不采用(反方向)"
    raise KeyError(名字)


def 跑病例(con, 名字, q="那上海呢"):
    """造一个病例,跑一遍,看系统怎么反应。"""
    import llm as _llm
    from agent_memory import 会话
    from context_resolver import 解析指代
    真的 = _llm.chat
    假, 说明 = 造病例(名字, 真的)
    _llm.chat = 假
    try:
        #  ★ 先造出一个"规则判不出"的局面(要有上文,而且要它判成反问)
        a = 智能体(con)
        for 铺垫 in ("2023Q3 上海浦东国际机场综合得分是多少",):
            a.问(铺垫)
        r = a.问(q)
    finally:
        _llm.chat = 真的
    return r, 说明


