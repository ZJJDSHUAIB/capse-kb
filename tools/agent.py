# -*- coding: utf-8 -*-
r"""
第 17 课 · 一个能【连续问】的最小 Agent —— 把工具层和记忆层接起来。

═══ 接之前是什么样 ═══
    两层【并排站着】,各自都能跑,但没连:

        工具层   run_tools(con, q)          —— 无状态:模型选 → 抽参数 → 干活
        记忆层   会话.用(q, 结果, 选中)      —— 有状态:决定这一轮该用谁

    ★ 后果:记忆层算出「该用借来的浦东」,而【没人拿这个决定去重新干活】——
      因为第一遍干活时,参数里【还没有浦东】。
    ★★ 所以「那全年呢」那类追问,记忆说"我接住了",而答案仍然是错的。

═══ ★★★ 接法:两遍 ═══
    第一遍:模型选 + 抽参数  →  得到【这一轮自己抽到了什么】
    记忆层:决定【这一轮实际该用谁】(可能借了上一轮的)
            ↓
    ★ 如果借了 → 第二遍:拿【补好的参数】重做"干活"那一步

    ⚠ 为什么要两遍,而不是"先问记忆再调工具":
      因为记忆要判断【这一轮抽到了什么】,那个判断【必须等抽完才知道】。
      而"借还是不借"又决定【干活用什么参数】—— 所以顺序只能是这个。

═══ ⚠ 这个 Agent 不做什么 ═══
    · 它【不自主决定下一步】—— 每一步做什么还是模型按牌子选,
      而"该不该重做"是【代码按规则判的】。
    · 它【不跨会话持久化】—— 关掉就没了。那是另一件事(存盘)。
"""
import sys, io
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))


class 智能体:
    """一个会话里能连续问的东西。★ 每次问都走:选工具 → 记忆 → (必要时)重做。"""

    def __init__(self, con, 让模型选=True):
        from agent_memory import 会话
        self.con = con
        self.会话 = 会话(con)          # ★ 传 con:记忆要问库"哪些字段不分机场"
        self.让模型选 = 让模型选
        self.历史 = []          # 只留给人看,不参与判断

    def 问(self, q):
        """问一句。返回一个字典 —— 三种结局:反问 / 答了 / 出错。"""
        from agent_tools import run_tools, 干活类

        #  ── 第一遍:抽参数(先不用干活,因为参数可能不全)──
        结果, 选中 = run_tools(self.con, q, 让模型选=self.让模型选)

        #  ── 记忆层:决定【这一轮实际该用谁】──
        (期次, 机场, 指标), 说明, 反问, 补过 = self.会话.用(q, 结果, 选中)

        if 反问:
            记录 = {"问": q, "结局": "反问", "反问": 反问}
            self.历史.append(记录)
            return 记录

        #  ── ★ 如果记忆补过参数 → 拿补好的【重做一遍干活那一步】──
        #  为什么必须重做:第一遍干活时用的参数里【没有借来的那个】,
        #  所以那一次的结果是【用不全的参数】做出来的 —— 不能用。
        重做过 = False
        if 补过 and any(名 in 选中 for 名 in 干活类):
            结果, 选中 = run_tools(self.con, q, 让模型选=self.让模型选,
                                    覆盖参数=(期次, 机场, 指标))
            重做过 = True
            说明.append("★ 记忆补了参数,所以【干活那一步重做了一遍】")

        记录 = {"问": q, "结局": "答", "选中": 选中, "结果": 结果,
                "参数": (期次, 机场, 指标), "说明": 说明, "重做过": 重做过}
        self.历史.append(记录)
        return 记录


# ══════════════════════════════════════════════════════════════════
#  自检:一段【真的对话】走一遍 —— 看第二句起能不能接住
#  ★ 用例就是实测里出过问题的那几句,不是编的。
# ══════════════════════════════════════════════════════════════════
对话 = [
    #  ═══ ★★★ 前两句是【专门为了走到"重做"那条分支】造的 ═══
    #  【为什么原来那 5 句走不到】
    #      借参数的那一轮(「那全年呢」)模型只选了「推期次」——
    #      ★ 它【没选干活类】,所以没有"第二次干活",重做那条分支【永远不触发】。
    #  【要走到它,第二句得同时满足两个条件】
    #      ① 自己抽不到机场(才会去借)
    #      ② 而且要【选查表】(才有"干活那一步"可以重做)
    #  ⚠ 第一版我造的「那 2024Q2 呢」不满足② —— 它没说"得分",模型认不出要查表。
    "2023Q3 上海浦东国际机场综合得分是多少",   # ① 自己抽全 → 查表
    "那 2024Q2 的得分呢",                  # ② 抽不到机场 → 借浦东 → 查表 → ★ 该重做

    #  下面几句验别的档
    "那合肥呢",                     # ① 合肥覆盖浦东
    "2025Q4 的样本量是多少",         # ④ 独立一问,不指代(★ 但这一句现在会污染,见报告)
    "那上海呢",                     # ③ 城市名有歧义 → 该反问
]


def main():
    import sqlite3
    from paths import DB
    from agent_tools import 干活类

    con = sqlite3.connect(DB)
    a = 智能体(con)
    print("=" * 78)
    print("  连续对话 自检 —— 重点看【第二轮起,参数从哪来】")
    print("=" * 78)

    for i, q in enumerate(对话, 1):
        r = a.问(q)
        print(f"\n{'─' * 78}")
        print(f"  [{i}] 用户:{q}")
        if r["结局"] == "反问":
            print(f"      → ★ 反问:{r['反问']}")
            continue
        期次, 机场, 指标 = r["参数"]
        print(f"      模型选了:{r['选中']}")
        print(f"      实际用的参数:期次={期次} 机场={机场} 指标={指标}")
        print(f"      重做过:{'是 ★' if r['重做过'] else '没(参数本轮就齐)'}")
        for x in r["说明"]:
            print(f"        · {x}")
        for 名 in 干活类:
            if 名 in r["结果"]:
                v = r["结果"][名]["值"]
                if isinstance(v, list) and v and len(str(v[0])) > 50:
                    v = f"[{len(v)} 段] {str(v[0])[:50]}…"
                elif isinstance(v, str) and len(v) > 70:
                    v = v[:70] + "…"
                print(f"      【{名}】{v}")

    print("\n" + "=" * 78)
    print("""
  ★ 要看的是【第二轮】:
      「那全年呢」自己没点名机场 —— 而它干活时用的机场,
      是记忆从上一轮借来的,并且【重做了一遍】。
      没有这一层,它只会答「我认不出『那全年呢』是几期」。
""")


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    main()
