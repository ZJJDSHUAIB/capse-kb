def 干活成了没(结果):
    """★ 选了干活那一步,而它【没拿到东西】—— 那一轮【不算答】。

    ═══ 为什么要有它（实测,不是设想）═══
        多轮里问「那在它那一档里算是什么水平」:
            "结局": "答"                      ← 它说答了
            "查表": {"值": null,
                     "怎么定的": "查表这一步没能执行:CannotAnswer:…"}
        ★★ 结局是「答」,而答案是【空的】—— 一个失败的操作报出了成功的消息。
        ★★★ 而这正是这个项目一路在打的:判不出要看得见。这一处【看不见】。
        ★ 而这个毛病【今天已经犯过一次】:
           `git push … | tail -3 && echo "已推送"` 打印了「已推送」,而 push 其实失败了。

    ═══ ★★★ 判断本来就有 —— 只是放错了地方 ═══
        chat.py 的展示层里【早就判了】(打「〔结果〕没查出东西」)。
        于是:终端看得见 · Web 看不见 · agent_eval 看不见 · 图版看不见。
        ★★ 把判断写在一个【消费者】里,而不是产生结果的地方 ——
           这是"只改一半"的另一种:改的不是半个功能,是【半个世界】。

    ═══ 判据用工具自己给的字段 ═══
        `值` 是不是空的 —— 信息本来就在返回值里,原来只是【没去看】。
        不另写一条判断。

    ★ 返回:True 成了 / False 没成 / None 一个干活类都没跑(不归这条管)
    """
    from agent_tools import 干活类
    干了 = [名 for 名 in 干活类 if 名 in 结果]
    if not 干了:
        return None
    return any(结果[名].get("值") for 名 in 干了)


#  ★★★ 2026-09-23:「这句话值不值得出一份计划」的预筛。
#  【为什么要有它 —— 成本实测】
#      每句话都出计划 → 多一次调用(约 1~2 秒)。而 65 题里只有 5 道真需要 ——
#      ★ 等于 92% 的调用是白花的。
#
#  【★ 判据:召回优先,宁可多走,不要漏】
#      有逗号/分号/如果/要是/顺便/以及/还有 → 出计划。
#      实测(65 题):送 17 道(26%),而【真正需要的 5 道里 4 道被筛中】。
#      ★★ 漏掉的那一道是 64「浦东2025Q4综合得分是多少」——
#         而它本来就【不需要】planner(它是那道反向题)。
#      ★★★ 所以对真正需要的,这个筛【零漏】,代价 26%。
#  ⚠ 而它是【召回优先】的:写宽了只是多花一次调用,写窄了会让该走计划的走不到。
#     ★ 两个方向的代价不一样 —— 所以宁可宽。
_像多步 = re.compile(r'[，,；;]|如果|要是|假如|顺便|以及|还有')


def 像多步(q):
    return bool(_像多步.search(q or ""))


#  ★★★ 2026-09-23:「这句话像不像在说【他自己在意什么】」的预筛。
#  【为什么要有它 —— 成本】
#      每一句都去问一次"这是什么记忆动作" → 多一次调用。
#      ★ 而大部分句子是【问数据】,不是在说偏好。
#  【★ 判据:召回优先 —— 写宽了只是多花一次调用】
#     有这些词 → 问一次:关注 / 在意 / 重点 / 喜欢 / 习惯 / 以后 / 别再 / 不用 / 不要
#  ⚠ 而它【必然漏】—— 换个说法就认不出。★ 所以这是【临时】的,标着。
#     ★★ 长久之计:让"改写"那一层顺便判 —— 但那要多一次调用,
#        而"说偏好"这件事【本来就少】,先这样。
_像说偏好 = re.compile(r'关注|在意|重点|喜欢|习惯|以后|别再|不用|不要|偏向|更想看')


def 像说偏好(q):
    return bool(_像说偏好.search(q or ""))


def 补漏(说明, q, 结果):
    """★ 一句话里漏了的那件要说出来 —— ★★【两条路都要调它】。

    【⚠⚠⚠ 2026-09-23:这一条【被漏接了两次】】
        ① 先只接在 agent 那条路上,而 score_eval 走的是 ask → 补了一次
        ② 补进 agent 之后,只接在【老路那一段】——
           ★★ 而走【计划】那条路时它【不跑】→ 漏了那件不说 → 静默。
           ★★★ 实测:题②「表现怎么样，要是不好就说说是哪一项拖后腿」
                走计划 → 条件判不了 → 停 → ★ 而"哪一项拖后腿没答"【没说】。
        两次形状一样:【同一个检查,一处接了一处没接】。
    ★ 所以抽成函数 —— 两处都调用它,而不是两处各写一遍。

    ⚠ 只在【切出来不止一段】时才跑 —— 那是能算的,省掉单句问话的那一次调用。
    """
    try:
        from 覆盖检查 import 切段, 查覆盖, 答了啥
        if len(切段(q)) > 1:
            #  ★ 用 覆盖检查.答了啥 拼答案 —— 复用它,不另写一份。
            #    ⚠ 第一版自己拼了 `for x in 值`,而值不一定是 list,
            #      是字符串时会【逐字符】拆开 → 有的题漏了却不报。
            _答文 = 答了啥({"结果": 结果})
            _段, _覆盖 = 查覆盖(q, _答文)
            _漏 = [s for s, c in zip(_段, _覆盖) if c is False]
            if _漏:
                说明.append(
                    "★ 你这一句里还有【" + "、".join(_漏)
                    + "】这一件我没答 —— 这一轮只做了前面那一件。"
                    "★ 我不确定是「库里没有这条路」还是「我做漏了」"
                    " —— 你追一句我再查。")
    except Exception as e:
        #  ★ 覆盖检查自己失败【不吞掉】—— 说清它没跑,而不是假装没说漏什么
        说明.append(f"⚠ 覆盖检查没跑成({type(e).__name__})—— 所以这一轮"
                    f"有没有漏答，我没查。")
    return 说明


class 智能体:
    """一个会话里能连续问的东西。★ 每次问都走:选工具 → 记忆 → (必要时)重做。"""

    def __init__(self, con, 让模型选=True):
        from agent_memory import 会话
        self.con = con
        self.会话 = 会话(con)          # ★ 传 con:记忆要问库"哪些字段不分机场"
        self.让模型选 = 让模型选
        self.历史 = []          # 只留给人看,不参与判断

    def 照计划答(self, q, 计划):
        """★ 一句话【多步/带条件】→ 照着计划走,不走那张固定的图。

        ═══ 为什么单独一条路,而不是改老路 ═══
            老路是 19/19 和 59/60 的来源 —— 动它就是在动基线。
            ★ 所以【只给多步/条件开一条新路】,老路一个字不改。

        ═══ ★★★ 判据为什么是"计划自己说它有几步" ═══
            另找一条"要不要走计划"的判据 —— 量过两条,都不行:
              · 标点分段:段数和"几件事"不成比例
              · 命中几个量名:用户说的是口语,不含库里的量名
            ★★ 而"一步还是多步"是【计划自己的属性】——
              拿计划来看一眼就行,不用另判。
            ⚠ 代价:每一句【够条件】的话多一次调用(约 1~2 秒)。
        """
        from planner import 执行计划
        记录, 有问题 = 执行计划(self.con, 计划)
        说明 = [f"★ 这一轮走的是【计划】—— 它拆成了 "
                f"{len(计划.get('步骤') or [])} 步（不是那张固定的图）"]
        for r in 记录:
            if "判成" in r:
                说明.append(f"  · 第{r['步']}步是岔路口:「{r['条件']}」→ 判成【{r['判成']}】")
            elif "走的是" in r:
                说明.append(f"    → 走的是【{r['走的是']}】")
            elif "值" in r:
                说明.append(f"  · 第{r['步']}步（{r.get('工具')}）:{str(r.get('值'))[:90]}")
            elif "结果" in r:
                说明.append(f"  ⚠ {r['结果']}")
        #  ═══ ★★★ 2026-09-23 修:结果的形状要【和别的路一样】 ═══
        #  【为什么 —— 实测抓到的】
        #      第一版把它包成 结果["计划"] = {值:[…]} ——
        #      ★ 而下游认的是【干活类工具的名字】(查表/查原文/查逐项):
        #        · 覆盖检查.答了啥 只看干活类 → ★ 计划那条路的答案【拼不出来】
        #        · 于是评估里 61 和 65 的"系统答"是【空的】
        #      ★★ 而"空"会被读成"它没答" —— 又一次【形状不一致装成了内容缺失】。
        #  ★ 所以这里【按工具名拆开】,让下游一视同仁 ——
        #    那是"接线":新路的输出要能被旧路的消费者读懂,而不是逼消费者认识新名字。
        结果 = {}
        for r in 记录:
            名 = r.get("工具")
            if not 名 or "原值" not in r:
                continue
            #  ★ 用【原值】不用【值】—— 后者是给人看的摘要(带 str、带 300 字截断)。
            #    ★★ 拿摘要当值用,会出两类错:list 变字符串(`for x in 值` 逐字符)、
            #       以及长内容被静默截断。见 planner 里那段注释。
            结果[名] = {"值": r.get("原值"), "把握": r.get("把握") or "确定",
                        "怎么定的": f"照着计划走的（第{r.get('步')}步）"}
        if not 结果:
            #  ★ 一步都没跑成 —— 那是"没答上",不是"答了空的"
            结果 = {"(计划)": {"值": None, "把握": "工具答不了",
                               "怎么定的": "计划里没有任何一步跑成"}}
        值 = [str(r.get("值")) for r in 记录 if r.get("值")]
        #  ═══ ★★★ 2026-09-23 修:「有问题」和「有没有答案」是【两件事】 ═══
        #  【为什么 —— 实测抓到的,而它是"局部失败拖死全局"的又一例】
        #      问「浦东2025Q4表现怎么样，要是不好就说说是哪一项拖后腿」:
        #        第1步 查表 → ★ 拿到了「综合得分 4.23,排名第 5/42」
        #        第2步 条件「综合得分低于同档或低于自身往期水平」→ ★ 判不了
        #            ★★ 而"判不了"是【对的】:那个条件本来就含糊（没说要拿什么比）。
        #        而结果:整句变成「答不出」—— ★★★ 把【第1步已经拿到的】丢掉了。
        #      ★ 那正是这个项目一路在打的:一处出问题,不该把整个答案拖死。
        #  ★ 修法:有没有答案【只看拿没拿到值】;
        #    "有问题"进说明（它已经在记录里了）—— 用户看得见哪一步没走成。
        结局 = "答" if 值 else "答不出"
        #  ═══ ★★★ 2026-09-23:「这一轮走的是计划」要【标出来】 ═══
        #  【为什么 —— 实测照出来的可观测性缺失】
        #     我把"选中"改成【按工具名拆开】之后,计划那条路看起来和老路一模一样:
        #       · 计划里两步都是"查表" → 选中=['查表']
        #       · 而老路也是 ['查表']
        #     ★★ 于是"它到底走了哪条路"【看不出来】—— 我自己都判错了,
        #        一度以为 65 走了老路。
        #     ★★★ 而"看不见"正是这个项目一路在防的。
        #  ★ 标法:选中里加一个「计划」—— 它不是工具名,而是【这一轮怎么走的】。
        #    ⚠ 而更要紧的是:下游【不许拿它当工具】(它不是干活类,不会被执行)。
        #  ★★★ 2026-09-23:计划这条路也要【补漏】—— ★★ 见 补漏() 那段注释。
        #    ⚠⚠ 实测:题②「表现怎么样，要是不好就说说是哪一项拖后腿」
        #      走计划 → 条件判不了 → 停 → ★ 而"哪一项拖后腿没答"【没说】→ 静默。
        #      ★ 根因:补漏只接在【老路那一段】,而计划这条路【没接】——
        #        这个检查【被漏接了两次】,两次形状一样。
        说明 = 补漏(说明, q, 结果)
        记 = {"问": q, "结局": 结局, "选中": ["计划"] + list(结果), "计划": 计划,
              "结果": 结果, "走法": "计划",
              "参数": (None, None, None), "说明": 说明, "重做过": False}
        self.历史.append(记)
        return 记

    def 问(self, q):
        """问一句。返回一个字典 —— 三种结局:反问 / 答了 / 出错。"""
        from agent_tools import run_tools, 干活类

        #  ═══ ★★★ 2026-09-23:先看这一句【要不要走计划】 ═══
        #  【为什么要先筛 —— 成本】
        #      每句话都出计划 → 多一次调用。实测 65 题里只有 5 道真需要 ——
        #      ★ 等于 92% 的调用是白花的。
        #  【★ 筛的判据 —— 召回优先,宁可多走不要漏】
        #      有逗号/分号/如果/要是/顺便/以及 → 出计划
        #      ★ 实测:65 题里送 17 道(26%),而【真正需要的 5 道里 4 道被筛中】——
        #        漏掉的那一道是 64「浦东2025Q4综合得分是多少」,
        #        ★★ 而它本来就【不需要】planner。所以对真正需要的,这个筛零漏。
        #  【★★ 而"要不要照它走"是【计划自己的属性】——
        #      一步 → 走老路(那次调用算白花);多步或带条件 → 照它走。】
        #      ⚠ 而"一步也算白花"这点很要紧:它意味着【老路一个字不受影响】。
        #  ⚠⚠⚠ 2026-09-23 修:必须先初始化。
        #    第一版只在【异常时】和【else】里赋值 ——
        #    而「像多步 → 出了计划 → 但计划是单步(所以没 return)」这条路上,
        #    它【从没被赋值】→ UnboundLocalError → 19 题评估【崩了】。
        #    ★ 而那是"分支没穷尽":我写了三条路,却漏了第四条。
        #    ★★ 和"只改一半"是近亲:都是【没把情况想全】。
        #  ═══ ★★★ 2026-09-23:这一句是不是在说【他自己在意什么】? ═══
        #  【为什么加 —— 用户给的建议里那一条,而他的理由是】
        #     「任何人都可能会问,所以加」
        #  ★ 会话那六个字段说的全是"这一轮问什么",而【用户在意什么】原来没地方放。
        #
        #  ⚠⚠⚠ 而它【必须排在"拒答"那道闸之前】—— 实测踩到的:
        #      问「以后不用重点看排名了」→ ★ 它先被【拒答】了
        #        (因为句子里没写期次,route 判"你要问哪一期")
        #      ★★ 于是【压根没走到这一段】,偏好没记下。
        #      ★★★ 而"用户在说偏好"这件事【和期次无关】——
        #          它不需要查任何数据,就该在【所有闸门之前】处理。
        #      ★★★★ 又一个"顺序错了":判断本身是对的,而它被放到了后面。
        #
        #  ⚠ 而它【只在像说偏好时】才去问一次 —— 见 像说偏好() 那段(成本)。
        _偏好说明 = []
        if 像说偏好(q):
            try:
                from 记忆动作 import 判动作, 应用
                _写 = 应用(self.会话, 判动作(q, self.会话.偏好))
                if _写:
                    _偏好说明.append(_写)
            except Exception as e:
                #  ★ 它自己坏了要说出来 —— 不然用户以为"记下了",而其实没记
                _偏好说明.append(
                    f"⚠ 我判断这一句是不是在说偏好时没跑成({type(e).__name__})"
                    f" —— 所以这一句【可能没记下来】")

        #  ═══ ★★★ 2026-09-23 补:agent 这条路上【缺了"拒答"这个出口】 ═══
        #  【怎么发现的 —— 逐道对 ask 和 agent,差出来的】
        #      题54「浦东去年考了多少分」
        #        ask   → ★ 拒答(route 判的:句子里没写期次,不猜)
        #        agent → ★★ 答了「2025Q4 上海浦东国际机场:综合得分 4.23」
        #      ★ 它猜了一个期次,而且【答得像个答案】。
        #      ★★ 根因:agent 的结局值只有「答」和「反问」——
        #         【没有"拒答"这一条】,而 ask 那条路上有,来源是 route()。
        #      ★★★ 而这就是"两套并行的判断机制"的又一次代价:
        #         同一个"该不该拒答"的问题,一条路有闸、另一条路没有。
        #
        #  【★ 判据用 route() —— 接线,不另写】
