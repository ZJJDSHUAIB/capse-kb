        #      「那虹桥呢」            → 对不上任何量名 → 它没说问什么 → 借上一轮的问法
        #      「那 2024Q2 的得分呢」   → 命中「得分」   → 它说了       → 不借
        #      「2025Q4 的样本量是多少」 → 命中「样本量」  → 不借
        #    而这个是【能算的】(量名从表结构来),已实测。
        from route import 量名
        _量名 = 量名(self.con)
