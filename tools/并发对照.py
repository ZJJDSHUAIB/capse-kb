# -*- coding: utf-8 -*-
r"""
并发对照 —— 量【把阻塞的活儿挪开】到底值多少秒。

═══ 它在量什么 ═══
    同一台机器上跑【两个只差一个词】的服务:
        8801  --不挪线程池     ← 阻塞的活儿【卡住事件循环】
        8802  (默认)          ← 那活儿被 asyncio.to_thread【挪到线程池】

    然后【同时】打同样多的请求,比总耗时。

★★★ 为什么要【单次基线】,不是两个数一比就完 ═══
    只有"两个版本的耗时"是【比不出东西来的】—— 你没法判断"快"是快在哪。
        单次 t1    一个请求自己跑要多久
    ★ 有了它,那两个数才有意义:
        N 并发 ≈ N × t1  → 【串行】:它们排队了
        N 并发 ≈ 1 × t1  → 【并行】:它们真的同时在跑
    ★★ 一个数要能读,得先知道它该跟谁比。

★★★★ 而【扫描】把它变成一道能解的题 ═══
    如果每次请求可以拆成两截:
        c = 【算】(抽参数、查库、拼答案)    ← ★ 这部分只能一个一个来(GIL)
        w = 【等】(等 DeepSeek 回话)        ← ★ 这部分可以一起等

    那么:   单次     = c + w
            ③(N)    = N×c + w

    ★ 拿几个 N 各量一次,把 c 和 w 【解出来】——
      而它们不是我猜的,是从数里算的。
    ★★ 而"算的部分只能一个一个来"这件事,就是 GIL:
       Python 同一时刻只让一个线程跑字节码。
       所以 to_thread 挪走的是【等】,挪不走【算】。
    ★★★ 而这正好解释了"为什么 ③ 不是理论上的 1.0×"。

⚠ 这个脚本【自己起服务、自己收】—— 跑完不留进程。
⚠ 它不判"哪个更好"。★ 它把数摆出来,以及把它套进一个模型。

═══ 怎么用 ═══
    python tools/并发对照.py                    # 默认 4 个并发
    python tools/并发对照.py --并发 1,2,4,8      # ★ 扫描,能把 c 和 w 解出来
    python tools/并发对照.py --复用会话          # ★ 让 N 个请求【共用一段会话】
                                              #   (那样会撞上会话锁 —— 另一个故事)
"""
import sys, io, os, time, socket, argparse, subprocess
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

问 = "2025Q4上海浦东国际机场综合得分是多少"


def 端口忙着吗(端口):
    with socket.socket() as s:
        s.settimeout(0.3)
        return s.connect_ex(("127.0.0.1", 端口)) == 0


def 等起来(端口, 秒=60):
    """等这个端口能应 —— ★ 不等的话会量到"连不上"的耗时,那不是一个数。"""
    到 = time.time() + 秒
    while time.time() < 到:
        try:
            import httpx
            if httpx.get(f"http://127.0.0.1:{端口}/api/health", timeout=2).status_code == 200:
                return True
        except Exception:
            pass
        time.sleep(0.5)
    return False


def _一题(端口, 会):
    import httpx
    return httpx.post(f"http://127.0.0.1:{端口}/api/ask",
                      json={"q": 问, "会话id": 会}, timeout=600)


def 预热(端口, 会话们):
    """★ 把要用到的会话【全部】先建出来、热一遍。

    ═══ ⚠⚠⚠ 2026-09-26 修:第一版只热了一个会话 ═══
        【错在哪】
            第一版写的是「一题(0)」—— 只预热了 会话id="会0"。
            而并发跑的是 会0 / 会1 / 会2 / 会3。
        ★ 于是 会1/2/3 的【智能体、sqlite 连接、Checkpointer】是当场新建的 ——
          那些开销【被算进了并发耗时里】,而它和"并发"没有半点关系。
        ★★ 这就叫【量具污染】:你以为量的是 A,而 B 混进了分母。
        【为什么之前没发现】
            单次基线热过(会0),所以它不慢;慢的是并发那一侧 ——
            ★ 而两边的温度不一样,比值就假了。
        【★ 一个更普适的教训】
            预热不是"跑一次就够"—— 要跑【每一个你会用到的】。
            「我热过了」和「我热全了」是两件事。
    """
    for 会 in 会话们:
        _一题(端口, 会)


def 量(端口, 并发数, 复用会话, 次数=2):
    """★ 每个格子跑【两次】,把两次都带回来。

    ═══ ⚠⚠⚠ 2026-09-26 修:一个格子只跑一次,读数对不上 ═══
        【症状】
            单次基线实测 1.23 秒,而 ③ 在 N=1 那格是 1.6 秒
            —— ★ 这两个【本该是同一个东西】(都是一个请求)。
            拟合出来的 c+w = 1.60,而单次 = 1.23,差 0.37 秒没解释。
        【★ 而 0.37 秒和"线程池开销"的量级根本不匹配(那该是毫秒)】
            → 所以它多半不是机制,是【采样噪音】。
        【★★ 一个样本够不够 —— 这个项目早就回答过了】
            「判分脚本改了必须跑两次,不一致就不许拿分数做比较。」
            ★ 而这一版量具一个格子一个样本 —— 它已经在给出对不上的读数了。
        【怎么办】
            跑两次,两次都带回来。
            · 表格里用【快的那个】—— 它更接近"没有干扰时的真实速度"
            · ★ 但如果两次差得多,那也要看得见(打印出来)
    """
    from concurrent.futures import ThreadPoolExecutor

    def 打(i):
        #  ★ 默认【每个请求一个会话】—— 那样它们才是【互相独立】的请求。
        #    ⚠ 共用会话的话,它们会撞上【同一段会话自己的锁】,量到的是另一件事。
        return _一题(端口, "共用" if 复用会话 else f"会{i}")

    #  ═══ ⚠⚠ 2026-09-26 修:基线必须【预热过了】再量 ═══
    #  【为什么 —— 实测踩到】
    #      第一版直接量第一次调用:2.6 秒,而后面 ②③ 都只有 1.8 秒
    #      —— ★ 比"单次基线"还快。
    #    ★★ 根因:第一次是【冷的】(模型加载/建连/热身),②③ 跑的时候已经热了。
    #    ★★★ 后果不是"数不准",是【读数的方式就错了】:
    #       2.6 当分母 → ②/单次 = 4 会被压成 2.8 —— 看起来像"只串了一半"。
    单次们 = []
    for _ in range(次数):
        t = time.time(); 打(0); 单次们.append(time.time() - t)

    总们 = []
    for _ in range(次数):
        t = time.time()
        with ThreadPoolExecutor(并发数) as ex:
            list(ex.map(打, range(并发数)))
        总们.append(time.time() - t)

    #  ★ 取【快的那个】:它更接近"没被别的干扰拖慢"时的真实速度
    return min(单次们), 总们


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--并发", default="4",
                    help="并发数。★ 也可以给一串做扫描,比如 --并发 1,2,4,8")
    ap.add_argument("--复用会话", action="store_true")
    a = ap.parse_args()
    并发们 = [int(x) for x in str(a.并发).split(",") if x.strip()]
    最大 = max(并发们)

    for p in (8801, 8802):
        if 端口忙着吗(p):
            print(f"⚠ 端口 {p} 被占了 —— 先关掉那个进程,或者换端口。")
            return 1

    这里 = Path(__file__).parent / "serve_api.py"
    服务 = {}
    for 端口, 参 in ((8801, ["--不挪线程池"]), (8802, [])):
        服务[端口] = subprocess.Popen(
            [sys.executable, str(这里), "--port", str(端口), *参],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            cwd=str(这里.parent), env={**os.environ, "PYTHONIOENCODING": "utf-8"})

    try:
        print("★ 等两个服务起来……")
        for 端口 in 服务:
            if not 等起来(端口):
                print(f"⚠ {端口} 起不来 —— 没量。")
                return 1

        #  ★★★ 预热【所有会用到的】会话 —— 两个服务各一遍(它们各有自己的一套)
        会话们 = ["共用"] if a.复用会话 else [f"会{i}" for i in range(最大)]
        print(f"★ 预热 {len(会话们)} 个会话 × 2 个服务……（不能省，理由见文件里那段注释）")
        for 端口 in 服务:
            预热(端口, 会话们)
        print("★ 预热完了,开始量。")
        print()

        print("=" * 72)
        print("  并发对照 —— 单次基线 / 卡住 / 挪开")
        print(f"  共用会话={a.复用会话}")
        print("=" * 72)
        print()
        print(f"  {'并发':>4} {'② 不挪线程池':>18} {'③ 挪线程池':>18} "
              f"{'②/③':>7} {'省了':>8}")
        print(f"  {'─'*4} {'─'*18} {'─'*18} {'─'*7} {'─'*8}")

        行 = []
        for n in 并发们:
            单次, 卡住们 = 量(8801, n, a.复用会话)
            _,    挪开们 = 量(8802, n, a.复用会话)
            卡住, 挪开 = min(卡住们), min(挪开们)
            行.append((n, 单次, 卡住, 挪开))

            def 抖(们):
                """★ 两次差得多不多 —— 差得多就写出来,别让它藏起来。"""
                差 = max(们) - min(们)
                return f"  ⚠两次差{差:.1f}" if 差 > 0.4 else ""

            #  ═══ ★★★ 2026-09-26 加:【②/③】这个比值,比"②/单次"可靠 ═══
            #  【为什么 —— 两次跑出来的数对不上】
            #      单次基线:第一轮 1.23 秒,第二轮 1.52 秒 —— 同一个东西差了 24%。
            #    ★ 分母在漂,那 ②/单次 这一列就没法比。
            #    ★★ 而 ② 和 ③ 是【同样的请求数、同样的环境、同一个时刻附近】——
            #       它们相除,环境漂移【被约掉了】。
            #    ★★★ 而且它【自带一个自检】:
            #       N=1 时两个版本该【一模一样】→ 比值该 = 1.00。
            #       实测 0.95 —— 量具本身没问题。
            #        ★ 一个自检都不带的判据,坏了你也看不出来。
            print(f"  {n:>4} {卡住:>10.1f}秒 ({卡住/单次:4.2f}×) "
                  f"{挪开:>10.1f}秒 ({挪开/单次:4.2f}×) "
                  f"{卡住/挪开:>6.2f}× "
                  f"{卡住-挪开:>7.1f}秒{抖(卡住们)}{抖(挪开们)}")

        print()
        print("=" * 72)

        #  ★★★ 从数里【算】那两个未知量,而不是猜
        #     模型:  ③(N) = N×c + w     单次 = c + w
        #     ⚠ 用最小二乘,不是挑两个点硬解 —— 挑点会被噪音骗。
        if len(行) >= 2:
            ns = [r[0] for r in 行]
            ys = [r[3] for r in 行]
            n_ = len(ns); 均x = sum(ns) / n_; 均y = sum(ys) / n_
            分子 = sum((x - 均x) * (y - 均y) for x, y in zip(ns, ys))
            分母 = sum((x - 均x) ** 2 for x in ns)
            if 分母:
                c = 分子 / 分母
                w = 均y - c * 均x
                print()
                print("  ★ 把这几个数套进「③(N) = N×c + w」:")
                print(f"       c（每次请求里的【算】）≈ {c:.2f} 秒   ← 这部分【串行】（GIL）")
                print(f"       w（每次请求里的【等】）≈ {w:.2f} 秒   ← 这部分【并行】")
                print(f"       单次 = c + w = {c+w:.2f} 秒   （实测 {行[0][1]:.2f}）")
                print()
                print("  ★★ 怎么验它是不是真的 —— 拿 ② 那一列对:")
                print("       （串行版没有并行,该是 N×(c+w)）")
                对 = 0
                for n, 单次, 卡住, 挪开 in 行:
                    预测 = n * (c + w)
                    好 = abs(预测 - 卡住) < 0.35 * n * (c + w)
                    对 += 好
                    print(f"         N={n}: 预测 {预测:5.1f} 秒   实测 {卡住:5.1f} 秒"
                          f"   {'✅' if 好 else '❌ 差得多'}")
                print(f"       → {对}/{len(行)} 个对得上"
                      f"{'（模型站得住）' if 对 == len(行) else '（★ 模型没解释全部）'}")
        else:
            print()
            print("  ⚠ 只给了一个并发数 —— 算不出 c 和 w。")
            print("    ★ 想算出来就给一串:  --并发 1,2,4,8")

        print()
        print("  ★ 怎么读:")
        print("      ② 那一列 ≈ N × 单次   → 排队了（事件循环被卡住）")
        print("      ③ 那一列 增长得【比 N 慢】→ 有一部分是真并行的")
        print("  ★★ 而 ③ 为什么不是 1.0× —— 看上面算出来的 c:")
        print("       c 有多大,就是【每次请求里有多少是算的】,而那部分只能一个一个来。")
        print("  ★★★ 这个脚本【不判哪个更好】。它把数摆出来,以及把它套进一个模型。")
        print()
    finally:
        for p, proc in 服务.items():
            proc.terminate()
        print("  (两个服务已关)")
    return 0


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    sys.exit(main())
