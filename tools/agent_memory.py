# -*- coding: utf-8 -*-
r"""
第 17 课 · 会话记忆 —— 只记它接不住的那一件事。

═══ 为什么要它(实测,不是设想)═══
    同一个进程里问两句:

        第一句:「分析上海浦东机场近两期表现」
            抽机场 → 上海浦东国际机场  ✅
            推期次 → 2025Q3、2025Q4    ✅

        第二句:「那全年呢」
            模型只选了「推期次」→ 值=[] 把握=没找到
            ★★ 而【机场也没抽出来】—— 因为「那全年呢」里没有机场名

    ★ 所以第二句的回答是「我认不出『那全年呢』是几期」——
      而它【完全不知道"那"指的是浦东】。

═══ ★★★ 规则是张君杰定的 ═══
    他原话:
        「丙。只有当『指代对象不明确』时才反问。
          如果本轮已经抽出了实体(比如用户说『浦东去年呢』),就直接用,不反问。」

    ★ 他后半句自己推出了实现判据 —— 也就是下面 _该用谁() 里那三档:
        ① 本轮抽出了实体            → 直接用,不反问
        ② 没抽出,而且没换过话题     → 用记忆里的
        ③ 没抽出,而且【中间换过话题】→ 反问

═══ 两个方向都会坏(所以"多记"不是保险)═══
    记太少 → 接不住(「那全年呢」「那它呢」全落空)
    记太多 → ★ 污染下一句:先问浦东,再问「2025Q4 样本量」,然后「那合肥呢」——
             记忆里的浦东还在,两个机场混在一起。
             ★★ 而那个错【看不出来】:格式正常,数字也都是真的。
             ★★★ 第 5 课量出过「期次污染 37%」,那是同一个病。

═══ ⚠ 它不做什么 ═══
    它【不猜语义】。"那"指的是什么,靠的是【哪一档规则】,不是靠理解。
    ★ 因为理解错了你看不出来 —— 而按规则走,走错了至少能查到是哪一档。
"""
import sys, io, re
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))


#  ★ 指代词:这些字一出现,就说明这一句在【指上文】,而不是独立的一句
指代词 = re.compile(r'那|它|这个|那个|该|此|这家|这家')


class 会话:
    """一个会话里,记住【实体】和【话题换过没】。

    ★ 为什么只记实体(机场/指标)和期次,不记整句话:
      整句话记下来,下一轮它会拿旧的问题去搜 —— 而那是污染。
      实体是【能补主语】的最小东西。
    """

    def __init__(self, con=None):
        self.con = con          # ★ 要它,才能问库"哪些字段不分机场"
        self.期次 = []          # 最近一次定下来的期次
        self.机场 = None        # 最近一次点名的机场
        self.指标 = None
        #  ═══ ⚠⚠ 2026-09-22 自检跑出来的一处设计错 ═══
        #  第一版这里叫「换过话题」,判据是【累计有没有出现过无实体的一轮】。
        #  ★ 结果:自检第 4 句「那去年呢」【该反问却没反问】——
        #     因为前一句「2025Q4 的样本量是多少」虽然没实体,但它【借到了浦东】,
        #     于是"换过话题"没被置上。
        #  ★★ 根因:累计的标记【分不出"刚刚"和"很久以前"】。
        #     而"那…"指谁,靠的恰恰是【紧挨着的那一轮】说的是谁。
        #  ★★★ 所以改成记录【上一轮有没有实体】—— 只看紧挨着的那一轮。
        #     ★ 教训:一个累计量,当成"当前状态"用,迟早出这种事。
        self.上一轮有实体 = False
        #  ═══ ★★★ 2026-09-22 加:上一轮做了什么动作 ═══
        #  【为什么需要它 —— 量出来的缺口,不是设想】
        #      那 19 道的 Agent 评估里,有 2 道(A02/I02)失败的原因是同一个:
        #          问「那合肥新桥呢」→ 它答「合肥新桥国际机场」,然后【就没有了】
        #      ★ 它抽到了实体,但【没去干活】—— 因为那句话里没有"得分"这种动作词。
        #      ★★ "那…呢"这种指代句【会省略谓语】,而省略掉的正是动作。
        #        所以:动作也得能继承,就像参数一样。
        self.上一轮动作 = []
        self.轮次 = 0

    def 用(self, q, 结果, 选中):
        """把这一轮的抽取结果并进记忆,并决定【这一轮该用谁】。

        返回 (实际该用的参数, 说明) —— 说明里写清有没有借上一轮的。
        """
        self.轮次 += 1
        本轮机场 = 结果.get("抽机场", {}).get("值") or []
        本轮指标 = 结果.get("抽指标", {}).get("值") or []
        本轮期次 = []
        for 名 in ("抽期次", "推期次"):
            if 名 in 结果 and 结果[名]["值"]:
                本轮期次 = 结果[名]["值"]
                break

        #  ═══ ★★★ 先看工具有没有报"有歧义" —— 有就直接反问 ═══
        #  【为什么必须抢在前面 —— 实测踩到】
        #      「那上海呢」:find_airport 算得好好的,
        #        值=[] 把握=有歧义
        #        怎么定的:用户说了城市名「上海」,而它对应 2 家机场:
        #                  上海浦东国际机场、上海虹桥国际机场 —— 是哪一家?
        #      ★ 而记忆层【只读了"值"】,值是空的,于是当成"这一轮没抽到实体",
        #        转而借了上一轮的合肥 —— 把工具【已经算好的那句反问】丢掉了。
        #      ★★ 又一次"算出来了但没人用"。所以这里先查"把握"。
        歧义 = [结果[k]["怎么定的"] for k in ("抽机场", "抽指标")
                if k in 结果 and 结果[k].get("把握") == "有歧义"]
        if 歧义:
            return ((None, None, None), [], "★ " + "\n       ".join(歧义), False, [])

        有实体 = bool(本轮机场 or 本轮指标)
        借到了 = False          # ★ 这一轮有没有从记忆里【拿到】实体
        #  ★ 这一轮在不在【指代上文】—— 判据是句子里有没有指代词。
        #    为什么不是"抽没抽到实体":「那全年呢」和「样本量是多少」都没抽到,
        #    但前者在指代、后者是独立的一句 —— 靠"抽没抽到"分不开这两种。
        本轮指代 = bool(指代词.search(q))
        说明 = []

        #  ── ① 本轮抽出了实体 → 直接用,并且覆盖记忆 ──
        if 有实体:
            if 本轮机场:
                self.机场 = 本轮机场[0]
            if 本轮指标:
                self.指标 = 本轮指标[0]
            说明.append("本轮自己抽到了实体,直接用")

        #  ── ② / ③ 没抽出实体 → 看要不要借记忆 ──
        else:
            #  ═══ ★★★ 判据是【这一轮有没有指代词】—— 不是"抽没抽到实体" ═══
            #  【为什么 —— 实测三次才找到】
            #      两种句子【都没有实体】,但意思完全不同:
            #          「那全年呢」          ← 有「那」,它在指代 → 该借
            #          「2025Q4 样本量是多少」← 没有指代词,它是独立的一句 → 换话题了
            #
            #      ★ 前两版判据都错在:拿"抽没抽到实体"当区分标准 —— 而它分不开这两种。
            #      ★★ 所以真正要问的是:**这一轮的"那"还能不能唯一地指向上文**。
            #         而"中间隔了一句【不指代】的话"之后,就不能了。
            if self.机场 or self.指标:
                if not 本轮指代:
                    #  ★ 这一轮没有指代词 —— 它是个独立的问题,话题到这里断了。
                    #     所以【下一轮】如果出现"那…",就指不明确了。
                    #     ⚠ 但【这一轮】不受影响:自己没指代,就不需要指代对象。
                    pass
                elif not self.上一轮有实体:
                    #  ★ ③ 这一轮在指代,而上一轮手上没有实体 ——
                    #     那个"那"指谁不明确,该反问,不该猜。
                    #
                    #  ⚠⚠ 2026-09-22 自检跑崩:第一版这里返回 (None, None, "话"),
                    #      而调用方期望 ((期次,机场,指标), 说明, 反问) ——
                    #      它把 None 当成那个三元组去解包 → TypeError。
                    #      ★ 同一个函数两种返回形状,又是这个病,而这次是我写的。
                    return ((None, None, None), [],
                            "⚠ 你这句话里有『那』,但它指的是什么【不明确】——"
                            f"上一句我问的是别的事,再上一句说的是"
                            f"「{self.机场 or self.指标}」。"
                            "你说清指哪个,我再答,我不猜。", False, [])
                else:
                    #  ═══ ★★★ 借之前先判:这一轮问的,是不是【全行业的量】? ═══
                    #  【为什么 —— 实测抓到的污染】
                    #      「2025Q4 的样本量是多少」—— 它自己没点名机场,
                    #      于是记忆借了上一轮的【合肥新桥】,带着它去查表,
                    #      结果值=None,报「参数不全」。
                    #      ★ 而真相是:样本量是全行业的数,【本来就不该带机场】。
                    #        "参数不全"那句话是【甩锅】—— 把"我不该带它"说成"参数不够"。
                    #
                    #  【张君杰定的处理】
                    #      甲 + 说明 + 替代方向 = 【给答案、说明修正、不反问、不甩锅】
                    #      ★ 不反问:用户没问错,只是这个量本来就不分机场。
                    #      ★★ 不甩锅:不能只来一句"参数不全"。
                    #
                    #  【判据是算的】见 route.不分机场的字段() —— 看表里有没有"机场"列。
                    借到了 = True
                    if self.机场:
                        说明.append(f"★ 这一轮没点名机场,借了上一轮的「{self.机场}」")
                    if self.指标:
                        说明.append(f"★ 借了上一轮的指标「{self.指标}」")
            else:
                pass                 # 记忆本来就是空的,没什么可借

        #  期次:本轮的优先,没有就借 (期次【不算"实体"】——
        #  ★ 为什么:「2025Q4 样本量是多少」这种题有期次但没实体,
        #    而它是个【新话题】。把期次算进实体,换话题就判不出来了。)
        if 本轮期次:
            self.期次 = 本轮期次
        #  ═══ ★★★ 2026-09-23 改:去掉那个 `not 有实体` ═══
        #  【为什么 —— 实测抓到的回归】
        #      问「那合肥新桥呢」:机场换成了合肥,而期次【该借上一轮的】。
        #      ★ 而这里写的是 `elif not 有实体 and self.期次` ——
        #        这一轮【有实体】(合肥)→ 条件为假 → 【不借】。
        #      ★★ 后果:查表报"参数不全"(期次是空的),而另一个工具答了别的期。
        #
        #  ⚠⚠ 而更要紧的是:这个修法【我已经在机场和指标上做过一次了】——
        #      上次改的是"三项各判各的",而我【只改了两项,漏了第三项】。
        #      ★ 教训:同一个修法要【把所有同类的地方都改一遍** ——
        #        只改一半,比不改更坏:你会以为改完了。
        #
        #  ★ 那个 `not 有实体` 原来是干什么的?—— 注释说它是为了
        #     「2025Q4 样本量是多少」那种【有期次没实体】的题不误判成"换了话题"。
        #     而那个判据用的是 `self.上一轮有实体`,和期次的借【不是一回事】——
        #     所以去掉它不会影响"换话题"那条。
        elif self.期次:
            说明.append(f"★ 这一轮没定期次,借了上一轮的 {self.期次}")

        #  ★★ 最后再更新"上一轮有没有实体" —— 必须放在最后,
        #     因为上面 ② 那一支读的就是【上一轮】的值。
        #     ⚠ 放到前面去,它就会把"这一轮"当成"上一轮",判据当场失效。
        #
        #  ⚠⚠ 2026-09-22 自检第二次跑出来的错:第一版这里写的是 = 有实体。
        #     于是「那全年呢」虽然【借到了浦东】,标记仍是 False ——
        #     下一句「2025Q4 的样本量是多少」就【被误判成"中间换过话题"】,
        #     反问了一句根本不需要反问的话。实测:6 句里错了 3 句。
        #  ★ 根因:判据问的是"这一轮结束时,手上有没有实体" ——
        #     而【借到的也算】。借到了,就说明话题还在延续。
        #  ★★ 顺手记一句:这个标记的意义是【"上一轮结束时手上有没有实体"】,
        #     名字叫"上一轮有实体"其实不准 —— 但改名字要动调用方,先留着,
        #     把这个说明写在旁边。
        #
        #  ⚠⚠ 又踩一次:我第一版改成 bool(有实体 or self.机场 or self.指标) ——
        #     而 self.机场 是【记忆里的】,从第一轮起就【永远有值】,
        #     于是这个表达式恒为 True,反问【永远不触发】(包括真该反问的时候)。
        #  ★ 根因:拿一个【只增不减的记忆值】去当【这一轮的事实】用 ——
        #     同一个量两个身份。所以这里用【只在"借到"那一支里才置位】的局部变量。
        self.上一轮有实体 = bool(有实体 or 借到了)

        #  ═══ ★★★ 问的是【全行业的量】吗? —— 是的话要说一句 ═══
        #  【为什么提到这一层,不放在"借"的分支里】
        #      第一版这段写在"借"那一支里,结果是:
        #        「2025Q4 的样本量是多少」【没走到借】(它不指代)—— 说明就没出现。
        #      ★ 可用户【本来就不知道】"样本量不分机场"——
        #        他不知道,就会以为系统漏了机场。
        #      ★★ 所以说明该由【问的是什么】决定,不该由【借没借】决定。
        #
        #  【张君杰定的】甲 + 说明 + 替代方向 = 给答案、说明修正、不反问、不甩锅
        #      ★ 不反问:用户没问错,只是这个量本来就不分机场
        #      ★★ 不甩锅:不能只来一句"参数不全"
        if self.con is not None:
            from route import 不分机场的字段
            全行业 = sorted([f for f in 不分机场的字段(self.con) if f in q],
                            key=len, reverse=True)
            if 全行业:
                if 借到了:
                    #  ★ 借了,但借错了 —— 把它退回去。
                    #    退回之后,下面 return 就会用【本轮抽到的】(= None),
                    #    而不是记忆里的那个机场。★ 不用另设变量,改这一个标记就够。
                    借到了 = False
                    说明.append("★ 我把刚才借来的那个机场【退回去了】—— 见下一条。")
                说明.append(
                    f"★ 你问的「{全行业[0]}」是【全行业】的数 —— 每一期一个,"
                    f"【不分机场】。所以你不用点名某个机场。")
                说明.append(
                    "★ 能按机场分的量是:综合得分、各个一级指标得分。"
                    "你要是想问某个机场所在档位的情况,"
                    "可以说「XX 所在档位有多少家机场」。")

        #  ═══ ★★★ 返回什么 —— 这里踩过一次,要说清 ═══
        #  【踩到的是什么】
        #      第一版直接 return (self.期次, self.机场, self.指标) ——
        #      而那是【记忆里的值】。智能体把它当成【这一轮该用的参数】用。
        #      ★ 于是「2025Q4 的样本量是多少」这一轮明明【没借】,
        #        返回的却是记忆里的合肥 —— 而它带着合肥去查表,查了个空。
        #      ★★ 根因:self.机场 这个字段【有两个身份】——
        #          既是"记忆里存着什么",又是"这一轮该用什么"。
        #          而这两件事在"没借"的时候【不一样】:
        #            记忆里还是合肥(留着下一轮借),而这一轮该用的是【无】。
        #
        #  ★★★ 这个病从第 5 课的 [:120] 起就在打 —— 而这次是我自己写的。
        #        所以:把"该用的"和"记着的"分开算。
        #
        #  ★ 期次不参与这个区分:它【先用自己的,没有再借】——
        #    而那个逻辑上面已经处理了,self.期次 就是这一轮该用的。
        #  ═══ ★★★ 2026-09-22 改:三项各判各的,不共用一个"借没借" ═══
        #  【为什么 —— 实测抓到的】
        #      问「那合肥新桥呢」:它【有实体】(合肥),于是走"有实体"那一支,
        #      而那一支【不借】—— 所以 指标 是 None。
        #      ★ 而上一轮刚抽到过「综合得分」—— 那句话里没有指标名,
        #        所以 answer_sql 认不出 → 抛 CannotAnswer。
        #      ★★ 根因:"有实体"被当成了"参数齐了"。
        #         而参数有三项 —— 用户可能只给了一项。
        #
        #  ★★★ 所以:【每一项自己判自己】—— 本轮抽到了就用本轮的,没抽到就用记忆里的。
        #      而那正是三档规则里 ② 那一条的精神,只是它原来只对"完全没实体"生效。
        #
        #  ⚠ 会不会借过头?"2025Q4 的样本量是多少"那一类里,借来的机场
        #     【已经被上面那段"全行业"的处理丢掉了】—— 所以是安全的。
        该用机场 = 本轮机场[0] if 本轮机场 else self.机场
        该用指标 = 本轮指标[0] if 本轮指标 else self.指标

        #  ═══ ★★★ 动作继承(2026-09-22)—— 量出来的缺口 ═══
        #  【为什么需要它 —— 不是设想,是分数照出来的】
        #      那 19 道的 Agent 评估里,2 道(A02/I02)失败的原因是同一个:
        #          问「那合肥新桥呢」→ 它答「合肥新桥国际机场」,然后【就没有了】
        #      ★ 它抽到了实体,但【没去干活】—— 那句话里没有"得分"这种动作词。
        #      ★★ "那…呢"这类指代句【会省略谓语】,而省略掉的正是动作。
        #        所以动作也得能继承,和参数一样。
        #
        #  【判据:不是"有没有动作词"】
        #      那要查词表,而 route.py 那张表【被砍过】(第 7 课删了"如何/哪些/怎么/几",
        #      因为它们会错)—— 它覆盖不了多少。
        #      ★ 改用:【模型这一轮选了干活类吗】——
        #        模型选不选,本身就是在读"这句话要什么"。
        #      ★★ 而它选不出来的时候,才是该继承的信号。
        #
        #  ⚠ 只在【有实体 或 借到了 或 在指代】时才继承 ——
        #     独立的一句("2025Q4 的样本量是多少")不该被上一轮的动作污染。
        from agent_tools import 干活类
        本轮干活 = [x for x in 选中 if x in 干活类]
        继承的动作 = []
        if 本轮干活:
            self.上一轮动作 = list(本轮干活)      # 它自己读出了动作 → 记下来给下一轮
        elif self.上一轮动作 and (有实体 or 借到了 or 本轮指代):
            继承的动作 = list(self.上一轮动作)
            说明.append("★ 这一轮没说做什么,沿用了上一轮的 "
                        + "、".join(f"「{x}」" for x in 继承的动作))

        return ((self.期次, 该用机场, 该用指标), 说明, None, 借到了, 继承的动作)

    def 清空(self):
        self.__init__()


