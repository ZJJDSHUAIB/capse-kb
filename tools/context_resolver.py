#  ══════════════════════════════════════════════════════════════════
#  ① 校验 —— 值在库里到底有没有
#
#  ★ 这是整个 P0-b 最要紧的一段。大模型的输出【一个都不能直接信】。
#  ⚠ 要检查到【组合】这一层:机场存在 ≠ 机场+期次这条记录存在。
#     实测:2023Q3 有 41 家机场,2025Q4 有 42 家 —— 不是每个机场每期都在。
# ══════════════════════════════════════════════════════════════════
def 校验(con, 机场=None, 期次=None, 指标=None):
    """补出来的东西,库里真的有吗?返回 (能不能用, 说明)。

    ★ 检查三层,而且【越往后越严】:
        ① 单个字段在不在
        ② 组合在不在(机场+期次)
        ③ 值本身合不合法
    """
    from route import load_airports, load_indicators

    if 机场:
        if 机场 not in set(load_airports(con).values()):
            return False, f"补出来的机场「{机场}」【不在库里】—— 不认"
    if 期次:
        ps = {r[0] for r in con.execute("SELECT DISTINCT 期次 FROM meta")}
        环 = [p for p in 期次 if p not in ps]
        if 环:
            return False, f"补出来的期次 {环} 【不在库里】(库里是 {sorted(ps)})—— 不认"
    if 指标:
        #  ★ 指标比机场宽松:综合得分/样本量这些【不在指标表里】但是合法的
        合法 = set(load_indicators(con)) | {"综合得分", "样本量", "机场数",
                                          "一级指标数", "二级指标数"}
        if 指标 not in 合法:
            #  ⚠ 措辞要准:第一版写的是"不在库里"——
            #    而实测「靠桥率」【在报告原文里出现过】,只是【没有进库】
            #    (第 2 课抽表时只收了 7 个一级指标)。
            #    ★ "不在库里"会让人以为"报告没提过它" —— 那是另一回事。
            return False, (f"补出来的指标「{指标}」【库里没有它的分数】"
                           f"(报告里可能提过,但它没进可查的指标表)—— 不认")

    #  ★★ 组合检查 —— 这一条最容易漏
    if 机场 and 期次:
        有 = [p for p in 期次
              if con.execute("SELECT 1 FROM 综合得分 WHERE 期次=? AND 机场=?",
                             (p, 机场)).fetchone()]
        if not 有:
            return False, (f"「{机场}」在库里,{期次} 也在库里 —— "
                           f"但【这两个凑一起没有记录】。不认。")
    return True, ""


#  ══════════════════════════════════════════════════════════════════
#  ② 提示词 —— 给什么,要什么
# ══════════════════════════════════════════════════════════════════
提示词 = """你在帮一个民航数据问答系统【解析指代】。你只做一件事:
把用户这一句话里省略或指代的东西,补成具体的值。

【上文】(最近的在最后)
{历史}

【系统现在记着的】
{记忆}

【★ 最近一轮建立了什么】(这是已知事实,不是让你猜的)
{最近}
{已知约束}
【用户这一句】
{当前}

要你判断的是:
  1. 这一句在指代上文吗?(有「那」「它」「这个」「上一期」「去年」这类说法)
  2. 它自己已经给了哪些值?(期次 / 机场 / 指标)
  3. 缺的那些,能不能从【最近一轮建立的】里补?补什么?

★★ 三条硬规矩:
  · 只在【最近一轮建立的】里面找。更早的提过的东西,【不要】拿来补 ——
    那多半是已经换掉的话题。
  · 补不了就老实说补不了,【不许编】一个看起来合理的值。
    编出来的值会被【代码查库】拦下,而你白编。
  · 「去年」「上一期」这类说法,参照点是【最近一轮的期次】,不是今天。

★★★ 第四条,而且最要紧:
  如果上面【已知约束】里说了"有歧义 / 对应好几个 / 不确定"——
  那你要输出 action=clarify,【不许替用户挑一个】。
  ★ 为什么:挑错了【查库查不出来】—— 那几个值都在库里,代码拦不住。
    所以"挑一个看起来合理的"在这里不是帮忙,是【制造一个看不出来的错】。

只输出 JSON,不要任何别的字:
{{"action": "fill 或 update 或 ignore 或 clarify",
  "期次": ["..."], "机场": "...", "指标": "...",
  "把握": "确定 或 默认推断 或 有歧义 或 没找到",
  "说明": "一句话说清你怎么补的;补不了就说为什么"}}

★ action 怎么选:
  fill    —— 从最近一轮补上了缺的部分
  update  —— 这一句自己给了新值,覆盖旧的
  ignore  —— 这一句和上文无关,不需要补
  clarify —— 【补不了】或者【不确定指向哪一个】—— 这时候宁可问,不要猜"""


def _历史文本(历史, n=6):
    """把对话历史压成几行。★ 只给最近 n 轮 —— 更早的没用,还容易误导。"""
    if not 历史:
        return "(这是第一句)"
    return "\n".join(f"  用户:{h['问']}" for h in 历史[-n:])


def _最近一轮(历史, 记忆):
    """★ 把"最近一轮建立了什么"写成【已知事实】递给模型 —— 这是张君杰定的那半。

    【为什么要单独给这一条】
      他说"不差那点 token",所以给了完整历史。
      ★ 但给全了历史会带来【误指】的风险:前面提过的机场,模型可能又拎出来。
      ★★ 所以把【最近一轮是什么】作为已知事实写清楚 ——
         不给它猜的机会。那也正是这个项目一路的做法:
         已知的东西代码递过去,不让模型推理。
    """
    if not 历史:
        return "  这是第一句,没有上文"
    行 = []
    上 = 历史[-1]
    if 上.get("结局") == "反问":
        行.append(f"  上一轮我问了用户一个问题,还没得到回答:{上['反问'][:60]}")
        return "\n".join(行)
    _, 机场, 指标 = 上.get("参数") or (None, None, None)
    期次 = (上.get("参数") or [None])[0]
    if 期次:
        行.append(f"  期次:{期次}")
    if 机场:
        行.append(f"  机场:{机场}")
    if 指标:
        行.append(f"  指标:{指标}")
    if not 行:
        行.append("  上一轮没有定下任何具体的东西")
    else:
        行.append("  ★ 这一句要补的,【只能从上面这几样里挑】")
    return "\n".join(行)


#  ══════════════════════════════════════════════════════════════════
#  ③ 解析 —— 问大模型,然后【过校验】
# ══════════════════════════════════════════════════════════════════
def 解析指代(con, q, 历史=None, 记忆=None, 最近=None, 已知约束=""):
    """问大模型要一个 Patch。返回 dict;失败时返回带 _走兜底 的 dict。

    ★ 返回 None 的两种情况,【调用方要能分清】:
        甲 大模型超时/连不上     → 走规则兜底
        乙 它给了值,但【校验不过】→ 也不能用,走规则兜底
      这里都返回 None,由调用方决定下一步 —— 因为"兜底"是调用方的事。

    ═══ ★★★ 2026-09-22 加 已知约束 ═══
        【为什么必须加 —— 实测抓到的】
            「那上海呢」:规则(find_airport)算得好好的,报「有歧义」——
              上海对应【两家】机场:浦东、虹桥,还写了句"是哪一家?"
            ★ 而我在调大模型时【没把这件事递过去】——
              于是它自己挑了一家(浦东)。
            ★★ 结果【看着对】(上文说的就是浦东),但它【对得没有依据】:
              挑虹桥的话,校验【一样通过】—— 因为两家都在库里。

        ★★★ 所以:规则知道的事,要递过去。这正是这个项目一路的做法 ——
             已知的东西代码递给模型,不让它推理。
            而这条约束的核心是:【有歧义时该 clarify,不该替用户挑】。
    """
    from llm import chat

    约束段 = ""
    if 已知约束:
        约束段 = ("\n【★ 规则已经报了这一条 —— 这是已知事实,不是让你猜的】\n"
                  f"  {已知约束}\n")

    prompt = 提示词.format(历史=_历史文本(历史),
                          记忆=json.dumps(记忆 or {}, ensure_ascii=False),
                          最近=最近 if 最近 is not None else _最近一轮(历史, 记忆),
                          已知约束=约束段,
                          当前=q)
    try:
        原始 = chat(prompt, max_tokens=300).strip()
    except Exception as e:
        return {"_失败": f"大模型没跑成:{type(e).__name__}", "_走兜底": True}

    #  ── 抠 JSON。★ 模型有时会把 JSON 包在 ``` 里,或者前后带一句话 ──
    m = re.search(r'\{.*\}', 原始, re.S)
    if not m:
        return {"_失败": f"它没给 JSON,给的是:{原始[:80]}", "_走兜底": True}
    try:
        p = json.loads(m.group(0))
    except Exception as e:
        return {"_失败": f"JSON 解析不了:{e}", "_走兜底": True}

    #  ── ★★★ 校验 —— 这一步【不能省】 ──
    期次 = p.get("期次") or []
    if isinstance(期次, str):
        期次 = [期次]
    好, 为什么 = 校验(con, 机场=p.get("机场") or None,
                      期次=期次 or None, 指标=p.get("指标") or None)
    if not 好:
        return {"_失败": 为什么, "_走兜底": True, "_模型原本想给": p}
    p["期次"] = 期次
    return p


