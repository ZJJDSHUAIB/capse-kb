r"""
第 17 课 P0-b · 让大模型做指代解析,但【它只出候选,代码说了算】。

═══ 为什么要这一层(张君杰问出来的)═══
    他原话:「别人的记忆都是靠这种代码来实现的吗?不靠大模型来理解吗?
             这种代码遇见一种新情况就要补一种吗?」

    ★ 他说的对。前面那三档规则是在【补语言现象】:
        指代词是什么 → 一条规则
        动作词是什么 → 又一条
      ★★ 而语言现象【补不完】—— 人说话的花样无穷。

    ★★★ 所以改成分工:
          大模型:理解 ——「那」指谁、这一句缺什么
          代码:  兜底 —— 它超时/输出不成格式,就走规则
          代码:  校验 —— 它补出来的值,库里到底有没有

═══ ★★★ 三层,顺序不能反 ═══
        ① 规则先判  —— 判得出就用规则(快、确定、不花钱)
        ② 判不出,才问大模型 —— 它擅长模糊的东西
        ③ 无论谁给的,【都过校验】 —— 值不在库里,当场不认

    ★ 第 ③ 层是这个项目的命根子:大模型会编,而编出来的东西
      格式正常、看着也对 —— 那正是"静默失败"。
    ★★ 所以校验不能是"看看像不像",必须是【库里查得到吗】。

═══ ⚠ 这个文件不做什么 ═══
    · 它不执行查询 —— 那是工具层的事
    · 它不改记忆 —— 改不改由智能体决定
    · 它不猜:校验不过就报"补不了",不编第二个
"""
