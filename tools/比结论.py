    ok = 0
    for 名, 行们, 要出现, *余 in 自检例:
        不许 = 余[0] if 余 else []
        出 = "\n".join(给结论(行们))
        缺 = [w for w in 要出现 if w not in 出]
        多 = [w for w in 不许 if w in 出]
        if 缺 or 多:
            print(f"  ❌ {名}\n     缺:{缺}  不该有:{多}\n     实得:{出!r}")
        else:
            print(f"  ✅ {名}")
            ok += 1
    #  ★ 额外一条:不许把排名题答反
    反 = 给结论([
        "2025Q4 深圳宝安国际机场:综合得分 4.27,排名第 2/42",
        "2025Q4 上海虹桥国际机场:综合得分 4.25,排名第 3/42",
    ])
    if any("上海虹桥国际机场 更靠前" in x for x in 反):
        print(f"  ❌ 排名答反了(它说虹桥更靠前):{反}")
    else:
        print("  ✅ 排名没答反(第2 比第3 靠前)")
        ok += 1
    #  ★ 额外一条:主量(综合得分)的结论【要排在排名之前】—— 见 给结论 里那段
    序 = 给结论([
        "2025Q4 上海浦东国际机场:综合得分 4.23,排名第 5/42",
        "2025Q4 北京大兴国际机场:综合得分 4.28,排名第 1/42",
    ])
    i得 = next((i for i, x in enumerate(序) if "更高" in x), None)
    i名 = next((i for i, x in enumerate(序) if "更靠前" in x), None)
    if i得 is None or i名 is None or i得 > i名:
        print(f"  ❌ 顺序不对 —— 综合得分该排在排名之前\n     实得:{序}")
    else:
        print("  ✅ 顺序对(综合得分的结论排在排名之前)")
        ok += 1
    print(f"\n  自检 {ok}/{len(自检例) + 2}")
