# -*- coding: utf-8 -*-
"""比结论 —— 【比】这个动作,一个函数,两条路共用。

═══ 为什么单独一个模块 ═══
    实测(tools/比一比.py,尺子修好之后):6 道比较题里【4 道没给结论】——
      · 计划路:两道全缺
      · 老路  :问「相差多少」那道给了;而问「拉开多少」「升了还是降了」
              两道【没给】—— 因为它的判据是【两个正则】,换个说法就不触发。

═══ 根因(两半,而它们是同一个病的两半) ═══
    老路  :判据挂在【问法】上
             `re.search(r'相差|差距|差多少|变化', q)` 和
             `re.search(r'哪[个家]|谁|高|低|好|差|并列', q)`
           ★ 换个说法 → 静默地不给了。而它【不出声】。
    计划路:动作【结构上到不了】
           老路一次调用拿到所有组合,所以 `len(vals) >= 2` 成立;
           ★ 而计划路每一步只查【一个】组合 —— 于是那个前提
             【永远为假】。这个动作在计划路上不是"没做好",是【到不了】。
    ★★ 合起来:「给比较结论」这个能力,被两个都不对的前提夹住了 ——
        一个要求"用户得那么问",一个要求"调用得那么调"。
      ★★★ 而它真正的前提只有一个:【这一轮取到了两个可比的同类值】。
          那是能算的(数个数),和问法怎么写、路怎么走【都无关】。

═══ 所以这一版改了两件事 ═══
    ① 判据:从【问法命中词表】换成【数的个数】。
       ⚠ 代价:不问比较的题(「两期分别是多少」)也会多出一行结论。
          ★ 认这个代价 —— 因为另一头是"用户问了比较而系统不说",
            而那条路【不出声】。多一行是看得见的,少一行是看不见的。
    ② 位置:从【工具层的一次调用里】挪到【答案组装那一层】——
       对【整轮取到的行】做一次。
       ★ 这样计划路把它拆成几次调用,也不影响结果。
    ③ ★ 两条路【调同一个函数】,不是各写一份。
       抄一份的话,今天修好明天就分叉 ——
       这个项目里「同一条规则只装一条路」已经出现过很多次。

═══ 它认什么 ═══
    认【事实行】(代码拼的那些行),不认模型写的话。
    目前只认主格式:
        `{期次} {机场}:{量名} {值},排名第 {名}/{总数}`
    ★ 一行里能拆出两个量(综合得分 + 排名)——
      因为那两样【本来就写在同一行里】。
    ⚠ 不认的行【静默跳过】,但 抽() 会把跳过的条数报出来 ——
      免得"没认出来"和"没有可比的东西"混成一个空结果。
       ★ 那正是这个项目一路在防的:两种不同的空,不能长得一样。
    ⚠ 逐项/档位那几种行【现在不认】(格式不同,而且"跨期逐项比"是另一件事)。
      这一版【不说它支持】。
"""
import re
import sys

#  ══════════════════════════════════════════════════════════════════
#  量的说法 —— ★ 这是【量的属性】,不是问法的属性
#
#  ⚠⚠ 为什么必须有"方向"这一栏:
#     「排名第 2」和「排名第 5」,数字大的那个【更差】——
#     而「综合得分 4.28」和「4.23」,数字大的那个【更好】。
#     ★ 如果不管方向、一律"谁大谁赢",排名题会答反,而且【答得像对的】。
#  ★ 而没写在这里的量 → 方向=None → 【只报大小,不报好坏】:
#     "A 比 B 大" 是算出来的;"A 比 B 好" 需要知道那个量的方向。
#     不知道方向就不说好不好 —— 那是"判不出就不判",不是"猜一个"。
#  ══════════════════════════════════════════════════════════════════
量的说法 = {
    "综合得分": {"好": "更高", "坏": "更低", "差词": "高",
                 "跨期好": "涨", "跨期坏": "降", "方向": +1},
    "得分": {"好": "更高", "坏": "更低", "差词": "高",
             "跨期好": "涨", "跨期坏": "降", "方向": +1},
    #  ★ 排名【越小越好】—— 这一栏就是为它写的
    "排名": {"好": "更靠前", "坏": "更靠后", "差词": "领先",
             "跨期好": "升", "跨期坏": "降", "方向": -1, "名次": True},
}

#  ══════════════════════════════════════════════════════════════════
#  ★★★ 2026-10-01:为什么【排名】也要自动比 —— 张君杰下的判断,理由我改写过
#  ══════════════════════════════════════════════════════════════════
#  【他的判断(原话)】
#      「我觉得他不是(噪音) 而且对答案是一种作证的话就算帮助」
#  ★ 结论【对】:那一行要留。而这个判断只有他能下 —— 那是价值判断,不是技术判断。
#
#  【★ 而他给的理由,我把它改了 —— 因为查了之后发现站不住】
#      他说的是"作证"(两条路指向同一个结论 = 交叉验证)。
#      ★ 而查了 综合得分排名 那行视图:
#            ROW_NUMBER() OVER (PARTITION BY 期次 ORDER BY 得分 DESC) AS 排名
#        → ★★ 排名是【从得分算出来的】。它们一致是【构造保证的】,
#          一致本身不携带信息 —— 那不是两个证人,是同一个证人的两种说法。
#      ⚠ 所以别把这一对当交叉验证用:它永远不会不一致,因而【不能报警】。
#        「作证」这个想法是对的,而它要用在【真的互相独立】的一对上
#        (PDF 里的数 vs 库里的数 / 同一指标 vs 报告里那句同比)。
#
#  【★★ 那它为什么还是要留 —— 三条更硬的】
#      ① 它是【能算的】——"能算的地方,程序就算出来"是这一路的脊梁。
#      ② 它多带了【总数】:「第5名」和「第5/42名」信息量不一样,得分里没这个。
#      ③ ★★ 而在【得分并列】的时候,它是【唯一】给出答案的那一行 —— 实测:
#             #15「2024Q4 南京禄口和青岛胶东谁综合得分高」
#                得分都是 4.18 → ★ 得分说"一样",等于没回答"谁高"
#                名次第7 vs 第8 → ★ 只有这一行说了他俩不一样
#         ★ 而第③条顺带照出一件事:并列时那个 1 和 2 是 ROW_NUMBER 随手编的。
#           所以那两道题上,【得分说"持平"、名次说"第7 vs 第8"——两句都对,
#           而它们说的是不同的事】。那一行不是复述,是补充了"并列是按什么排的"。
#  ⚠ 这条判断在【代码里】而不是只在台账里 —— 因为将来改这个文件的人
#    看到"排名为什么自动比"时,该看到的是【这个理由】,不是"我试出来的"。
#  ══════════════════════════════════════════════════════════════════

#  ══════════════════════════════════════════════════════════════════
#  事实行 → (期次, 机场, 量名, 数值)
#  ⚠ 正则【只在行首匹配】—— 于是它认不出自己产出的结论行(那些以 `  →` 开头)。
#    这个性质是【必须有】的:否则重跑一次会把结论当成新事实,越滚越多。
#  ══════════════════════════════════════════════════════════════════
主行 = re.compile(
    r'^\s*(\d{4}Q\d)\s+(\S+?):\s*([^\s:]+)\s+(-?\d+(?:\.\d+)?)'
    r'(?:\s*,\s*排名第\s*(\d+)\s*/\s*(\d+))?'
    #  ══ ★★★ 2026-10-01:名次后面那个【并列说明】也要能容忍 ══
    #  【为什么】ask.py 那行事实现在末尾多了「(与XX同分,两家并列)」——
    #    而这条正则原来以 `$` 收尾 → ★ 加了括号它就【匹配不上】,
    #    于是 比结论 会【静默地不再给结论】:答案照常出来,只是少了那一行。
    #  ★★ 这正是这一路反复栽的那个:改了【生产者】没改【消费者】。
    #     → 所以这次先把解析它的地方全找了一遍(4 处:ask / 比结论 / 名次影响面 / planner),
    #       逐个确认哪几处会被打破 —— 破的只有这一条和生产者。
    #  ⚠ `[^)]*` 不认嵌套括号 —— 够用(那句话里不会有括号),如实记着。
    r'(?:\s*\([^)]*\))?\s*$')

#  ★ 排名那一栏从【同一行】里再拆一个量出来 —— 它是 主行 里的一个捕获组,
#    ⚠ 不另立一个正则:同一个格式写两遍,迟早不一致(而这里不一致就是静默的)。

#  ══════════════════════════════════════════════════════════════════
#  ★★★ 2026-10-01:哪些行算"是数据的行" —— 而这里【正面认】,不列排除表
#  ══════════════════════════════════════════════════════════════════
#  【怎么发现的 —— 实测题 53 / 62,而它是纯拼错】
#      两条答案各多出一句「⚠ 有 1 行我没认出来是什么量」。
#      那一行是 `★ 你没点名要哪个指标,我按【综合得分】答。`
#      ★ 我写的排除表是 `startswith("*")` —— ASCII 星号;
#        而它是 `★`,U+2605。★ 一个字符之差,那张表就【不生效】。
#  【★★ 而就算拼对了,排除法本身也是错的】
#      这个世界上的"不是数据的行"是【列不完的】——说明、警告、岔路口、
#      结论、偏好提示……今天多一种,明天多一种,那张表永远差一条。
#      而"是数据的行"是【有形状的】。
#  ★★★ 所以【正面认】:一行以【期次】开头 → 它一定是数据。
#      认出来了 → 抽值;认出来了而我不认识它这种格式 → 报"没认出";
#      ★ 压根不是数据的行 → 【静默跳过】,不报 —— 因为它本来就不该被认。
#  ⚠ 报"没认出"的意义是【有一行可能是数据而我没读】。
#    把说明行算进去,那个数就虚高,而虚高的警告等于没有警告。
_像事实行 = re.compile(r'^\s*\d{4}Q\d\b')


def 抽(行们):
    """从一堆事实行里抽 (期次, 机场, 量名, 数值)。

    ★ 返回 (值们, 没认出来的条数) —— 两种"空"要能分开:
        认出来了但只有一个对象  → 没得比
        有数据行我没认出来      → 这把我【不认识这种行】
    """
    值们, 没认出 = [], 0
    for 行 in (行们 or []):
        文 = str(行).strip()
        if not 文:
            continue
        m = 主行.match(文)
        if m:
            期, 场, 量, 值, 名, 总 = m.groups()
            值们.append((期, 场, 量, float(值)))
            #  ★ 排名:同一行里再拆一个量。见文件头 —— 它俩本来就同一行。
            if 名:
                值们.append((期, 场, "排名", float(名)))
            continue
        #  ★ 认不出:只在【它一看就是数据】时才算 —— 见上面那段
        if _像事实行.match(文):
            没认出 += 1
    return 值们, 没认出


def _数(v):
    """★ 数字怎么打 —— 统一一个写法,免得 4.20 和 4.2 看着像两个数。"""
    return f"{v:g}"


def _差(a, b):
    return round(abs(a - b), 2)


def 比一组(组, 说, 分表=None):
    """组 = [(期次, 机场, 数值), ...],同一个量名。→ 一行结论,或 None。

    ★ 三条路分开走,判据都是【能算的】:
        两边期次不同、机场相同 → 跨期比
        两边机场不同、期次相同 → 跨机场比
        两个都不同             → 泛化措辞(不硬套"跨期"或"跨机场")
    ⚠ `分表` = {(期次,机场): 综合得分} —— ★ 只有"名次"那一组要用它,
      见下面"名次并列"那段。别的量传 None 就行。
    """
    对象 = sorted({(p, a) for p, a, _ in 组})
    if len(对象) < 2:
        return None                      # ★ 只有一个对象 = 自己跟自己比,不叫比
    方向 = (说 or {}).get("方向")
    #  ══════════════════════════════════════════════════════════════════
    #  ⚠⚠⚠ 2026-10-01:名次那一套【必须在这里算】,不能挪到底下分支里去
    #  ══════════════════════════════════════════════════════════════════
    #  【怎么发现的】下面那个「持平」分支【提前 return】,
    #     而"名次"这三个东西我原来写在【跨期分支里面】(在它后面)——
    #     ★ 于是排名持平的那种题,输出的是一句【光秃秃的数字】:
    #         实测:「→ 两期持平(都是 1)」—— 那是"第1名"被念成了一个 1。
    #     ★★ 而"两期持平(都是 1)"和"两期持平(都是 4.23)"【长得一模一样】,
    #        读者分不出哪个是名次、哪个是得分。
    #  ★★★ 根因还是那个:同一个打印规则【按分支分了几份】,
    #     而有一条分支【在它前面就 return 了】→ 它永远走不到。
    #     → 修法:算一次,所有分支共用。
    #
    #  ⚠ 而【自检为什么没抓到】:自检里有「跨期·持平」,但那是【得分】的持平
    #     (名次那一栏本来就该是空的);★ 缺的正是【排名也持平】那一格。
    #     → 已补上一条(见 自检例)。
    名次 = (说 or {}).get("名次")

    def _形(v):
        return f"第{_数(v)}名" if 名次 else _数(v)

    单位 = "名" if 名次 else ""
    #  ★ 名次句【标出"名次:"】—— 它和得分写在同一行数据里,是附带那条。
    #    ⚠ 不标的话读者会以为主语是得分:题 10 / 28 上试出来的。
    前缀 = "  → 名次:" if 名次 else "  → "

    if 方向 == -1:
        好 = min(组, key=lambda x: x[2])       # 排名:小的赢
        差 = max(组, key=lambda x: x[2])
    else:
        好 = max(组, key=lambda x: x[2])       # 默认按"大的"排,下面再判方向
        差 = min(组, key=lambda x: x[2])

    if abs(好[2] - 差[2]) < 1e-9:
        #  ═══ ★ 持平 —— 而它能算出来,所以【不许说成谁赢】 ═══
        #  ⚠ 为什么单独一档:「没有差」是最容易被"编一个差出来"的地方,
        #    而编出来的差【格式正常、看着合理】。
        同一场 = len({a for _, a, _ in 组}) == 1
        return (f"{前缀}{'两期' if 同一场 else '几家'}持平"
                f"(都是 {_形(好[2])})")

    跨期 = len({p for p, _, _ in 组}) > 1 and len({a for _, a, _ in 组}) == 1
    d = _差(好[2], 差[2])
    if 跨期:
        #  ★ 跨期用"涨/降" —— 用户问「是升了还是降了」时,
        #    "哪个期次更高"那句话【答不到】他问的那件事。
        早期 = sorted({p for p, _, _ in 组})[0]
        #  ⚠ 这里只能按【期次先后】说涨跌,不能按"大/小"——
        #    否则排名题会把"第2名"说成"涨了"。
        早值 = [x for x in 组 if x[0] == 早期]
        晚值 = [x for x in 组 if x[0] != 早期]
        if not 早值 or not 晚值:
            return None
        甲 = 早值[0][2]
        乙 = 晚值[-1][2]
        期晚 = 晚值[-1][0]
        if abs(甲 - 乙) < 1e-9:
            return f"{前缀}两期持平(都是 {_形(甲)})"
        #  ▲ 谁变好,由【方向】定;没方向就只报大小
        if 方向 is None:
            return (f"{前缀}从 {早期} 的 {_形(甲)} 到 {期晚} 的 {_形(乙)},"
                    f"相差 {_数(d)}")
        #  ══════════════════════════════════════════════════════════════
        #  ★★★★★ 2026-10-01:跨期【一句话里两件事都说】
        #  ══════════════════════════════════════════════════════════════
        #  【为什么 —— 实测题 10,而它是我改坏的】
        #      问「2024Q1和2024Q4的北京大兴国际机场【哪个】综合得分高」
        #        老代码:→ 2024Q4 北京大兴国际机场 更高(4.24 vs 4.22)
        #        我第一版:→ 从 2024Q1 的 4.22 到 2024Q4 的 4.24,涨了 0.02
        #      ★ 信息没丢(读者能推出来 Q4 高)——
        #        而【他问的是"哪个高",答的是"涨了多少"】。那叫答非所问。
        #  【★ 而"用户问的是哪个"这件事,判据【又会变成词表】】
        #      哪个高 / 涨跌 —— 两个方向,得挑一个说。
        #      ★★ 而那就是老代码的病根(判据挂在问法上),修它不能又用问法。
        #  ★★★ 所以不判:一句话里【两件都说】——
        #         {晚期} {谁} {更高/更低}(v晚 vs v早),比 {早期} {涨/降}了 d
        #      ★ 它对两种问法都答到了,而且【一个判据都不需要】。
        谁 = 晚值[-1][1]
        好的是晚的 = ((乙 > 甲) == (方向 > 0))
        词_谁 = 说["好"] if 好的是晚的 else 说["坏"]
        词_变 = 说["跨期好"] if 好的是晚的 else 说["跨期坏"]
        return (f"{前缀}{期晚} {谁} {词_谁}({_形(乙)} vs {_形(甲)}),"
                f"比 {早期} {词_变}了 {_数(d)}{单位}")
    #  ── 跨机场(或维度不同的泛化) ──
    def _名(p, a):
        """★ 两个维度都变的时候,名字里【必须带期次】。

        ⚠⚠ 2026-10-01 修 —— 实测题 70,而它是我写漏的:
            「比较北京大兴和上海浦东2025Q3和2025Q4的综合得分变化」
            第一版给的是「北京大兴国际机场 更高(4.3 vs 4.23),高 0.07」——
            ★ 那句话【没说是哪一期】。而数据里有【两期】。
            ★★ 根因:带期次的那个名字(_名)第一版【只用在了"没方向"那条分支】,
               后两条分支直接用了 `好[1]`(光秃秃一个机场名)。
               ★★★ 又一次"只在一条路上做对了"。
        """
        return f"{p} {a}" if len({x[0] for x in 组}) > 1 else a
    #  ⚠⚠ 变量名【不能叫 _差】—— 上面那个算差的函数就叫 _差。
    #     第一版我写成 `_差 = _名(...)`,于是整个函数里 _差 变成局部变量,
    #     而上面 `d = _差(好[2], 差[2])` 那句 → UnboundLocalError。
    #     ★ 又一个「同一个名字装两个东西」—— 而这次它【吼出来了】,
    #       不是静默的。自检一跑就撞上。
    _好名 = _名(好[0], 好[1])
    _差名 = _名(差[0], 差[1])
    if 方向 is None:
        #  ★ 不知道这个量越大越好还是越小越好 → 【只说大小,不说好坏】
        return f"  → {_好名} {_数(好[2])} > {_差名} {_数(差[2])},相差 {d}"
    if (说 or {}).get("名次"):
        #  ══════════════════════════════════════════════════════════════
        #  ★★★★ 2026-10-01:得分一样的时候,【不许说谁更靠前】
        #  ══════════════════════════════════════════════════════════════
        #  【怎么发现的 —— 实测题19】
        #      「2024Q1北京大兴和深圳宝安【并列第几】」, 期望:并列第1/41
        #      两家都是 4.22,而序号是 1 和 2(ROW_NUMBER 随手编的)。
        #      ★ 于是这一行说:「名次:北京大兴国际机场 更靠前(第1 vs 第2)」——
        #        而上一行刚说过「几家持平(都是 4.22)」。
        #      ★★ 两行自相矛盾,而【矛盾是那一行造成的】:两家分数一样,
        #          "更靠前"是拿那个编出来的序号说的。
        #  【★★ 而判据是【能算的】:两家的综合得分是不是同一个数。】
        #      而那个数【就在同一行事实里】——不用另查库,分表() 已经抽出来了。
        #  ★★★ 这也顺带说明:能算的东西一旦抽出来,就【别再用旁边那个不能算的】。
        分 = (分表 or {}).get((好[0], 好[1]))
        与 = (分表 or {}).get((差[0], 差[1]))
        if 分 is not None and 与 is not None and abs(分 - 与) < 1e-9:
            return (f"  → 名次:{_好名} 和 {_差名} 并列"
                    f"(综合得分都是 {_数(分)},两个名次是排列顺序,不分先后)")
        #  ★ 排名说"名次",不说 4.28 那种小数。第2 vs 第3。
        return f"  → 名次:{_好名} {说['好']}(第{_数(好[2])} vs 第{_数(差[2])})"
    return (f"  → {_好名} {说['好']}({_数(好[2])} vs {_数(差[2])}),"
            f"{说['差词']} {d}")


def 给结论(行们, 要说=量的说法):
    """★ 主入口 —— 给【这一轮所有的事实行】,回一串结论行。

    ⚠ 两条路都调这一个函数。见文件头 ③。
    """
    值们, 没认出 = 抽(行们)
    按量 = {}
    for 期, 场, 量, 值 in 值们:
        按量.setdefault(量, []).append((期, 场, 值))
    #  ★★★ 分表 —— 给"名次"那一组用的:两家的综合得分是不是同一个数。
    #  ⚠ 从【已经抽出来的值】里捡,不另查库 —— 那个数本来就在同一行事实里,
    #    再查一遍库 = 同一件事两个来源,迟早不一致。
    #  ⚠⚠ 它【必须定义在下面那个循环之前】—— 第一版我插到了循环后面,
    #     于是循环里读它 → UnboundLocalError。★ 同一个坑这个项目踩过好几次
    #     (见 ask.py 里"facts 必须在函数级初始化"那段):一个变量在下面被读,
    #     而它【只在某几条分支里被赋值】。
    分表 = {}
    for 期, 场, 量, 值 in 值们:
        if 量 in ("综合得分", "得分"):
            分表[(期, 场)] = 值
    出 = []
    #  ═══ ★★★ 2026-10-01:顺序 —— 主量排前面 ═══
    #  【怎么发现的】跑出来是这样:
    #      问「浦东和北京大兴谁综合得分高」,答案是
    #        → 北京大兴国际机场 更靠前(第1 vs 第5)      ← ★ 排名的结论【排前面了】
    #        → 北京大兴国际机场 更高(4.28 vs 4.23),高 0.05
    #    ★ 两行都对,而【顺序把答案埋了】:用户看第一行以为答的是排名。
    #  【★ 而"哪个是主量"不用新判据】
    #      `量的说法` 那个表【本身就是按主次写的】——
    #      综合得分是头号量(整个库围着它转),排名是它的附庸(写在同一行里)。
    #      ★★ dict 在 Python 里【保持插入顺序】,所以那张表的顺序就是优先级,
    #         不用另立一个表(另立一个 = 同一个判断写两遍,迟早不一致)。
    #  ⚠ 表里没有的量 → 排在最后,按名字。
    _序 = {n: i for i, n in enumerate(要说)}
    for 量 in sorted(按量, key=lambda n: (_序.get(n, len(_序)), n)):
        组 = 按量[量]
        对象 = {(p, a) for p, a, _ in 组}
        if len(对象) < 2:
            continue
        行 = 比一组(组, 要说.get(量), 分表)
        if 行:
            出.append(行)
    #  ══════════════════════════════════════════════════════════════════
    #  ⚠⚠ 2026-10-01:这道警告【只在"这一轮确实在比"的时候】才报
    #  ══════════════════════════════════════════════════════════════════
    #  【怎么发现的 —— 实测题 65/66/67,跑完全量才露出来】
    #      「浦东2025Q4排第几，前三名是谁」这种题,答案里有一行
    #        `2025Q4 前 5 名:第1名 …;第2名 …`  ← 期次开头、而格式是另一种
    #      ★ 于是它被算进"没认出",答案里就多出一句
    #        「⚠ 有 1 行【是数据】而我不认识它这种格式,所以没拿来比」。
    #      ★★ 而这一轮【只有一个对象】(只查了浦东)—— 本来就没得比。
    #         那句话会让读者以为【漏了什么】,而其实一行都没漏。
    #  【判据】认出来的数据里【有没有 ≥2 个对象】:
    #      有 → 这一轮在比,而那行没读进来【可能真的漏了】→ 要说
    #      没有 → 没得比,那句话是噪音
    #  ⚠ 而这不是放宽:真的"该比而没认出来"的情形,对象数一定 ≥2 ——
    #     要比,至少得有两个东西。
    _有得比 = any(len({(p, a) for p, a, _ in g}) >= 2 for g in 按量.values())
    if 没认出 and _有得比:
        #  ★ 不认识的行【说出来】—— 否则"我不认识这种行"会被读成"没有可比的东西"
        出.append(f"  ⚠ 有 {没认出} 行【是数据】而我不认识它这种格式,"
                  f"所以没拿来比 —— 不是我比过了说没差。")
    return 出


