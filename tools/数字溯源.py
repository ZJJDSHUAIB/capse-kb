# -*- coding: utf-8 -*-
r"""
数字溯源 —— 一句话里的数字,是从【事实】来的,还是模型自己造的?

═══ 它是干什么的 ═══
    方案是「事实层 → 模板 + 占位符 → LLM 组织语言 → 回填」。
    而回填之后要回答一个问题:

        ★ 这句话里的数字,每一个都能追回事实吗?

    它能追回 → 说明模型没编。
    追不回   → ⚠ 可能是它编的,也可能是「语言里的数字」。

═══════════════════════════════════════════════════════════════
  ⚠⚠⚠ 而这里有一条【实测踩出来的界线】—— 别把"摆出来"写成"一律拒"
═══════════════════════════════════════════════════════════════
    【先例:报告那条路的"硬查",假报了【三轮】】
        第1轮  把 '09' 从 '2025Q4-P09' 里切出来   → 报"数据里没有 09"
        第2轮  把 '1'  从加粗编号 '**1.**' 里切出来 → 报"数据里没有 1"
        第3轮  把「第 1 名」里的 1 当成数据          → 报"数据里没有 1"
      ★ 三轮都是【假阳性】—— 而假阳性的代价是:
        一个本来对的回答被判"有问题" → 重新生成 → 白花钱,甚至永远过不了。

    【所以这把尺子分成两档,不是一个数】
        ★ 硬判（能算,错了就是错了）:
            ① 占位符有没有全部回填
            ② 定性词有没有被换掉
        ⚠ 摆出来（不判,由人看）:
            ③ 表外数字 —— ★ 它【既可能是模型编的,也可能是语言里的数字】
               「前10名」「第1名」「2025Q4」都会被扫进来。

    ★★★ 一句话:【能算的硬判,不能算的摆出来】——
        那正是这个项目一路的做法(见 README「关键设计决策」)。

═══ 怎么用 ═══
    python tools/数字溯源.py --自检          # 拿几个造好的例子撞它自己
    from 数字溯源 import 查
    硬判, 表外 = 查(答案文本, 事实)
"""
import re
import sys
import io
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))


#  ══════════════════════════════════════════════════════════════════
#  占位符的写法
#     ★ 用「{{N1}}」这种双花括号 —— 因为它【不会和自然文本撞】。
#       ⚠ 而单花括号 {N1} 在 f-string 里还要转义,容易写错。
#  ══════════════════════════════════════════════════════════════════
#  ═══ ★★★★★ 2026-09-30:占位符【用真键名】(「{机场}」「{名次}」),不编号 ═══
#  【这一天里为它踩了三个坑,记下来别重走】
#
#      第1版  取名() = f"{k.upper()}"           ★ 中文键 upper() 还是中文,
#             而正则是 [A-Za-z_]... → 【匹配不到】→ 尺子一直在空转
#
#      第2版  改成 N1/N2 按位置编号              ★ 名字和含义脱钩
#             → 模板里写「在 {N4} 家机场中排第 {N5} 位」,
#               而事实 dict 的顺序一变,就填成了
#               「在 5 家机场中排第 42 位」—— ★★ 名次和总数填反了
#
#      第3版（现在）★ 直接用【事实的键】当占位符名
#             · 名如其义 —— 顺序怎么变都不会错
#             · 正则放宽成 \{([^{}]+)\} 就能收中文
#             · ⚠ 而模型照抄中文占位符没问题(它就在骨架里,原样可见)
#
#  ★★ 教训:「占位符名要不要表意」这件事,
#      只有到【模板和事实的顺序不一致】时才会暴露 ——
#      而那时错误是【静默的】:填上了、格式对、数字全是真数,就是配错了。
占位 = re.compile(r'\{([^{}]+)\}')   # ★ 名字里可以有中文


def 取名(事实):
    """★ 事实 dict【原样】当映射表 —— 键就是占位符名。

    ★ 数字和定性词【一起】放进来 ——
      因为"略高/小幅回落"这种词也会被模型改,而它们也该被钉死。
    ★★ 为什么不编号:见上面那段"踩了三个坑"。
      名如其义,顺序怎么变都不会填错。
    """
    return dict(事实)


def 填(模板, 表):
    """把 {{名}} 换成真值 —— ★ 这一步是【代码做的】,模型碰不到。"""
    return 占位.sub(lambda m: str(表.get(m.group(1), m.group(0))), 模板)


#  ══════════════════════════════════════════════════════════════════
#  ① 硬判 —— 这两条错了就是错了
#  ══════════════════════════════════════════════════════════════════
def 查占位符(模型输出, 表):
    """★ 在【回填之前】查 —— 占位符是不是原样回来的。

    ═══ ⚠⚠⚠ 2026-09-30:这两个检查必须【分开】,而且顺序不能反 ═══
        【怎么发现的 —— 自检抓到的】
            第一版只有 查() 一个函数,它内部是【先填、再查】:
                填后 = 填(模型输出, 表)
                硬, 表外 = 查(填后, ...)
            ★ 于是"有没有没填上的占位符"这一条【永远查不到】——
              因为查之前已经被填光了。
            ★★ 自检里那个"模型漏填一个占位符"的例子当场没被抓出来。
            ★★★ 而如果没写自检,这把尺子会【永远说"没问题"】。
        【修法:拆成两个函数,顺序写在名字里】
            查占位符(模型输出)   ← 回填【之前】
            查回填后(答案)       ← 回填【之后】
    """
    if 表 is None:
        表 = {}
     #  ═══ ⚠⚠⚠ 2026-09-30 修:判据【写反了】 ═══
    #  【症状】
    #      模型原样输出了 7 个占位符,而校验报:
    #        「⚠ 还有 7 个占位符没被填上」
    #  ★ 根因:第一版的判据是【"有没有占位符"】——
    #    而【模型原样保留占位符,正是我们要的】!
    #    占位符的存在【不是错】——它是模型在照抄骨架。
    #  ★★ 正确的判据只有一条:
    #      占位符里的名字,是不是【都是表里认识的】。
    #      不认识的 = 模型自己造了一个,或者改错了名 → 那才是错。
    硬 = []
    用到 = 占位.findall(str(模型输出))
    没见过的 = sorted({x for x in 用到 if x not in 表})
    if 没见过的:
        硬.append(f"⚠ 出现了【不认识】的占位符:{没见过的}"
                  f" —— 模型自己造了一个,或者改错了名")
    #  ⚠ 而【没用到】某个占位符不算错 ——
    #    挑哪些事实值得说是模型的判断(见文件头三层图),那是它的活。
    return 硬


def 查回填后(答案, 表, 模板=None):
    """★ 在【回填之后】查 —— 定性词在不在、有没有表外数字。

    返回 (硬判的问题清单, 表外数字清单)。
    ★ 硬判那栏【空了才算过】;表外数字那栏【只是给人看的】——
      它非空【不代表出错】,见文件开头那段。
    """
    硬 = []

    #  ① 定性词有没有被换掉
    #     ★ 这一条是【这一步最容易被漏掉的】——
    #       占位符全对,而模型把「小幅回落」说成「大幅下降」,那句就是假的。
    for 名, 值 in 表.items():
        #  只有【定性词】(非数字)才查 —— 数字由占位符保证,不用在这儿再查一遍
        if isinstance(值, (int, float)):
            continue
        if 值 and str(值) not in str(答案):
            硬.append(f"⚠ 定性词「{值}」({名})在答案里【没出现】"
                      f" —— 要么被换了说法,要么被删了")

    #  ③ 表外数字 —— ⚠ 只列,不判
    该有 = {str(v) for v in 表.values() if isinstance(v, (int, float))}
    #  ★ 定性词里也可能嵌着数字(比如"前 11.9%"),一并算进来
    for v in 表.values():
        if isinstance(v, str):
            该有 |= set(re.findall(r'\d+(?:\.\d+)?', v))
    #  ★ 模板里本来就有的字面数字(比如问句里的期次)也算"该有"
    if 模板:
        该有 |= set(re.findall(r'\d+(?:\.\d+)?', str(模板)))

    看到 = re.findall(r'\d+(?:\.\d+)?', str(答案))
    表外 = [x for x in 看到 if x not in 该有]

    return 硬, 表外


def 查(模型输出, 表, 模板=None):
    """★ 给外面用的【一步到位】版 —— 内部按正确顺序调那两个。

    ⚠ 别在外面自己拼顺序 —— 这个 bug 就是因为顺序错了才有的。
    """
    硬 = 查占位符(模型输出, 表)
    填后 = 填(模型输出, 表)
    硬2, 表外 = 查回填后(填后, 表, 模板 if 模板 is not None else 模型输出)
    return 硬 + 硬2, 表外


#  ══════════════════════════════════════════════════════════════════
#  自检 —— ★ 拿造好的例子撞它自己,看它会不会【该抓的抓、不该抓的不抓】
#
#  ⚠ 为什么要有自检:报告硬查那三轮假阳性,都是【没自检】的结果。
#    而被测物只有一套,尺子要"想清楚被测物该干什么"—— 那一层最容易错。
#  ══════════════════════════════════════════════════════════════════
例子 = [
    #  (名字, 事实, 模型输出, 该不该硬判出问题)
    ("全对", {"机场": "上海浦东国际机场", "期次": "2025Q4", "得分": 4.23,
              "名次": 5, "总数": 42, "与同档": "略高", "与上期": "小幅回落"},
     "上海浦东国际机场在 2025Q4 的综合得分是 4.23,在 42 家机场中排第 5。"
     "与同档平均相比略高,与上期相比小幅回落。", 0),

    #  ⚠⚠ 2026-09-30:这个例子【跟着判据一起改了】。
    #     原来是「模型漏填一个占位符」→ 期望判错。
    #     ★ 而判据改成"只有【不认识】的占位符才算错"之后,
    #       "原样保留占位符"正是我们要的 → 那个期望【就过期了】。
    #     ★★ 换成一个真错的:模型【自己造】了一个占位符。
    #     教训:改判据的时候,【例子要一起看】—— 否则自检会一直红着,而原因在例子上。
    ("★★ 模型自己造了一个不认识的占位符",
     {"得分": 4.23, "名次": 5},
     "综合得分是 4.23,排第 {名次X}。", 1),

    ("★ 模型原样保留了占位符 —— 那是【对的】,不该判错",
     {"得分": 4.23, "名次": 5},
     "综合得分是 4.23,排第 {名次}。", 0),

    ("★★ 数字全对,而定性词被换掉了",
     {"得分": 4.23, "与上期": "小幅回落"},
     "综合得分是 4.23,较上期大幅下降。", 1),

    ("⚠ 语言里的数字(前10名) —— ★ 不该硬判出错",
     {"得分": 4.23, "名次": 5, "总数": 42},
     "综合得分是 4.23,在 42 家机场中排第 5,进入了前 10 名。", 0),
]


def 自检():
    print("=" * 74)
    print("  数字溯源 · 自检")
    print("=" * 74)
    过 = 0
    for 名, 事实, 模型输出, 该 in 例子:
        表 = 取名(事实)
        硬, 表外 = 查(模型输出, 表, 模型输出)
        对 = (len(硬) == 该)
        过 += 对
        print(f"\n  {'✅' if 对 else '❌'} {名}")
        print(f"      模型写的是:{模型输出[:70]}")
        print(f"      硬判:{硬 if 硬 else '（没问题）'}")
        if 表外:
            print(f"      ⚠ 表外数字(只是列出来,不代表错):{表外}")
        if not 对:
            print(f"      ★ 该判出 {该} 个问题,实际判出 {len(硬)} 个")
    print(f"\n{'=' * 74}")
    print(f"  {过}/{len(例子)} 个对")
    print("=" * 74)
    return 过 == len(例子)


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--自检", action="store_true")
    a = ap.parse_args()
    sys.exit(0 if 自检() else 1)
