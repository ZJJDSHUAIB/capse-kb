r"""
「带条件 / 多步」那类问法的尺子 —— 第 21 课。

═══ 为什么要有这一把（它是量出来的缺口）═══
    ★ 用户 2026-09-23 说「肯定会啊，以后出报告也要用得上」——
      而拿现有 79 道题（60 题评估集 + 19 题 Agent 评估）扫条件词:
      ★★ 【0 道】。所以他们说的"收益 0"有一半是假的 ——
         收益确实 0，但那是【因为尺子照不到那儿】，不是因为它没价值。
      ★★★ 这正是那一课一路在讲的:「量具只覆盖它覆盖的地方」。

═══ 五道题，四种形状 + 一道反向 ═══
    ① 字面条件     如果…就…            该走【它走到的那一支】
    ② 隐晦条件     "不好就…"           该先判"好不好"，再决定要不要展开
    ③ 要先算才知道指谁 「低的那家」      该先比出来，才知道代词指谁
    ④ ★ 反向       问一个数             【不该】走任何分支
    ⑤ 半道         两步,不是分支        两件都必然要答

    ★★ 第 ④ 道是这个判据【另一个方向】:没有它，一个"什么都当条件处理"的
       实现也能把前三道蒙对。

═══ 报三态，不是一个总分 ═══
    ✅ 答对      ★ 静默（该答的没答，而答案里不说）
    ⚠ 该答而反问（方向相反的错）    · 看着对，其实是碰巧

=== 怎么用 ===
    python tools/条件题测试.py
"""
import sys, io, sqlite3
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from paths import DB

#  ★ 每题:(标号, 问句, 该答出来的关键片段们, 说明)
#    ⚠ 关键片段是【人定的】—— 见 docs/评估集_带条件.md,那份是 AI 起草、待用户审。
题目 = [
    ("① 字面条件",
     "分析浦东近两期，如果降了就查原因，没降就看看它和同档平均水平比怎么样",
     ["平均"], "该只说它走到的那一支（库里两期都是 4.23 → 没降 → 走「比同档」）"),

    ("② 隐晦条件",
     "浦东2025Q4表现怎么样，要是不好就说说是哪一项拖后腿",
     #  ⚠⚠ 2026-09-23 修:原来是 ["拖后腿","出港服务","机场商贸"] ——
     #     ★ 而"哪一项拖后腿"这一件【系统确实答不了】(那个条件本来就含糊,
     #       planner 判不了 → 停)。★ 所以要求它给出"出港服务/机场商贸"
     #       等于要求一件它【做不到】的事。
     #     ★★ 而这一课真正的靶子是【判不出看得见】:
     #        它答不了,就该【说出来】—— 那才是这一格该判的。
     #     ★★★ 改法:判【它有没有说"这一件我没答"】,而不是判它答没答出来。
     ["这一件我没答", "综合得分 4.23"],
     "★ 该先判「好不好」;判不了就要【说出来】—— 而不是静默"),

    ("③ 要先算才知道指谁",
     "浦东和虹桥2025Q4谁高，低的那家差在哪",
     #  ⚠⚠ 2026-09-23 修:原来是 ["虹桥", "低"] —— 而"低"这个字【报告里没出现】
     #     (它说的是"判成【成立】那一支"),于是【答对的】被判"缺" → 判"静默"。
     #     ★ 改法:判【那两件事做没做】——
     #       "上海虹桥国际机场"在 → 比出来了;  "它跟同档"在 → 逐项表给了。
     ["上海虹桥国际机场", "它跟同档"], "该先比出谁高，再说低的那家差在哪"),

    ("④ ★ 反向:不该走分支",
     "浦东2025Q4综合得分是多少",
     ["4.23"], "★ 一个数 + 出处就够了，不该展开"),

    ("⑤ 两步,不是分支",
     "浦东2025Q4排第几，前三名是谁",
     #  ⚠⚠ 2026-09-23 修:原来是 ["第 5", "大兴"] —— 而系统答里写的是
     #     「第5名」(【没有空格】) → `"第 5" in 文` 为 False → 判"缺" → 判"静默"。
     #     ★ 症状:一道【完全答对】的题被判成"最要命的那种错"。
     #     ★★ 而根因是【判据写得太字面】:一个空格就错了。
     #     ★★★ 改法:用【能算的】判 —— "它自己的名次"和"前三名名单"在不在,
     #          而不是抠一个写死的字符串。
     #           「第5名 上海浦东国际机场」在 → 那两件事就都答了。
     ["第5名 上海浦东国际机场", "第1名 北京大兴国际机场"], "两件都必然要答"),
]


def 答了啥(r):
    """★ 把这一轮【工具的输出】+【说明】拼起来。

    ⚠⚠ 2026-09-23 修:第一版只拼了【工具的值】——
      于是"我漏了哪件没答"那句话(它在【说明】里)【看不到】,
      一道【已经说出了自己没答什么】的题,被判成"静默(最要命的那种)"。
      ★ 而"说出来了"和"没说"是【两回事】—— 那正是今天修了一整天的东西:
         「判不出看得见」。★ 尺子如果看不见它说的话,就等于没修。
    """
    片 = []
    for _, v in (r.get("结果") or {}).items():
        vv = v.get("值")
        if not vv:
            continue
        for x in (vv if isinstance(vv, list) else [vv]):
            片.append(str(x))
    片 += [str(x) for x in (r.get("说明") or [])]      # ★ 说明也要看
    return "\n".join(片)


def main():
    con = sqlite3.connect(DB)
    from agent import 智能体

    print("=" * 82)
    print("  「带条件 / 多步」那类问法的尺子 —— 主链现在表现如何")
    print("  ★ 五道题来自 docs/评估集_带条件.md（AI 起草、待用户审）")
    print("=" * 82)

    计 = {"✅ 答对": 0, "★ 静默": 0, "⚠ 该答而反问": 0, "❌ 答错": 0, "🔇 答不出": 0}
    for 标, q, 该有, 说明 in 题目:
        a = 智能体(sqlite3.connect(DB))
        try:
            r = a.问(q)
        except Exception as e:
            print(f"\n{标}\n  问:{q}\n  ⚠ 抛了:{type(e).__name__}: {str(e)[:90]}")
            计["❌ 答错"] += 1
            continue
        结 = r.get("结局")
        if 结 == "反问":
            判 = "⚠ 该答而反问"
            注 = f"它反问:{str(r.get('反问'))[:90]}"
        elif 结 == "答不出":
            判 = "🔇 答不出"
            注 = "★ 出声了 —— 至少用户能看见它没答上"
        else:
            文 = 答了啥(r)
            欠 = [k for k in 该有 if k not in 文]
            if not 欠:
                判 = "✅ 答对"
                注 = ""
            elif 结 == "答" and 文:
                #  ★ 答了,而该有的片段缺了 —— 而答案里【没说自己缺了什么】→ 静默
                判 = "★ 静默"
                注 = f"缺:{欠}"
            else:
                判 = "❌ 答错"
                注 = f"缺:{欠}"
        计[判] += 1
        print(f"\n{标}")
        print(f"  问:{q}")
        print(f"  ★ {判}   （结局={结}）")
        print(f"     该有:{说明}")
        if 注:
            print(f"     {注}")
        if 结 == "答":
            短 = 答了啥(r)[:150].replace("\n", " / ")
            print(f"     答了:{短}")

    print("\n" + "=" * 82)
    for k, v in 计.items():
        if v:
            print(f"  {k:<14} {v}/5")
    print("=" * 82)
    print("""
  ★ 这几个数【不能合并成一个总分】—— 代价不一样:
     ✅ 答对     —— 好
     ★ 静默      —— 该答的没答，而答案里【不说】← 最要命的那种
     ⚠ 该答而反问 —— 方向相反的错:把能答的推回给用户 —— ★ 用户会觉得系统笨
     🔇 答不出   —— 出声了，看得见（难看，但不骗人）

  ★★ 这份尺子的【条件】:那五道是 AI 写的、期望也是 AI 写的 ——
     还没经用户审。★ 所以它现在的数是"倾向"，不是"定论"。""")


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    main()
