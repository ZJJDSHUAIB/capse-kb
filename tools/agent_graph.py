# -*- coding: utf-8 -*-
r"""
用【状态图】跑同一个 Agent —— 和 agent.py 里的版本并存,互相做对照。

═══ 为什么并存,而不是替换 ═══
    ★ 这个项目一路的做法:换一个做法,就【留一个旧的当对照】——
      「每轮结果另存带轮次名」「旧牌子留着做对照」都是这个。
    ★★ 而"换形状"这件事尤其需要对照:它【不该改变行为】,
       而"不该变"要【跑出来才算数】,不能靠我说。

═══ 它和 agent.py 的关系 ═══
        智能体.问()          手写的 if,一串代码
        图智能体.问()        ★ 同一批逻辑,放进节点和边里
    ★ 节点函数【复用】智能体的那些方法 —— 不是抄一遍。
    ★★ 所以两边跑出来应该【逐字一样】。不一样就是搬错了。

═══ 这个文件想让"形状"变得看得见 ═══
    看 agent.py 的 问():你只看到一段很长的函数。
    看这个文件的 _建图():★ 你能看到有【几个步骤】、每个步骤【什么条件下】去哪。
    ★★ 而 LangGraph 做的就是这件事 —— 只不过它还管持久化、并行、中断。
"""
import sys, io
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from graph import 图
from agent_tools import 干活类


class 图智能体:
    """和 智能体 同一批逻辑,但用图跑。★ state 就是那一串本来要手传的东西。"""

    def __init__(self, con, 让模型选=True):
        from agent import 智能体
        self._内 = 智能体(con, 让模型选)      # ★ 复用它 —— 不抄逻辑
        self.con = con
        self.图 = self._建图()

    #  ══════════════════════════════════════════════════════════════
    #  节点:每一个都是 `state -> 要更新的那部分`
    #  ★ 里面调的是 智能体 的既有逻辑,【一行都没改】
    #  ══════════════════════════════════════════════════════════════

    def _起(self, s):
        from agent_tools import run_tools
        #  ★ 参照在这一步取一次 —— 为什么,见 agent.py:58 那段
        参照 = self._内.会话.期次 or None
        结果, 选中 = run_tools(self.con, s["问"], 让模型选=self._内.让模型选,
                                参照期次=参照)
        return {"参照": 参照, "结果": 结果, "选中": 选中}

    def _记忆(self, s):
        (期次, 机场, 指标), 说明, 反问, 补过, 继承的动作 = \
            self._内.会话.用(s["问"], s["结果"], s["选中"])
        return {"期次": 期次, "机场": 机场, "指标": 指标, "说明": 说明,
                "反问": 反问, "补过": 补过, "继承的动作": 继承的动作}

    def _大模型(self, s):
        """规则判不出 → 【才】问大模型。★ 见 agent.py:94 那段的理由。"""
        from context_resolver import 解析指代
        patch = 解析指代(self.con, s["问"], self._内.历史,
                         {"期次": self._内.会话.期次, "机场": self._内.会话.机场,
                          "指标": self._内.会话.指标},
                         已知约束=s["反问"])
        期次, 机场, 指标, 补过, 说明 = s["期次"], s["机场"], s["指标"], s["补过"], s["说明"]
        if patch and not patch.get("_走兜底"):
            补期次 = patch.get("期次") or []
            补机场 = patch.get("机场") or None
            补指标 = patch.get("指标") or None
            if patch.get("action") in ("fill", "update") and (补期次 or 补机场 or 补指标):
                期次, 机场, 指标 = 补期次 or 期次, 补机场 or 机场, 补指标 or 指标
                补过 = True
                说明 = list(说明) + [
                    f"★ 规则判不出,问了大模型 —— 它说:{patch.get('说明', '')[:80]}",
                    f"★ 补出来的值【过了代码校验】(机场/期次/指标 都在库里)"]
        return {"大模型补的": patch, "期次": 期次, "机场": 机场, "指标": 指标,
                "补过": 补过, "说明": 说明}

    def _补做(self, s):
        from agent_tools import run_tools
        补做过 = False
        if s.get("继承的动作"):
            补做, _ = run_tools(self.con, s["问"], 让模型选=False,
                                覆盖参数=(s["期次"], s["机场"], s["指标"]),
                                参照期次=s["参照"],
                                只要这些=s["继承的动作"])
            结果 = {**s["结果"], **补做}
            return {"结果": 结果, "补做过": True}
        return {"补做过": 补做过}

    def _重做(self, s):
        from agent_tools import run_tools
        if s["补过"] and not s.get("补做过") and any(名 in s["选中"] for 名 in 干活类):
            结果, 选中 = run_tools(self.con, s["问"], 让模型选=self._内.让模型选,
                                    覆盖参数=(s["期次"], s["机场"], s["指标"]),
                                    参照期次=s["参照"])
            说明 = list(s["说明"]) + ["★ 记忆补了参数,所以【干活那一步重做了一遍】"]
            return {"结果": 结果, "选中": 选中, "说明": 说明, "重做过": True}
        return {"重做过": False}

    def _筛(self, s):
        """查原文取回来的原文 → 交给生成层【筛出用户要的那句】。"""
        结果 = dict(s["结果"])
        if "查原文" in 结果 and 结果["查原文"]["值"]:
            try:
                from ask import gen_answer
                hs = [h for h in 结果["查原文"]["值"]
                      if h.get("文本") and h.get("期次") and h.get("页码")]
                if hs:
                    说成人话 = gen_answer(s["问"], hs)
                    结果["查原文"] = dict(结果["查原文"], 值=[说成人话])
                    结果["查原文"]["怎么定的"] += ";★ 交给了生成层,筛出回答了问题的部分"
                    return {"结果": 结果,
                            "说明": list(s["说明"]) + [
                                "★ 检索取回的是原文,已交给生成层筛出答案那一段"],
                            "大模型补的": None}
            except Exception as e:
                结果["查原文"] = dict(结果["查原文"])
                结果["查原文"]["怎么定的"] += (
                    f";⚠ 生成层没跑成({type(e).__name__}),所以下面是原文未筛")
        return {"结果": 结果}

    def _完(self, s):
        """收尾:反问 vs 答 —— 和 agent.py 里那两处 return 一一对应。"""
        if s.get("反问") and s.get("大模型补的") is None:
            return {"结局": "反问", "反问": s["反问"]}
        if s.get("反问") and not s["补过"]:
            原因 = (s["大模型补的"].get("说明") or s["大模型补的"].get("_失败")
                    or "补不出来") if isinstance(s.get("大模型补的"), dict) else "补不出来"
            return {"结局": "反问",
                    "反问": s["反问"] + f"\n      (★ 我还问了一次大模型,它也说:{str(原因)[:60]})"}
        return {"结局": "答"}

    #  ══════════════════════════════════════════════════════════════
    #  图:看这一段,就能看出【有几步、什么条件下走哪条】
    #  ★ 而 agent.py 里那段代码【同一个东西,但看不出来】—— 那正是换形状的意义
    #  ══════════════════════════════════════════════════════════════
    def _建图(self):
        g = 图("起")
        g.加节点("起", self._起)
        g.加节点("记忆", self._记忆)
        g.加节点("大模型", self._大模型)
        g.加节点("补做", self._补做)
        g.加节点("重做", self._重做)
        g.加节点("筛", self._筛)
        g.加节点("完", self._完)

        g.加边("起", lambda s: "记忆")
        #  ★ 条件边一:规则判不出(要反问)→ 去问大模型;否则直接走补做
        g.加边("记忆", lambda s: "大模型" if s["反问"] else "补做")
        #  ★ 条件边二:大模型也没补出来(或它说 clarify)→ 直接收尾(那是反问)
        g.加边("大模型", lambda s: "补做" if s["补过"] else "完")
        g.加边("补做", lambda s: "重做")
        g.加边("重做", lambda s: "筛")
        g.加边("筛", lambda s: "完")
        g.加边("完", lambda s: None)
        return g

    def 问(self, q):
        """跑一遍图,返回和 智能体.问() 同形状的记录。"""
        s = self.图.跑({"问": q})
        if s["结局"] == "反问":
            记录 = {"问": q, "结局": "反问", "反问": s["反问"]}
        else:
            记录 = {"问": q, "结局": "答", "选中": s["选中"], "结果": s["结果"],
                    "参数": (s["期次"], s["机场"], s["指标"]),
                    "说明": s["说明"], "重做过": s.get("重做过", False)}
        self._内.历史.append(记录)
        return 记录


# ══════════════════════════════════════════════════════════════════
#  对照自检:两个版本跑【同一段对话】,逐字比
#  ★ 这才是"换形状没改行为"的证据 —— 不是我说没改,是跑出来一样
# ══════════════════════════════════════════════════════════════════
对话 = [
    "2025Q3 上海浦东国际机场综合得分是多少",
    "那合肥新桥呢",
    "那 2024Q2 的得分呢",
    "2025Q4 的样本量是多少",
    "那上海呢",
    "2025Q4 报告里,测评指标为什么调整过",
]


def main():
    import sqlite3, json
    from paths import DB
    from agent import 智能体
    from agent_graph import 图智能体

    con = sqlite3.connect(DB)
    甲 = 智能体(con)          # 手写 if 那版
    乙 = 图智能体(con)        # 图那版

    print("=" * 78)
    print("  对照:手写 if  vs  状态图 —— 同一段对话,逐字比")
    print("=" * 78)
    同 = 0
    for i, q in enumerate(对话, 1):
        a = 甲.问(q)
        b = 乙.问(q)
        #  ★ 比什么:结局 / 反问 / 参数 / 选中 / 说明 / 重做过
        #  ⚠⚠ 而【反问那一栏要先剁掉大模型写的那半】——
        #     实测踩到:两个版本的反问里,那句括号注释是大模型生成的,
        #       甲说「上海浦东、上海虹桥两家机场」,乙说「上海浦东国际机场和上海虹桥国际机场两家」
        #       —— 语义一样,措辞不同。★ 而我差点把它报成"搬错了"。
        #     ★★ 根因:【拿一个会抽样的东西当判据】—— 那正是这个项目一路在治的。
        #     所以:反问只比【第一行】(规则写的那句),括号那句不比。
        def 剁(a):
            if a is None:
                return None
            return str(a).split("\n")[0]
        甲值 = {"结局": a["结局"], "反问": 剁(a.get("反问")), "参数": a.get("参数"),
                "选中": a.get("选中"), "说明": a.get("说明"), "重做过": a.get("重做过")}
        乙值 = {"结局": b["结局"], "反问": 剁(b.get("反问")), "参数": b.get("参数"),
                "选中": b.get("选中"), "说明": b.get("说明"), "重做过": b.get("重做过")}
        差 = {k: (甲值[k], 乙值[k]) for k in 甲值 if 甲值[k] != 乙值[k]}
        对 = not 差
        同 += 对
        print(f"\n  {'✅' if 对 else '❌'} [{i}] {q}")
        print(f"       甲(手写):{a['结局']}  参数={a.get('参数')}  重做={a.get('重做过')}")
        print(f"       乙(图)  :{b['结局']}  参数={b.get('参数')}  重做={b.get('重做过')}")
        if 差:
            for k, (x, y) in 差.items():
                print(f"       ⚠ 【{k}】不一样:\n          甲={x}\n          乙={y}")
        #  图走了哪些节点 —— ★ 那正是这一课想让人看见的东西
        print(f"       图走的节点:{乙.图.轨迹}")

    print("\n" + "=" * 78)
    print(f"  {同}/{len(对话)} 句结构完全一样")
    print("=" * 78)
    print("""
  ★ 一样 = "换形状没改行为"的证据。
  ★★ 不一样 = 搬错了 —— 而那【正是要用对照抓的东西】。

  ⚠ 比的是【结构】(结局/参数/选中/说明),不是生成的文本 ——
    后者每次都不同(第 11 课量过:生成是抽样的)。

  ★★★ 而底下那行「图走的节点」是这一课真正的产出:
      以前要看懂流程得读一段很长的函数,现在看那一行就知道它走了哪条路。""")


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    main()
