# -*- coding: utf-8 -*-
r"""
第 8 课 · 报告的第 5 节:结论与建议 —— **让大模型下结论,但每条都得挂上依据。**

═══ 为什么这一节的写法和其他四节不一样 ═══
    前四节是【把查到的数据说成话】,第 5 节是【从数据里得出新判断】。

    新判断【天然不是"有据"的】—— 它是推出来的,不是查出来的。
    所以硬查那套(每个数在不在数据里)对它【不适用】——
    它可能一个数都不提,但结论是错的。

    → 所以换一个把关方式:**每一条结论,必须指出它依据的是前四节的哪一条。**

═══ 这一节把报告里的话分成两类 ═══
    【事实】  前四节的数(有出处,硬查保证)
    【推断】  第 5 节的结论(必须挂依据;挂不上的,如实标"纯推断")

    ★ 中间没有第三种。**报告里每一句话都能被归到这两类里。**
      这就是"可核验的报告"和"漂亮文档"的分界线。

═══ ⚠ 这道把关比硬查弱,必须说清 ═══
    它只能检查"【有没有】挂依据",检查不了"【挂的依据对不对】"。
    挂了一个不相关的依据,它照样通过。
    **它把"完全没查"变成"查了一道" —— 和 verify() 那句原话一样。**
"""
import sys, io, re, json, sqlite3
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

DB = Path(r"D:\capse-kb\data\processed\capse.db")

PROMPT = """你在给一份机场满意度报告写【第 5 节:结论与建议】。

前面四节的数据(JSON)在下面。你要根据它写:
1. **最终应该关注什么**
2. **下一步建议是什么**

★ 硬规则(必须遵守):
1. 你写的每一条结论,**后面必须用括号写上它依据的是哪个数**,格式:(依据:机场商贸 3.74 比同档低 0.02)
2. **不许出现数据里没有的数字。**
3. **不许把推断说成事实。** 如果一条结论是从数据【推】出来的、不是数据直接写着,
   在句末加「(推断)」两个字。
4. 数据里没有的东西(比如"因为天气""因为施工"),**一律不许写** —— 你不知道。
5. 如果数据不足以支撑某一类结论,**就明说"数据不足,无法判断"**,不要硬凑。

数据(JSON):
{data}

直接输出第 5 节的正文。"""


# ══ ★ 我撤掉了什么,为什么 ══════════════════════════════════
#  原来这里有个 split_claims():把第 5 节切成一句句,查每条【有没有写"依据:"】。
#
#  **它没用,而且错在根上。** 实测:
#      · "## 第 5 节:结论与建议"       被当成一条陈述(那是标题)
#      · "最该盯的是机场商贸——它是全部指标中的最低分"
#        这句话【本身就是依据】,只是没写"依据:"两个字
#      · 我在用「有没有某两个汉字」把守一段【自由的话】—— 那注定不准
#
#  ★ 而且就算它准了,方向也是错的:
#    **强制每条写"依据:…",会让"结论"退化成"填表"。**
#    第 5 节之所以值钱,恰恰因为它是在【说话】。框死了就没有结论了。
#
#  ★ 正确的做法不是【逐句查】,是【整节声明】:
#      前四节  → 事实(有据,硬查保证)
#      第 5 节  → 推断(整节标注,不混进事实)
#    **用户读到第 5 节,知道那是"系统的判断",不是"数据说的"。**
#    这才是"报告里每一句话都能分类"的落地 —— 分的是【节】,不是【句】。
#
#  ⚠ 所以这一节只有一道硬查(数字有没有据),外加一个声明。
#    **诚实说:这道把关比前四节弱。** 但强行加硬判据会更糟。



def main():
    from report_data import build
    from report_gen import collect_numbers, NUM
    from llm import chat

    con = sqlite3.connect(DB)
    d = build(con)
    print("=" * 78)
    print(f"  {d['机场']} {d['期次']} · 第 5 节:结论与建议")
    print("=" * 78)

    brief = json.dumps(d, ensure_ascii=False, default=str)
    try:
        sec5 = chat(PROMPT.format(data=brief), max_tokens=900)
    except Exception as e:
        print(f"  ★ 大模型没跑成:{type(e).__name__}: {e}")
        return

    print("\n──── 第 5 节 ────")
    print(sec5)

    print("\n" + "=" * 78)
    print("  ★ 两道把关")
    print("=" * 78)

    # ① 数字还是要有据(和前面四节同一道)
    #    ⚠ 先把【编号】剔掉再抽数:实测 "**1.**" "2." 这类会被当成数字,
    #      假报一堆"找不到"。**编号是排版,不是数据。** —— 这一课第五次同类了。
    body = re.sub(r'\*\*\d+[.、]\*\*|^\s*\d+[.、]\s', ' ', sec5, flags=re.M)
    allowed = collect_numbers(d)
    bad = {m.group(0) for m in NUM.finditer(body)
           if round(float(m.group(0)), 2) not in allowed and int(float(m.group(0))) not in allowed}
    if not bad:
        print("  ① 数字:✅ 全部有据(编号已剔除后再比的)")
    else:
        print(f"  ① 数字:★ 这些在数据里找不到:{sorted(bad)}")


    n_infer = sec5.count('推断')
    n_short = sec5.count('数据不足') + sec5.count('无法判断')
    print("\n  ② 它有没有把推断说成事实?")
    print(f"       它自己标了「推断」{n_infer} 处")
    print(f"       它自己说了「数据不足 / 无法判断」{n_short} 处")
    print("""
  ★ 这一节的把关方式【和前四节不一样】,必须说清:
      前四节  → 事实。硬查得住:每个数字在不在数据里。
      第 5 节  → 推断。**整节声明,不混进事实。**

  ⚠ 我试过"逐句查有没有挂依据",撤了 —— 见代码里那段注释。
     用「有没有某两个汉字」把守一段自由的话,注定不准;
     而且强制格式会让"结论"退化成"填表"。
  ⚠ 所以这道把关比前四节弱。**诚实的说法:前四节可核,第 5 节只能标。**""")



if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    main()
