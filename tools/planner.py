r"""
先出计划,再审,最后【摊给人看】—— 而【先不执行】。

═══ 为什么要单独这一步(而不是直接让它做) ═══
    ★ 实测那一个"带条件的任务":

        「分析浦东近两期,如果降了就查原因,没降就比同档」
        → 它把"如果…就…"当成了【两个并列的查询】,
          于是查表 + 查原文都调了,而【条件那一层没走】。

    ★★ 根因:现在系统接的是【一句话】,走的是一张【固定的图】——
       而那个任务要的是"先做一步 → 看结果 → 再决定走哪条"。
    ★★★ 业界管这个叫 Plan-and-Execute:
         先出计划 → ★ 有一个【审查点】 → 再执行。
         而那个"审查点"正好是这个项目一路在做的:不能静默执行。

═══ 所以最小的一版【只做前半】═══
    ① 让模型出计划(JSON)
    ② 代码审:工具名认不认识、参数在不在库里
    ③ ★ 把计划摊出来给人看 —— 而【先不执行】

    ★ 为什么最小的是这个:它【不碰现在那条能跑的链】,
      而它能回答【最要紧的那个问题】:"模型出的计划,靠不靠谱?"
    ★★ 而那正是该先量的 —— 量完了再决定要不要真的照它执行。

═══ ⚠ 这一版【不做什么】 ═══
    · 不执行 —— 只出计划、审、摊开。
    · 不接进主链 —— 它是个独立的东西,现有六套自检两套尺子都不动。
    · 不做 reflection —— 那要等计划跑起来才有意义。

═══ 怎么用 ═══
    python tools/planner.py                       # 跑内置的几句
    python tools/planner.py "分析浦东近两期,降了查原因,没降比同档"
"""
