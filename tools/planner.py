#  ① 提示词 —— 给什么,要什么
#
#  ★ 关键:【已知的东西递过去】(这个项目一路的做法)。
#    工具名从 TOOLS 拿、取值从库里拿 —— 那样它不会编。
#    ★★ 而"不许编"要写清,因为编了【代码会拦】(见 审计划),它白编。
# ══════════════════════════════════════════════════════════════════
def _工具清单():
    """★ 从 agent_tools.TOOLS 拿 —— 单一真相源,不另抄一份。

    ⚠ 只给【干活类】(要模型选的那些)。抽参数那四个【总是跑】,
      它们不该出现在计划里 —— 计划该说的是"做什么",不是"抽什么"。
    """
    from agent_tools import TOOLS
    行 = []
    for t in TOOLS:
        if not t.get("要模型选"):
            continue
        行.append(f"  · {t['名字']}:{t['什么时候用']}")
    return "\n".join(行)


def _取值清单(con):
    """库里的期次 / 机场 / 指标 —— ★ 只给这些,不许它编别的。"""
    from route import load_airports, load_indicators
    期次 = [r[0] for r in con.execute("SELECT DISTINCT 期次 FROM meta ORDER BY 期次")]
    机场 = sorted(set(load_airports(con).values()))
    指标 = sorted(set(load_indicators(con)) | {"综合得分"})
    return 期次, 机场, 指标


提示词 = """你在把用户的一句话拆成【几步】—— 只拆,不做。

【能用的工具】(只能用这些,名字【一模一样】地写)
{工具}

【能用的取值】(只能用这些 —— 下面的清单里没有的,【不许写】)
  期次:{期次}
  机场:{机场}
  指标:{指标}

【用户这一句】
{问}

═══ 输出一段 JSON,没别的话 ═══
{{
 "任务": "一句话说清用户要什么",
 "步骤": [
   {{"编号": 1, "工具": "查表", "参数": {{"期次": ["..."], "机场": "...", "指标": "..."}},
     "要得到什么": "一句话 —— 这一步做完该拿到什么"}},
   {{"编号": 2, "看第几步": 1, "条件": "一句话说清判什么",
     "真": {{"工具": "查原文", "_问": "拿去搜的那句话", "参数": {{...}}, "为什么": "..."}},
     "假": {{"工具": "查表",   "参数": {{...}}, "为什么": "..."}}}}
 ]
}}

★★ 三条硬规矩:
  · 如果用户只是问【一个数或一件事】,那就【只有一步】—— 别硬拆成多步。
  · 条件必须是【能拿数字比出来的】("末期 < 前期"),不要写"如果看起来不好"。
  · 补不了就老实说补不了,【不许编】工具名或参数值 ——
    编出来的会被【代码查库】拦下,而你白编。

★ 而用「查原文」时【必须】多写一个 "_问":
   它是【拿去原文里搜的那句话】——因为查原文是"拿话去搜",不是"拿参数去查"。
   ⚠ 不写它,那一步就没法执行。"""


def 出计划(con, q, max_tokens=700):
    """让模型出一份计划。返回 dict,或带 _失败 的 dict(调用方看着办)。"""
    from llm import chat
    期次, 机场, 指标 = _取值清单(con)
    prompt = 提示词.format(工具=_工具清单(), 期次=期次, 机场=机场, 指标=指标, 问=q)
    try:
        原始 = chat(prompt, max_tokens=max_tokens).strip()
    except Exception as e:
        return {"_失败": f"大模型没跑成:{type(e).__name__}: {e}"}
    m = re.search(r'\{.*\}', 原始, re.S)
    if not m:
        return {"_失败": f"它没给 JSON,给的是:{原始[:120]}"}
    try:
        return json.loads(m.group(0))
    except Exception as e:
        return {"_失败": f"JSON 解析不了:{e}", "_原文": 原始[:200]}


#  ══════════════════════════════════════════════════════════════════
#  ② 代码审 —— 而这是这一版【最要紧的一段】
#
#  ★ 为什么不能让模型自己保证:它编的成本为零,而编出来的东西
#    【格式正常、看着合理】—— 那正是这个项目一路在打的静默失败。
#  ★★ 所以:工具名要在清单里、参数值要在库里、条件要指向前面某一步。
#     三样都是【能查的】,不用理解。
# ══════════════════════════════════════════════════════════════════
def 审计划(con, 计划):
    """返回 (通过了没, [每一条为什么])。★ 不通过【要说清哪一条】。"""
    from agent_tools import TOOLS
    from route import load_airports, load_indicators

    if "_失败" in 计划:
        return False, [计划["_失败"]]

    已知工具 = {t["名字"] for t in TOOLS if t.get("要模型选")}
    有期次 = {r[0] for r in con.execute("SELECT DISTINCT 期次 FROM meta")}
    有机场 = set(load_airports(con).values())
    有指标 = set(load_indicators(con)) | {"综合得分"}

    错 = []
    步骤 = 计划.get("步骤") or []
    if not 步骤:
        return False, ["计划里一步都没有"]

    def 审一步(s, 标):
        if s.get("工具") not in 已知工具:
            错.append(f"{标}:工具「{s.get('工具')}」不在清单里 —— 那是编的")
        p = s.get("参数") or {}
        #  ═══ ★★★ 2026-09-23 加:【它说要做的事】和【它给的工具参数】对不对得上 ═══
        #  【为什么 —— 实测抓到的,而这一条【原来查不出来】】
        #     计划第 2 步"假"那一支写着:
        #        为什么: 「…需先获取【同档平均】数据」
        #        参数:   {期次:['2025Q4'], 机场:浦东, 指标:【综合得分】}
        #     ★★ 它【说】要比同档平均,而它【调】的是综合得分 —— 对不上。
        #        执行出来确实【没有同档平均】(计划里说了要比,答案里没有)。
        #     ★★★ 而上面那三条(工具名/期次/机场/指标 在不在库里)【全都通过】——
        #         那三条查的是"有没有编",查不了"要做的事对不对"。
        #         ★ 这正是项目里那句:【校验拦得住"编的",拦不住"选错的"】。
        #
        #  ⚠ 判据是【临时的】:靠"平均"这个词 ——
        #    和 ask.py 那个 平均词 一样,换个说法就认不出。
        #    ★ 长久之计是过一遍量名层(见 docs/量名表.md)——
        #      但那要调大模型,而这一步现在要快。先通路,标记着。
        _说 = " ".join(str(s.get(k) or "") for k in ("要得到什么", "为什么"))
        _指 = p.get("指标")
        if _说 and _指 and re.search(r'平均|均值', _说) and _指 != "行业平均":
            错.append(
                f"{标}:【意图和参数对不上】—— 它说「{_说[:34]}」，"
                f"而参数里的指标是「{_指}」。★ 话里要的是「平均」，"
                f"参数里给的是别的量 —— 这一步做出来不会是它说的事。")
        #  ═══ ★★★ 2026-09-23 加:【先校验形状,再校验值】 ═══
        #  【为什么 —— 实测崩了,而崩的方式说明一个更大的洞】
        #      问「浦东2025Q4表现怎么样，要是不好就说说是哪一项拖后腿」,
        #      模型把 `指标` 写成了【一个列表】——
        #      而这里 `指 not in 有指标` 是【集合查找】→
        #         TypeError: unhashable type: 'list' → ★ 整个审计划【崩了】。
        #
        #    ★★ 而这一段的立意是「代码审:工具名认不认识、参数在不在库里」——
        #       它查的是【有没有编】,而【没查"形状对不对"】。
        #       形状不对时它不是"拦下并说清",是【直接崩】。
        #       ★ 而崩了之后:要么整个流程挂了,要么被上层兜住变成静默 ——
        #         两种都比"说清形状不对"差。
        #
        #    ★★★ 所以先判形状 —— 而这【不是多此一举】:
        #       大模型给的东西【形状也不保证】,而"保证形状"是代码的责任。
        def _形状(值, 该是, 标2, 名):
            if 值 is None:
                return True
            if 该是 == list:
                if not isinstance(值, list):
                    错.append(f"{标2}:{名}该是一个列表,它给的是 "
                             f"{type(值).__name__} —— ★ 形状不对，不是「库里没有」")
                    return False
                return True
            if not isinstance(值, str):
                错.append(f"{标2}:{名}该是一个字符串,它给的是 "
                         f"{type(值).__name__} —— ★ 形状不对，不是「库里没有」")
                return False
            return True

        if _形状(p.get("期次"), list, 标, "期次"):
            for 期 in (p.get("期次") or []):
                if not isinstance(期, str):
                    错.append(f"{标}:期次里有一项不是字符串:{期!r}")
                elif 期 not in 有期次:
                    错.append(f"{标}:期次「{期}」库里没有")
        场 = p.get("机场")
        if _形状(场, str, 标, "机场") and 场 and 场 not in 有机场:
            错.append(f"{标}:机场「{场}」库里没有")
        指 = p.get("指标")
        if _形状(指, str, 标, "指标") and 指 and 指 not in 有指标:
            错.append(f"{标}:指标「{指}」库里没有")

    for i, s in enumerate(步骤, 1):
        if "条件" in s:
            看 = s.get("看第几步")
            if not isinstance(看, int) or not (1 <= 看 < i):
                错.append(f"第{i}步:条件看的是第 {看} 步 —— 那【不是前面某一步】")
            for 支 in ("真", "假"):
                if not isinstance(s.get(支), dict):
                    错.append(f"第{i}步:{支} 那一支没写")
                else:
                    审一步(s[支], f"第{i}步·{支}")
        else:
            审一步(s, f"第{i}步")

    #  ★ 每个"看第几步"都要【真的指向前面的步骤】—— 不然那条件无从判起
    return (not 错), 错


#  ══════════════════════════════════════════════════════════════════
#  ③ 摊开 —— 给人看的一段话
#  ★ 而那是 Plan-and-Execute 那个【审查点】的人话版本:
#    它要自己做几步决定,所以【必须先说清它打算做什么】。
# ══════════════════════════════════════════════════════════════════
def 摊开(计划, 错=None):
    行 = []
    if "_失败" in 计划:
        return f"⚠ 出不了计划:{计划['_失败']}"
    行.append(f"  任务:{计划.get('任务', '?')}")
    for s in (计划.get("步骤") or []):
        if "条件" in s:
            行.append(f"  {s.get('编号')}. 【看第 {s.get('看第几步')} 步的结果】"
                      f"条件:{s.get('条件')}")
            真, 假 = s.get("真") or {}, s.get("假") or {}
            行.append(f"       ├ 成立 → {真.get('工具')}  {_简述(真.get('参数'))}")
            行.append(f"       └ 不成立 → {假.get('工具')}  {_简述(假.get('参数'))}")
        else:
            行.append(f"  {s.get('编号')}. {s.get('工具')}  {_简述(s.get('参数'))}")
            行.append(f"       要得到:{s.get('要得到什么', '（没写）')}")
    if 错 is not None:
        if 错:
            行.append("  ★ 代码审 · 不通过:")
            for x in 错:
                行.append(f"      ✗ {x}")
        else:
            行.append("  ★ 代码审 · 通过(工具名和参数值都在库里)")
    return "\n".join(行)


#  ══════════════════════════════════════════════════════════════════
#  ④ 执行 —— 照着计划走
#
#  ★★★ 而"条件那一步谁来算"这一件事,是这一段唯一的设计判断:
#      计划里写的是【一句话】("末期 < 前期"),而那句话【要有人判】。
#      三个候选:① 让模型写可执行的表达式 ② 出计划时就写成结构化的 ③ 执行时问模型
#      ★ 选 ③ 的理由,是那条判据:
#         "选错了【会被抓住】的选择,可以交给模型"
#      ★★ "降了没降"判错会怎样:两支走下去【结果不同】——
#         说"降了"就去查原因,而数据里没降,【用户看得出来】。
#      ★★★ 所以这个选择交出去是安全的。而 ①② 都是在【避免问模型】,
#            按那条判据,这里没必要避免。
# ══════════════════════════════════════════════════════════════════
判条件提示词 = """判断下面这个条件【成立还是不成立】。

条件:{条件}

第 {第几步} 步的结果:
{结果}

★ 只回答两个字:「成立」或「不成立」。
    · 数字比较就直接比 —— 别脑补。
    · 结果里【没有可比的东西】就说「成立」?不 —— 那种情况回答「判不了」。"""


def 判条件(条件, 第几步, 结果文本):
    """让模型判条件。返回 True / False / None(判不了)。"""
    from llm import chat
    try:
        答 = chat(判条件提示词.format(条件=条件, 第几步=第几步,
                                     结果=结果文本[:1200]),
                  max_tokens=10).strip()
    except Exception as e:
        return None
    if "成立" in 答 and "不成立" not in 答:
        return True
    if "不成立" in 答:
        return False
    return None


def 执行计划(con, 计划, 追问=False):
    """照着计划走。返回 (每步的记录, 出没出问题)。

    ★ 每步之后检查【它自己说要得到什么】——
      而那正是 reflection 的雏形:这一步做成了没有。
      ⚠ 现在只检查"值是不是空的"—— 那是【能算的】那部分。
    """
    from agent_tools import _调工具
    if "_失败" in 计划:
        return [{"步": "?", "结果": f"计划本身出不了:{计划['_失败']}"}], True

    记录 = []
    各步的值 = {}
    有问题 = False
    #  ═══ ★★★ 2026-09-23 加 待播:条件判完的那句话【要进答案】 ═══
    #  【为什么 —— 洞②:条件判错了,用户看不出来】
    #      条件判错 → 走错支 → 而答案【照样像个答案】→ ★ 静默。
    #     ★★ 这是这一层最要命的地方:它自己做了一个决定,而那个决定【藏在过程里】。
    #     ★★★ 所以:判完必须【说出来】—— 判成了什么、依据是哪个数、所以走了哪一支。
    #        那正是 plan-and-execute 那个"审查点"的人话版本:
    #        它要替用户做几步决定,所以【必须先说清它决定了什么】。
    #     ★ 而用户拿到这句话,就能自己判断"它判得对不对" —— 判断权还给他。
    #        这跟用户定的那条规矩是一致的:「数据摆出来,程序给判断」。
    待播 = None

    for 步 in (计划.get("步骤") or []):
        编号 = 步.get("编号")

        if "条件" in 步:
            看 = 步.get("看第几步")
            前面 = 各步的值.get(看, "")
            成立 = 判条件(步.get("条件", ""), 看, str(前面))
            判词 = {True: "成立", False: "不成立", None: "★ 判不了"}[成立]
            记录.append({"步": f"{编号}(条件)", "条件": 步.get("条件"),
                         "看第几步": 看, "前面那步的结果": str(前面)[:200],
                         "判成": 判词})
            if 成立 is None:
                记录.append({"步": f"{编号}(条件)", "结果": "★ 判不了 —— 不往下走,也不猜"})
                有问题 = True
                break
            走 = 步.get("真") if 成立 else 步.get("假")
            记录.append({"步": f"{编号}(条件)", "走的是": 走.get("工具") if 走 else None,
                         "为什么": (走 or {}).get("为什么", "")})
            #  ★★★ 这句话要播出去 —— 见上面那段注释
            待播 = (f"★ 第{编号}步是个岔路口:我拿第{看}步的结果判"
                    f"「{步.get('条件')}」→ 判成【{判词}】。"
                    f"依据:{str(前面)[:120]}。"
                    f"所以走的是【{'成立' if 成立 else '不成立'}】那一支"
                    f"({(走 or {}).get('工具') or '没写'})。")
        else:
            走 = 步

        if not isinstance(走, dict):
            记录.append({"步": f"{编号}", "结果": "这一支没写 —— 停"})
            有问题 = True
            break

        #  ★ 调工具 —— 参数从计划里拿(★ 不再让模型选;那是计划的全部意义)
        参 = 走.get("参数") or {}
        try:
            r = _照计划调(con, 走, 参)
        except Exception as e:
            r = {"值": None, "把握": "工具答不了", "怎么定的": f"{type(e).__name__}: {e}"}

        各步的值[编号] = r.get("值")
        值 = r.get("值")
        有东西 = bool(值) and 值 != [""]

        #  ★★★ 把条件那句话【放进答案里】—— 见上面 待播 那段注释。
        #    ⚠ 只在【这一步真的拿到了东西】时才播:拿不到会走下面那条"没拿到"的分支,
        #      而那一条【本身就会出声】—— 两条都播就重复了。
        if 待播 and 有东西:
            值 = [待播] + list(值 if isinstance(值, list) else [值])
            各步的值[编号] = 值
            待播 = None

        记录.append({"步": f"{编号}", "工具": 走.get("工具"), "参数": 参,
                     "把握": r.get("把握"), "怎么定的": (r.get("怎么定的") or "")[:150],
                     "值": str(值)[:300],
                     "它说要得到": 步.get("要得到什么", "（没写）")})

        #  ★ reflection 的雏形:它自己说"这一步要得到 X"—— 拿到了吗?
        if not 有东西:
            记录.append({"步": f"{编号}", "★ 没拿到":
                          f"它说要得到「{步.get('要得到什么', '?')}」,而结果是空的 —— 停,不往下走"})
            有问题 = True
            break

    return 记录, 有问题


def _照计划调(con, 步, 参):
    """按计划里的【工具名 + 参数】去调 —— 走的是和主链同一套工具。

    ★ 为什么单独一个函数:计划里的参数是【一份 JSON】,
      而那四个抽参数的工具【要的是问句】—— 所以这里直接调【干活类】那两个。
    """
    from agent_tools import _查表, _查原文, _查逐项
    工具 = 步.get("工具")
    if 工具 == "查表":
        return _查表(con, "", 参.get("期次") or [], 参.get("机场"), 参.get("指标"))
    if 工具 == "查原文":
        return _查原文(con, 步.get("_问") or 参.get("问") or "", 参.get("期次") or [])
    if 工具 == "查逐项":
        #  ★★★ 2026-09-23 加 —— 而它正是被这道题逼出来的:
        #    「浦东2025Q4表现怎么样，要是不好就说说是哪一项拖后腿」
        #    ★ 模型要【一次查 7 个指标】,而"查表"的参数形状是【一个字符串】——
        #      它写不成,于是写成列表,而代码审崩了。
        #    ★★ 所以这一段的形状本来就该是【一个工具】:输入"哪个机场哪一期",
        #      输出【一整张对照表】。那才配得上"一步查 7 项"。
        return _查逐项(con, 参.get("期次") or [], 参.get("机场"))
    return {"值": None, "把握": "不认识的工具", "怎么定的": f"计划里写了「{工具}」"}


def _简述(参数):
    if not isinstance(参数, dict):
        return ""
    p = []
    for k in ("期次", "机场", "指标"):
        if 参数.get(k):
            p.append(f"{k}={参数[k]}")
    return " ".join(p)


