# -*- coding: utf-8 -*-
r"""
说人话 —— 把【代码查出来的事实】交给大模型组织成一句话,而数字锁死。

═══ 它解决什么 ═══
    现在 SQL 那条路的答案是代码拼的:
        「2025Q4 上海浦东国际机场:综合得分 4.23,排名第 5/42」
    ★ 对,但生硬。而更要紧的是:【它做不了判断】——
      说不出"这个成绩算好还是差""和上期比是涨还是落""该不该提醒他"。

═══ ★★★ 三层,而分工是这一路量出来的 ═══
        SQL / Python
             ↓
    ┌──────────────────┐
    │ Fact Layer       │  ★ 全由代码算 —— 数字【和定性词】都在这里
    │  得分 4.23        │
    │  名次 5/42        │
    │  与同档 "略高"     │  ← ★ 定性也由代码定档,不是模型说
    │  与上期 "小幅回落"  │
    └──────────────────┘
             ↓
    ┌──────────────────┐
    │ 占位符替换        │  ★ 数字和定性词【都变成 {N1}】——
    │  {机场} 本期…{N1} │     模型【碰不到】它们
    └──────────────────┘
             ↓
    ┌──────────────────┐
    │ LLM 判断层        │  ★ 它只剩三件事可做:
    │                   │     · 挑哪些事实值得说
    │                   │     · 怎么连
    │                   │     · ★ 要不要那个"但是"
    └──────────────────┘
             ↓
    ┌──────────────────┐
    │ 回填 + 校验        │  ★ 校验用 数字溯源.py
    └──────────────────┘
             ↓
          最终答案

═══ ★★★★ 为什么"占位符"和"提示词强调"不是一个级别 ═══
    ❌ 提示词:  「得分是 4.23,请不要修改它」
        ★ 那是在【相信模型遵守规则】—— 而它不遵守时【不报错】。
    ✅ 占位符:  「得分是 {N3}」→ 模型输出 {N3} → 代码填成 4.23
        ★★ 那是在【从架构上限制它的权限】—— 它想改也没得改。

═══ ⚠⚠ 而有一条实测的界线:校验【不能"一律拒"】 ═══
    报告那条路的"硬查"假报过【三轮】——
    「前10名」的 10、「第1名」的 1、「2025Q4」的 2025 全被当成编的数。
    ★ 所以校验分两档:【能算的硬判,不能算的摆出来】。
      见 数字溯源.py 开头那段。

═══ 怎么用 ═══
    python tools/说人话.py                    # 拿内置例子跑一遍
    python tools/说人话.py --事实 '{"机场":"上海浦东国际机场",...}'
"""
import sys
import io
import json
import argparse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from 数字溯源 import 取名, 填, 查, 占位


#  ══════════════════════════════════════════════════════════════════
#  ★ 模板 —— 也就是"骨架"
#
#  ⚠⚠ 这一块【该由人写,不该由我写】——
#     因为"排名第 5/42 该说成什么"是措辞判断,不是技术。
#     下面这版是我起的草稿,★ 标着【待改】。
#  ══════════════════════════════════════════════════════════════════
默认模板 = """{机场} 在 {期次} 的综合得分是 {综合得分}，在 {总数} 家机场中排第 {名次} 位。
与同档平均水平相比{与同档}，与上期相比{与上期}。"""


提示词 = """你在帮一个民航数据问答系统【组织回答】。

【已经由程序算好的事实】
@@事实@@

【建议的骨架 —— 占位符原样保留,顺序可以按你的判断调】
@@骨架@@

【用户的原始问题】
@@问题@@

═══════════════════════════════════════════════════
请仅依据上面提供的事实组织回答。

★ 事实中的数值、实体、期次、比较关系【均已由程序计算】,
  并且已经写成了 {名次} 这样的占位符。请【保持其语义不变】。

你的任务是:
  1. 判断用户问题最值得关注的【是哪几条事实】;
  2. 选择合适的比较关系进行解释;
  3. 把这些事实组织成自然、简洁的回答。

⛔ 不要自行进行新的数值计算。
⛔ 不要引入事实中不存在的结论。
⛔ 占位符（形如 {名次}）【原样保留】,不要改写、不要翻译、不要删除。
═══════════════════════════════════════════════════

只输出组织好的那段话,不要解释你怎么想的。"""


def 组织(事实, 问题, 模板=None, 试跑=False):
    """事实 + 问题 → 说成人话的答案（含校验结果）。

    ★ 返回 (最终答案, 校验结果 dict, 模型原始输出)。
      三个都返回,是为了【能看见中间那一步】——
      出问题时能分清是"模型写歪了"还是"回填错了"。
    """
    模板 = 模板 or 默认模板
    表 = 取名(事实)

    #  ① 把模板里的占位符换成"真值占位"
    #     ⚠ 注意:这一步不是填真值,是【确认模板里的占位符名对得上】
    模板里有的 = set(占位.findall(模板))
    表里有的 = set(表)
    if not 模板里有的 <= 表里有的:
        缺 = 模板里有的 - 表里有的
        return None, {"硬判": [f"⚠ 模板里用了不存在的占位符:{缺}"], "表外": []}, ""

    #  ② 给模型看的"事实"—— ★ 把真值写成占位符形式,它照抄就行
    给模型的 = "\n".join(f"  {名} = {值}" for 名, 值 in 表.items())
    骨架 = f"（按这个骨架组织，占位符原样保留）\n{模板}"

    if 试跑:
        #  ★ 不调模型,只看看发给它的是什么 —— 省一次调用
        文本 = (提示词.replace("@@事实@@", 给模型的)
                     .replace("@@骨架@@", 模板)
                     .replace("@@问题@@", 问题))
        return None, {"给模型的": 给模型的, "骨架": 模板, "全文": 文本,
                      "占位符表": 表}, ""

    #  ③ 交给模型
    from llm import chat
    #  ⚠ 2026-09-30 修:第一版忘了把【骨架】传给模型 ——
    #    于是它只看到映射表,不知道用哪些占位符、什么顺序,就会自由发挥。
    #    ★ 而"骨架"的全部用意就是【约束结构】。
    #    ★★ 是"只看发的什么"那个开关一眼照出来的 —— 先看再跑的价值。
    #  ⚠⚠ 2026-09-30 修:提示词【不能用 .format()】——
    #    因为它正文里就有 {N1} 这种占位符示例,format 会把它们当成真字段。
    #    ★ 第一版用 format,于是我在提示词和模板里到处转义({{N1}}),
    #      而【模板是变量值、不经过 format】—— 结果模型看到两种写法混着,
    #      它自然写了单花括号,而正则要双的 → 回填全失败。
    #    ★★ 改用 replace:提示词里可以自由出现 {N1}。
    文本 = (提示词.replace("@@事实@@", 给模型的)
                 .replace("@@骨架@@", 模板)
                 .replace("@@问题@@", 问题))
    原始 = chat(文本, max_tokens=400).strip()

    #  ④ 回填
    答案 = 填(原始, 表)

    #  ⑤ 校验 —— ★ 用那把单独量过的尺子
    硬判, 表外 = 查(原始, 表, 模板)

    return 答案, {"硬判": 硬判, "表外": 表外, "占位符表": 表}, 原始


#  ══════════════════════════════════════════════════════════════════
#  ★ 主链调这个 —— answer_sql 开了开关就走到这儿
#  ══════════════════════════════════════════════════════════════════
def 从事实说(q, facts):
    """事实【列表】→ 一句话。返回 (答案 or None, 校验)。

    ═══ ⚠ 第一刀【只处理一个实体一个期次】 ═══
        facts 是列表 —— 因为 answer_sql 那个分支可能查出多期/多机场
        (「浦东和虹桥谁高」「2023Q3 和 2025Q4」那种)。
        ★ 而【多个的骨架完全不一样】:它要说的是"谁高""相差多少",
          不是"某家这期多少分"。
        ★★ 所以第一刀只处理 len(facts)==1 的 —— 其余的返回 None,
           主链那边【退回老路】(代码拼的原话),一句话不多说。
        ⚠ 而这是【故意的边界】,不是漏了 —— 第二刀才做比较类的骨架。
    """
    if not facts:
        return None, {"硬判": ["没有事实"], "表外": []}
    if len(facts) > 1:
        return None, {"硬判": [], "表外": [],
                      "_跳过": f"这一刀只处理单个实体单期次(这次有 {len(facts)} 条)"}

    答案, 校验, _ = 组织(facts[0], q, 单期模板)
    return 答案, 校验


#  ★ 单个实体、单个期次的骨架。
#  ⚠⚠ 这一块【该由人写】—— 见文件开头那段(措辞是判断,不是技术)。
#     ⚠ 而第一刀【还没有参照】(与同档/与上期)—— 那要靠 机场分档 表另算,
#       是第二刀的事。所以现在这句话只有"是什么",还没有"算好还是差"。
单期模板 = """{机场} 在 {期次} 的综合得分是 {综合得分}，在 {总数} 家机场中排第 {名次} 位。"""


#  ══════════════════════════════════════════════════════════════════
#  内置例子 —— ★ 用【真数据】(2025Q4 上海浦东,来自 capse.db)
#  ══════════════════════════════════════════════════════════════════
例子事实 = {
    "机场": "上海浦东国际机场",
    "期次": "2025Q4",
    "综合得分": 4.23,
    "名次": 5,
    "总数": 42,
    "与同档": "高 0.08",
    "与上期": "低 0.02",
}
例子问题 = "上海浦东国际机场这期表现怎么样？"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--事实", help="事实 dict 的 JSON")
    ap.add_argument("--问题", default=例子问题)
    ap.add_argument("--只看发的什么", action="store_true",
                    help="★ 不调模型,只打印发出去的东西 —— 省一次调用")
    a = ap.parse_args()

    事实 = json.loads(a.事实) if a.事实 else 例子事实

    print("=" * 74)
    print("  说人话 —— 事实 → 一句话")
    print("=" * 74)
    print(f"\n  用户问:{a.问题}")
    print(f"\n  ★ 事实层(全由代码算):")
    for k, v in 事实.items():
        print(f"      {k} = {v}")

    答案, 校验, 原始 = 组织(事实, a.问题, 试跑=a.只看发的什么)

    if a.只看发的什么:
        print(f"\n  ★ 发给模型的:")
        for l in 校验["给模型的"].splitlines():
            print(f"      {l}")
        print(f"\n  ★ 骨架(占位符待填):")
        for l in 校验["骨架"].splitlines():
            print(f"      {l}")
        print(f"\n  ★ 占位符表:{校验['占位符表']}")
        return 0

    print(f"\n  ── 模型原样输出 ──")
    print(f"      {原始}")
    print(f"\n  ── 回填之后 ──")
    print(f"      {答案}")
    print(f"\n  ── 校验 ──")
    if 校验["硬判"]:
        for x in 校验["硬判"]:
            print(f"      ❌ {x}")
    else:
        print(f"      ✅ 硬判全过")
    if 校验["表外"]:
        print(f"      ⚠ 表外数字(只是列出来,不代表错):{校验['表外']}")
    return 0 if not 校验["硬判"] else 1


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    sys.exit(main())
