import sys, io, re, sqlite3, argparse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from paths import DB, DOCS

测试集 = DOCS / "说法测试集.md"

#  ★ 从 ask.py 拿【真的那一条】—— 不在这里另抄一份正则。
#    抄一份的话,改了 ask.py 这把尺子就【悄悄量错】,而且不报错。
from ask import 平均词, _档位词, _问的是平均

该答档均 = "档均"
该反问 = "反问"
出声的去向 = {"判不出", "拒答"}


def 读测试集():
    """从 md 的表格里读出行。★ 表就是尺子的输入 —— 改说法不用改代码。"""
    行 = []
    for ln in 测试集.read_text(encoding="utf-8").splitlines():
        if not ln.startswith("|"):
            continue
        #  ⚠ 必须【去掉反引号】—— md 里那几格写的是 `档均`(带反引号),
        #    第一版没去,于是 c[3] == "档均" 永远不成立 → 正向被算成 0 句。
        #    ★★ 而它【没报错】,报的是一个看着像样的数 —— 量具坏了,先修量具。
        c = [x.strip().strip("`").strip() for x in ln.strip("|").split("|")]
        if len(c) < 4 or not c[0].isdigit():
            continue
        行.append({"号": int(c[0]), "说法": c[1], "期次写法": c[2], "问的是": c[3]})
    return 行


def 分组(行):
    正 = [r for r in 行 if r["问的是"] == 该答档均]
    问 = [r for r in 行 if r["问的是"] == 该反问]
    反 = [r for r in 行 if r["问的是"] not in (该答档均, 该反问)]
    return 正, 问, 反


#  ══════════════════════════════════════════════════════════════════
#  词表层
# ══════════════════════════════════════════════════════════════════
def 跑词表层(con, 行):
    正, 问, 反 = 分组(行)

    def 认得(q):
        c = _问的是平均(q)
        return c, ("词表命中" if c else "词表没命中:句子里没有「平均」也没有「均值」")

    print(f"\n── 正向:该答【档均】的({len(正)} 句)· 认得出几个 ──")
    对 = 0
    for r in 正:
        c, 为什么 = 认得(r["说法"])
        对 += c
        print(f"  {'✅' if c else '❌ 漏了'}  {r['号']:>2}. {r['说法']}"
              + ("" if c else f"   ← {为什么}"))

    print(f"\n── ★ 反问:该【出声】的({len(问)} 句)· 词表会不会静默答成档均 ──")
    静 = 0
    for r in 问:
        c, _ = 认得(r["说法"])
        静 += c
        print(f"  {'❌★ 会被静默答成档均' if c else '✅ 认不出(→ 后面才有机会出声)'}"
              f"  {r['号']:>2}. {r['说法']}")
    print(f"     ★ 这一组【词表层判不了对错】—— 词表认不出≠系统答错,"
          f"\n       要看系统【最后出声没出声】。用 --全链 量。")

    print(f"\n── 反向:【不该】答成档均的({len(反)} 句)· 有没有误判 ──")
    没错 = 0
    for r in 反:
        c, 为什么 = 认得(r["说法"])
        没错 += (not c)
        print(f"  {'✅ 没误判' if not c else '❌★ 判成档均了'}"
              f"  {r['号']:>2}. {r['说法']}   (它真正问的是:{r['问的是']})")
    return 对, len(正), 没错, len(反), 静, len(问)


#  ══════════════════════════════════════════════════════════════════
#  全链层 —— 跑真的那条链
# ══════════════════════════════════════════════════════════════════
def 跑全链层(con, 行):
    import ask
    from route import load_airports, load_indicators
    airports = load_airports(con)
    indicators = load_indicators(con)
    正, 问, 反 = 分组(行)
    出 = {}                      # 号 → 去向

    for r in 行:
        try:
            d = ask.ask(con, r["说法"], airports, indicators)
            去向 = d.get("去向", "?")
            答 = " ".join(str(x) for x in (d.get("答案") or []))[:110]
            警 = " / ".join(d.get("警告") or [])
        except Exception as e:
            去向, 答, 警 = "抛异常", f"{type(e).__name__}: {e}"[:110], ""
        出[r["号"]] = 去向
        mark = "🔇 出声" if 去向 in 出声的去向 else "🔊 答了"
        print(f"\n  {r['号']:>2}. [该:{r['问的是']:<4}] {mark} · 去向={去向}")
        print(f"      问:{r['说法']}")
        if 答:
            print(f"      答:{答}")
        if 警:
            print(f"      ⚠ {警}")

    def 出声率(组):
        if not 组:
            return 0, 0
        n = sum(1 for r in 组 if 出.get(r["号"]) in 出声的去向)
        return n, len(组)

    a, b = 出声率(正)
    c, d = 出声率(问)
    print(f"\n  ★ 正向该【答】,该出声的有:{a}/{b}  (这几个是拒答/判不出,属于没答上)")
    print(f"  ★★ 反问该【出声】,真出声的有:{c}/{d}  (剩下的就是静默作答 —— 最要命的那种)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--全链", action="store_true", help="跑真的那条链(会调大模型)")
    a = ap.parse_args()
    con = sqlite3.connect(DB)
    行 = 读测试集()

    print("=" * 78)
    print("  第 20 课 · 尺子:认不认得出「这是在问平均」")
    print(f"  这一版:{'全链层(用户最后拿到什么)' if a.全链 else '词表层(第 20 课要换掉的那一层)'}")
    print("=" * 78)

    if a.全链:
        跑全链层(con, 行)
    else:
        对, 正n, 没错, 反n, 静, 问n = 跑词表层(con, 行)
        print("\n" + "=" * 78)
        print(f"  认得出(正向):  {对}/{正n}")
        print(f"  没误判(反向):  {没错}/{反n}")
        print(f"  会被静默答成档均(反问组):  {静}/{问n}   ← ⚠ 不看这个数就是自欺")
        print("=" * 78)

    print("""
  ★ 这些数【不能合并成一个总分】—— 它们的代价不一样:
     漏了是"答不出",静默作答是"答错而看不出来"。
  ★★ 第 20 课的目标不是把某一个数刷到满分,
     是【换掉底下那一层】之后,几个数都别变差、而且没为任何一句写规则。""")


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    main()
