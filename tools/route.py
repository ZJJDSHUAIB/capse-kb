def hard_limits(q):
    """⚠ 2026-09-19 起【没有调用方了】—— 留着当参照,不要以为它还在工作。

    它原来被 verify() 的门② 用(检查"用户点名的限定词,检索兑现了吗")。
    门② 因为判据是【字面】而报假警报,已去掉;
    ★ 那个职能被 ask.check_missed() 接走了("它说没有,而限定词其实搜得到")。
    ★★ 留着它的原因:以后若想恢复门②,得先看它原来是怎么抽限定词的。
    """
    """问句里的硬限定词。抽不到 → 空列表(不判)。"""
    out = []
    for m in LIMIT.finditer(q):
        x = m.group(0).strip().lstrip('的')
        if len(x) >= 2 and x not in out:
            out.append(x)
    return out


def verify(con, q, periods, airport, hits):
    """事后验证:走了检索的题,【答之前】回头看一眼 —— 这题真的该走检索吗?

    ═══ 为什么要"事后"再验一次 ═══
        路由是【事前】判的,判错了它自己不知道。
        但答完之前还有一道机会:看看检索回来的东西,到底能不能回答这个问句。

    ═══ 两边对不上 = 信号 ═══
        问句里【应该有】什么          vs   检索回来的【实际有】什么
        ─────────────────────────────────────────────────
        有期次 + 有机场                     一个数字都没有
        → 用户问的是"某个机场某一期的数据"
        → 而检索回来的文字里根本没有数
        → 这题八成是要数的,【判错了】

    ═══ 这个检查的边界(必须写清楚,否则会变成新的幻觉) ═══
        它只能抓【一边有、另一边没有】这种粗的对不上。
        如果检索回来的文字里【顺带】出现了别的数字(报告里到处是数字),
        它就抓不住了 —— 那不是判对了,是【检查被绕过去了】。
        兜底检查不是安全保证,只是把"完全没查"变成"查了一道"。
    """
    # ══ 门①:问"某个机场某一期" → 查回来的东西里有没有数 ══════
    #   (第 4 课就有的一道,没动)
    if periods and airport is not None:
        has_number = any(NUMBER.search(h["文本"]) for h in hits)
        if not hits:
            return "检索一条都没回来,但问句里有期次有机场 —— 判错了,该走 SQL"
        if not has_number:
            return "检索回来了内容,但里面一个数字都没有 —— 而问句要的是一个数,判错了"
        return None

    # ══ ★★ 门② 于 2026-09-19 去掉 ═══════════════════════════
    #
    #  它原来长这样:
    #     lims = hard_limits(q)
    #     miss = [x for x in lims if not any(x in h["文本"] for h in hits)]
    #     if miss: return f"你问的「{miss}」,在检索回来的 {len(hits)} 页里找不到"
    #
    #  ★ 它的【意图】是对的:"用户点名的那一条,检索兑现了吗" 是个真信号。
    #  ★★ 它错在【判据】—— 字面。
    #     题51 的限定词是「著作权声明」,而库里写「法律声明」;
    #     题52 的限定词是「测评简介」,而库里写「CAPSE简介」。
    #     字面找不到 → 响。**而生成层按意思找到了,还标了出处。**
    #     → 它报的全是【假警报】,而项目规矩是"假警报多了,真警报就没人看了"。
    #
    #  ★★★ 为什么是【去掉】而不是改判据:
    #     它的职能已经被 ask.check_missed() 接走了,而且那个判得更准 ——
    #     "它说『材料里没有』,而限定词其实搜得到"。
    #     ★ 两条规则说同一件事,会在同一批题上【打架】:
    #       一个说"没取到"(按字面),一个说"取到了"(生成层答出来了)。
    #     项目规矩:「同一条规则只装在一条路上」。
    #
    #  ⚠ 门① 留着 —— 它抓的是【另一件事】:问"某机场某期"而回来的文字里一个数都没有,
    #    那是【路由判错】(该走 SQL 却走了检索)。没人取代它。
    #
    #  ★ 这一条本身也是项目那个老故事的又一次:
    #    第 4 课建门② 时,题就是"期次+机场"那个形状的;
