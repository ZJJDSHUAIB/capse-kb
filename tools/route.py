def 不分机场的字段(con):
    """库里哪些字段是【全行业】的(不按机场分)?

    ═══ ★★★ 判据:看【表里有没有"机场"这一列】 ═══
        meta 表:        期次 / 样本量 / 机场数 / 一级指标数 / 二级指标数 / 口径版本
                        ★ 它【没有】机场列 → 里面的量都是全行业的
        综合得分表:      期次 / 【机场】/ 得分 / 来源
                        ★ 它【有】 → 那些量按机场分

    ★ 为什么用表结构、不写一张清单:
      写清单要人维护 —— 加一个字段就得记得改。
      而从表结构算,【库里加了新字段,它会自动跟上】。
    ★★ 这和"列名就是这个系统能说出名字的东西的定义"是同一条思路。

    ⚠ 期次要排掉:它到处都是,但它区分的是【时间】,不是【哪个机场】。
    """
    不分 = set()
    for (表,) in con.execute("SELECT name FROM sqlite_master WHERE type='table'"):
        cols = [r[1] for r in con.execute(f"PRAGMA table_info({表})")]
        if "机场" not in cols:
            不分 |= set(cols)
    return 不分 - {"期次"}


def _结论(值, 怎么定的, 把握):
    """抽参数的统一返回形状 —— 把"抽出什么"和"怎么抽的"一起交出去。"""
    return {"值": list(值), "怎么定的": 怎么定的, "把握": 把握}


def 单值(结论):
    """从统一形状里取【那一个】值 —— 没有就是 None。

    ★ 给"最多只会有一个"的调用方用(机场、指标)。
      ⚠ 期次【不能用它】—— 期次天然可能是多个("2023Q3 和 2025Q4 比较"),
        用了会【默默丢掉】其中几个,而那又是一次静默。
    """
    return 结论["值"][0] if 结论["值"] else None


def find_periods(con, q, 表=None):
    """问题里提到的季度。返回统一形状(见上面那段说明)。"""
    got = sorted({f"{y}Q{m}" for y, m in QUARTER.findall(q)})
    if not got:
        return _结论([], "句子里没有「2025Q4」这种写法", "没找到")
    return _结论(got, f"句子里直接写着 {'、'.join(got)}", "确定")


def mentions_annual(q):
    """提到"年度报告"吗? —— 年度报告【没有入库】,是拒答的第一号来源。"""
    return "年度" in q and not QUARTER.search(q)


def find_airport(con, q, 表=None):
    """在问题里找机场简称。取最长匹配(避免「上海浦东」被「上海」这种短名抢走)。

    ⚠ 多个命中时那是【猜】—— 所以"把握"标成"有歧义",不假装是确定的。
    """
    airports = 表 if 表 is not None else load_airports(con)
    hits = [core for core in airports if core in q]
    if hits:
        名 = [airports[c] for c in hits]
        取了最长 = max(名, key=len)
        说明 = f"问题里出现了 {len(hits)} 个机场名:{'、'.join(名)}"
        if len(hits) == 1:
            return _结论([取了最长], 说明, "唯一")
        return _结论([取了最长], 说明 + f";取了最长的那个「{取了最长}」", "有歧义")

    #  ═══ ★★★ 2026-09-22 加:整名一个都没命中 → 试【用户只说城市】 ═══
    #
    #  【为什么要加 —— 实测踩到,而且后果很重】
    #      用户说「那合肥呢」,而库里的简称是【合肥新桥】——
    #      于是抽不出来。而后果不止是"抽不出":
    #        ★ 会话记忆里那一轮被判成"没抽到实体",
    #          于是它【借了上一轮的浦东】来答"那合肥呢"。
    #        ★★ 也就是说:用户问合肥,系统答了浦东 —— 而【看不出来】。
    #           格式正常,数字也都是真的,只是答的不是合肥。
    #        ★★★ 那是"旧信息污染新问题",也就是 Update 没做成功。
    #
    #  【判据 —— 全是算的,不用问模型】
    #      把每个简称的【前两个字】当城市名,看它在不在问题里。
    #      · 那个城市只对应【一个】机场 → 认它
    #      · 对应【两个或更多】→ 歧义,不该猜
    #
    #  ★ 实测库里 43 个简称,前两字相同的【只有 4 组】:
    #        上海 → 浦东 / 虹桥      北京 → 大兴 / 首都
    #        乌鲁 → 地窝堡 / 天山    成都 → 双流 / 天府
    #    而「合肥」「深圳」「厦门」这种只有一个 —— 所以绝大多数能安全地认。
    #
    #  ⚠ 它排在【精确匹配之后】:整名能命中就用整名 ——
    #    这样加这一层【不会改变原来任何一道题的答案】。
    城市命中 = {}
    for core, full in airports.items():
        if len(core) > 2 and core[:2] in q:
            城市命中.setdefault(core[:2], []).append(full)
    if not 城市命中:
        return _结论([], "问题里没有库里任何一个机场名,也没只报城市名", "没找到")

    候选 = []
    for 城, 全名们 in 城市命中.items():
        候选 += [(城, n) for n in 全名们]
    if len(城市命中) > 1:
        #  问题里出现了两个不同城市名 —— 那是【对比题】,该由 find_airports 处理,
        #  这里只报"有歧义",不猜
        return _结论([], "问题里出现了多个城市名:"
                     + "、".join(f"{c}({len(n)}个机场)" for c, n in 城市命中.items()),
                     "有歧义")
    城, 全名们 = next(iter(城市命中.items()))
    if len(全名们) == 1:
        return _结论([全名们[0]],
                     f"用户只说了城市名「{城}」,而库里它只有一家机场:{全名们[0]}",
                     "唯一")
    return _结论([], f"用户说了城市名「{城}」,而它对应 {len(全名们)} 家机场:"
                 + "、".join(全名们) + " —— 是哪一家?", "有歧义")


def find_airports(con, q, airports):
    """在问题里找【所有】机场。长的优先,不重叠,返回全名。

    ★ 为什么要有复数版(实测,题 9/11/13/15/59):
      find_airport 只返回【一个】,注释写明了是故意的 ——
        "取最长匹配(避免'上海浦东'被'上海'这种短名抢走)"
      本意是【防重名重叠】,但它同时把「两个不同机场」也压成了一个。

    ★★ 第二次修(挑战集 C3,「2025Q4浦东和虹桥机场的得分分别是多少」):
      库里存的是「上海浦东」「上海虹桥」,而匹配方向是
        「简称【是不是】问句的子串」→ "上海浦东" 不是 "浦东和虹桥…" 的子串 → 一个都认不出。
      **方向反了。** 该问的是"问句里的词,是不是某个机场名的一部分"。
      → 加一条【尾段匹配】:「上海浦东」的尾 2 字「浦东」在问句里 → 认。

      ⚠ 两条底线:
        ① 唯一性:一个尾段对得上多个机场 → 【不认】。
        ② 位置要对:尾段匹配时,它在问句里的位置是【尾段】的位置,不是全名的位置。
           第一版忘了这点,于是「虹桥」算出的位置是 -1,被当成"没找到"丢掉了。
           **匹配成功却算错位置 —— 那比不匹配更隐蔽。**
    """
    # ① 完整简称 / 全名,直接命中
    found = []                       # [(问句里的位置, 简称, 命中文本的长度)]
    for c in airports:
        i = q.find(c)
        if i >= 0:
            found.append((i, c, len(c)))

    # ② 再退一步认【尾段】—— 但必须唯一,而且跳过 ① 已经认到的
    #    ⚠ 第一版这里是 `if not found:` —— 于是「武宿和大连」只认出了大连:
    #      ① 认到了「大连」,② 就整段不跑了,「武宿」永远没机会。
    #      **"找到一些就不再找剩下的" —— 那是静默漏掉,不是"够了"。**
    got = {c for _, c, _ in found}
    tails = {}
    for c in airports:
        if c in got:
            continue
        for L in (2, 3):
            if len(c) <= L:
                continue
            t = c[-L:]
            if t in q:
                tails.setdefault(t, []).append(c)
                break
    for t, v in tails.items():
        if len(v) == 1:              # ★ 撞车就不认 —— 宁可认不出,不可认错
            found.append((q.find(t), v[0], len(t)))


    # ③ 去掉重叠(长的优先:别在「上海浦东」里再认出一个「浦东」)
    found.sort(key=lambda x: (-x[2], x[0]))
    keep, used = [], []
    for i, c, L in found:
        if any(not (i + L <= s or s + L2 <= i) for s, L2 in used):
            continue
        keep.append((i, c))
        used.append((i, L))

    # ④ 按在问句里出现的先后返回全名
    return [airports[c] for _, c in sorted(keep, key=lambda x: x[0])]



#  ═══ ★★★ 2026-09-22 加:固定答案名 ═══
#  【为什么 —— 量出来的根因,不是设想】
