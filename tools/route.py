def load_airports(con):
    """库里的机场全名 → 去掉通用后缀的简称,用于口语匹配。

    "上海浦东国际机场" → "上海浦东"      (用户会说"上海浦东")
    "北京首都国际机场" → "北京首都"
    这是规则版最脆的地方 —— 用户也可能说"浦东""首都机场",那就要认不出来了。
    """
    out = {}
    for (name,) in con.execute("SELECT DISTINCT 机场 FROM 综合得分"):
        core = name
        for suf in ("国际机场", "机场"):
            if core.endswith(suf):
                core = core[: -len(suf)]
                break
        out[core] = name
    return out


