def check():
    """题目自检:编号唯一、每道都有期望、类型合法。"""
    errs = []
    编号s = set()
    for c in CASES:
        if c["编号"] in 编号s:
            errs.append(f"{c['编号']}: 编号重复")
        编号s.add(c["编号"])
        if len(c["对话"]) != len(c["期望"]):
            errs.append(f"{c['编号']}: 对话 {len(c['对话'])} 句,"
                        f"而期望有 {len(c['期望'])} 条 —— 对不上")
        for e in c["期望"]:
            if e["类型"] not in ("答", "反问", "说不成立"):
                errs.append(f"{c['编号']}: 期望类型「{e['类型']}」不认识")
            if not e.get("必须含"):
                errs.append(f"{c['编号']}: 有一条期望没写【必须含】—— 那它判不了")
    return errs


