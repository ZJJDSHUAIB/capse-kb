r"""
第 15 课 · 工具说明书 —— 把能力变成【能被模型挑的东西】。

═══ 为什么需要它 ═══
    现在系统选路靠的是 route.py 里的两张词表:

        NUMERIC = re.compile(r'多少|几分|第几|排名|得分|样本量…')
        PROSE   = re.compile(r'为什么|原因|背景|变更|介绍…')

    ★ 那套东西很快、很可预测,而且【出错能查 —— 因为表就摆在那儿】。
    ★★ 所以 60/60 是它跑出来的 —— 这一课【不是来推翻它的】。

═══ 那这一课在干什么 ═══
    有些选择,词表解决不了。实测那一句:

        「分析上海浦东机场近两期表现,发现明显下降再分析原因」
        期次 → 没找到,因为:句子里没有「2025Q4」这种写法

    ★ "近两期"不是一种【能枚举的格式】:得先知道最新是哪一期,再往前数两期。
    ★★ 所以有一类选择必须交给模型。**而交出去要有东西交** —— 那就是这张说明书。

═══ ★★★ 交出去的判据(这一课最要紧的一句)═══
    只有【选错了会被抓住】的选择,才交给模型:

        交出去:选哪个工具、期次填什么
                → 选错了答案就不对,而硬判据会响

        留在代码:要不要做数字校验、要不要标出处
                → 交出去,它不校验你也不知道 —— 那是静默

    ⚠ 一句话:交出去的是【错了会被抓住】的那些。

═══ 说明书 = 四样东西 ═══
    名字 / 什么时候该用我 / 要什么输入 / 交出什么
    ★ 其中「什么时候该用我」是【给模型看的那句话】——
      写宽了它什么都抢,写窄了该用的时候想不起来。
"""
