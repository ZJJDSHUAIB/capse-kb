#  工具名 → 真的去调的那个函数(懒加载,免得 import 绕圈)
def _调工具(名字, con, q, 表=None):
    from route import find_periods, find_airport, find_indicator
    if 名字 == "抽期次":
        return find_periods(con, q)
    if 名字 == "抽机场":
        return find_airport(con, q, 表)
    if 名字 == "抽指标":
        return find_indicator(con, q, 表)
    if 名字 == "推期次":
        return 推期次(con, q)
    raise KeyError(名字)


# ══════════════════════════════════════════════════════════════════
#  ★★★ 推期次 —— 「去年」「近两期」这种相对说法
#
#  ═══ 这是张君杰定的规则落地的地方 ═══
#      他原话:
#          「去年 = 上一年最后一期」作为默认没错,但【不能静默执行】。
#          不加标注 → 坏了(静默误导)
#          加标注   → 不够好(看得见,但还是只给了 Q4)
#          加标注 + 支持追问全年 → 最好
#
#  ★ 这一版做前两档:默认 + 出声。
#  ★★ 第三档(追问全年)要【记住上一轮说了什么】—— 那是记忆,第 17 课。
#
#  ═══ ⚠ 为什么要单独写这个工具,而不是让模型算 ═══
#      实测(第 16 课):
#          问大模型「今天是几号」→ 它答「我无法知道今天的日期和当前年份,
#                                    我没有实时联网获取当前时间的能力」
#                                   ★ 三次都一样,它自己说得很清楚
#          而程序 → 2026-09-22 17:36,精确到分钟
#
#      ★★ 所以"去年是哪一年"这件事【只有代码知道】。
#          交给模型只有两种结局:放弃,或者编一个 —— 而编的那个看不出来。
#      ★★★ 这是"能算的地方别问大模型"的【第四个位置】:
#           ① 提问(表格解析) ② 判分 ③ 生成层 ④ 时间和日期
# ══════════════════════════════════════════════════════════════════

中文数 = {'一': 1, '两': 2, '二': 2, '三': 3, '四': 4, '五': 5}


def 推期次(con, q):
    """把「去年」「近两期」「最新一期」推成具体期次。★ 一定会说清用了什么默认。"""
    import datetime
    from route import _结论
    有期 = [r[0] for r in con.execute("SELECT DISTINCT 期次 FROM meta ORDER BY 期次")]
    if not 有期:
        return _结论([], "库里一期都没有", "没找到")
    今天 = datetime.date.today()

    #  ① 去年 / 上一年 → 上一年【最后一期】  ← ★ 这是默认惯例
    if any(w in q for w in ("去年", "上一年", "上年")):
        年 = 今天.year - 1
        命中 = [p for p in 有期 if p.startswith(str(年))]
        if 命中:
            return _结论(
                命中[-1:],
                f"★ 我按【默认惯例】理解「去年」:上一年({年})的最后一期。"
                f"⚠ 另一种理解是「{年} 全年」,那是 {len(命中)} 期"
                f"({命中[0]}~{命中[-1]})—— 如果你要的是全年,说一声。",
                "默认推断")
        return _结论([], f"库里没有 {年} 年的数据", "没找到")

    #  ② 近 N 期
    m = re.search(r'近\s*([一二三四五六两\d]+)\s*期', q)
    if m:
        难 = m.group(1)
        n = int(难) if 难.isdigit() else 中文数.get(难, 0)
        if n <= 0:
            return _结论([], f"读不出「近{难}期」是几期", "没找到")
        return _结论(有期[-n:], f"最新一期是 {有期[-1]},往前数 {n} 期", "确定")

    #  ③ 最新 / 现在
    if any(w in q for w in ("最新", "现在", "当前")):
        return _结论(有期[-1:], f"库里最新的一期是 {有期[-1]}", "确定")

    return _结论([], "句子里没有「去年」「近N期」这种相对说法", "没找到")


def run_tools(con, q, 让模型选=True):
    """模型读牌子挑 → 真的调 → 返回 {工具名: 那个工具的统一形状结果}。

    ★ 为什么返回值里【保留了"把握"和"怎么定的"】:
      那是唯一让调用方能看出"这一步是猜的"的东西。
      丢掉了它,后面就只剩一个看起来确定的值 —— 而它可能是个猜的。
    """
    if not 让模型选:
        选中 = [t["名字"] for t in TOOLS]      # 对照用:全调,不问模型
    else:
        from llm import chat
        牌子 = "\n".join(f"- {t['名字']}:{t['什么时候用']}" for t in TOOLS)
        prompt = f"""下面有几个工具。读说明,判断【这一个问题】要用哪些工具。

工具:
{牌子}

问题:{q}

★ 可以选【多个】—— 一句话同时需要两样时,两个都要选。
★ 也可以一个都不选 —— 如果这个问题不需要其中任何一个,回答「都不用」。

只回答工具名,用「、」分隔,不要解释。"""
        #  ⚠ max_tokens 给 30 —— 实测给 20 时,选两个工具的回答会被截断,
        #    而截断的结果会变成"只选了一个" —— 那是一次【静默的丢】。
        raw = chat(prompt, max_tokens=30).strip()
        选中 = [t["名字"] for t in TOOLS if t["名字"] in raw]

    结果 = {}
    for 名 in 选中:
        结果[名] = _调工具(名, con, q)
    return 结果, 选中


