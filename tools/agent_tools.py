def ask_model(q, 用旧牌子=False):
    """把说明书递给模型,让它挑。返回它选的工具名(或 None)。"""
    from llm import chat
    牌子 = "\n".join(
        f"- {t['名字']}:"
        f"{旧牌子_抽期次 if (用旧牌子 and t['名字'] == '抽期次') else t['什么时候用']}"
        for t in TOOLS)
    prompt = f"""下面有几个工具。读它们的说明,判断【这一个问题】该用哪个工具。

工具:
{牌子}

问题:{q}

只回答工具名,不要解释。如果这个问题【不应该】用其中任何一个,回答「都不用」。"""
    return chat(prompt, max_tokens=20).strip()


