# ══════════════════════════════════════════════════════════════════
#  5 句真的问法 —— 用来试牌子写得对不对
#
#  ★ 3 句【该】找它 + 2 句【不该】找它 —— 两个方向都要试。
#    ⚠ 只试"该找"的话,一句"什么时候都用我"的牌子会全过 ——
#      而那正是最坏的牌子。
# ══════════════════════════════════════════════════════════════════
CASES = [
    #  (问法, 该不该交给「抽期次」, 为什么)
    ("2025Q4上海浦东国际机场综合得分是多少", True,
     "句子里直接写着 2025Q4"),
    ("2023Q3和2025Q4的上海浦东，哪个分高", True,
     "同样直接写着,而且是两个期次"),
    ("2024Q3上海浦东国际机场的机场安检得分是多少", True,
     "句子里直接写着 2024Q3"),

    ("分析上海浦东机场近两期表现，发现明显下降再分析原因", False,
     "「近两期」不是固定写法 —— 抽期次认不出来,该先去别处定期次"),
    ("浦东去年考了多少分", False,
     "「去年」同样不是固定写法"),

    #  ★★★ 这一句是【干扰项】—— 是张君杰做的那一块。
    #      它句子里【确实写着】2025Q4,所以按最初那版牌子(只看有没有固定写法)
    #      它会被选中,而那是错的:
    #        「2025Q4 浦东多少分」   → 答案是一个数  → 期次是【答案的一部分】
    #        「2025Q4 为什么调整…」  → 答案是一段原文 → 期次只是【查哪一期的条件】
    #      ★ 所以判据不是"句子里有没有 2025Q4",是【期次在问题里是什么角色】。
    ("CAPSE 2025Q4 报告里，测评指标为什么调整过", False,
     "★ 干扰项:句子里写着 2025Q4,但主角是「为什么」—— 期次只是查哪一期的条件"),
]


# ══════════════════════════════════════════════════════════════════
#  ★★★ 旧牌子(改之前那一版)—— 留着是为了做对照
#
#  【为什么要留一个旧版】实测踩到的:
#      我【同时】改了两样 —— 改牌子 + 加了一句干扰项。
#      结果干扰项过了。而那是【哪一样】让它过的?分不出来。
#
#  ★ 所以把旧牌子留下来,拿【同一句】跑两遍:
#      旧牌子 + 干扰句 → 若选中抽期次,说明旧牌子确实会抢错活
#      新牌子 + 干扰句 → 若没选,那【改牌子】这一步值多少就有了数
#
#  ★★ 这和"每轮结果另存带轮次名"是同一条纪律:
#     不留下对照,你就只会看到一个好结果,而不知道它是【因为什么】好的。
# ══════════════════════════════════════════════════════════════════
旧牌子_抽期次 = (
    "问题里【直接写着】某一期或某几期的编号时用我,"
    "写法长得像「2025Q4」「2023Q3」。"
    "★ 注意:我只能认这种固定写法。"
    "如果问题是「近两期」「去年」「上一期」这种说法,"
    "我【认不出来】—— 那种情况不要指望我,要先去别处把期次定下来。"
)


def ask_model(q, 用旧牌子=False):
    """把说明书递给模型,让它挑。返回它选的工具名(或 None)。"""
    from llm import chat
    牌子 = "\n".join(
        f"- {t['名字']}:"
        f"{旧牌子_抽期次 if (用旧牌子 and t['名字'] == '抽期次') else t['什么时候用']}"
        for t in TOOLS)
    prompt = f"""下面有几个工具。读它们的说明,判断【这一个问题】该用哪个工具。

工具:
{牌子}

问题:{q}

只回答工具名,不要解释。如果这个问题【不应该】用其中任何一个,回答「都不用」。"""
    return chat(prompt, max_tokens=20).strip()


def main():
    print("=" * 78)
    print("  第 15 课 · 试牌子:把说明书递给模型,看它挑不挑得对")
    print("=" * 78)
    print(f"\n  {len(CASES)} 句问法({sum(1 for _,w,_ in CASES if w)} 句该找,"
          f"{sum(1 for _,w,_ in CASES if not w)} 句不该找)\n")

    right = 0
    for q, 该找, 为什么 in CASES:
        选 = ask_model(q)
        #  ★ 判据:它选了「抽期次」= 该找;选了别的或"都不用" = 不该找
        真选了 = "抽期次" in 选
        对 = (真选了 == 该找)
        right += 对
        print(f"  {'✅' if 对 else '❌'} {q}")
        print(f"       期望:{'该找' if 该找 else '不该找'}  "
              f"实际:{'找了' if 真选了 else '没找'}(它答「{选}」)")
        print(f"       理由:{为什么}")
        print()

    print("=" * 78)
    print(f"  {right}/{len(CASES)} 对")
    print("=" * 78)
    print("""
  ★ 打 ❌ 的那些,就是【牌子写得不好的地方】—— 那才是要改的。
    两个方向含义不同:
      · 该找却没找 → 牌子写窄了(或者"什么时候用"里条件太严)
      · 不该找却找了 → ★★ 更危险:它会抢别人的活,而且抢错了你看不见
""")


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    main()
