"""比一比 —— 专门量【比较类】问题:两条路给不给结论,给的一样不一样。

═══ 为什么需要单独一把尺子 ═══
    比较题的答案是【一个判断】(谁高 / 差多少),不是【一堆数】。
    ★ 而"给了两个数"和"给了结论"在打印上【几乎一样】——
      两条 4.23 / 4.28 摆着,看起来就是答了。
    ★★ 所以这个项目一路在打的静默失败,在比较题上有一个很具体的形状:
       「数都查到了,而没比」。
    ★★★ 光靠眼睛看打印【分不出来】—— 要一把只问一件事的尺子:
        「这一条答案里,结论出现了没有?」

═══ 尺子怎么量 —— 对着【要件】勾,不审自己答得对不对 ═══
    每题先写好要件(几个必须出现的东西,用正则写),然后往上勾。
    ★ 这是【覆盖清单】那个方法,不另造一套判法:
        审自己答得对不对 → 看着完整、有出处 → 没理由打回
        勾要件           → 缺的那条【藏不住】
    ⚠ 要件【也是我写的】,所以它也会写错 ——
      所以每题都把【期望答案】一起写在文件里,改的时候一眼能看到对不对。

═══ 配对:同一句话,两种说法,逼它走两条路 ═══
        「…和…谁高」      (没逗号) → 老路
        「…和…，谁高」    (有逗号) → 计划路
    ★ 这两句【问的是同一件事】,所以两条路的答案【必须一样】。
      ★★ 不一样 = 又是"同一条规则只装一条路"。
      ⚠ 而这一对是【故意造的】:不造它,两条路的差异【永远不会自己露出来】。

用法:
    python tools/比一比.py              # 全跑
    python tools/比一比.py --只跑 甲    # 只跑某一组
"""
