#
#     ⚠ 只覆盖【两种】—— 都是手上【有真实案例】的。
#       没有案例的(编数字、编出处)先不接:接了也不知道写对没有。
#
#  ★★★ 循环【能容纳两种动作形态】,这是有意设计成这样的:
#
#     「再来一轮」型 —— 换个输入,再生成一次
#        用于【说不清哪一步出的问题、只能再赌一次】的情况。
#        ★ 它靠赌,所以有上限(MAX_RETRY)。
#
#     「一次到位」型 —— 算出来补上
#        用于【失败原因清楚、而且能算】的情况。
#        ★★ 它不赌 —— 算出来就确定,所以补完就结束,不进下一轮。
#
#  ⚠⚠ 但截至 2026-09-22,【在用的只有「一次到位」这一种】——
#      「再来一轮」那一种写出来过,后来实测发现它的依据作废、而且有风险,删了。
#      详见下面 RETRY_PLAN 里那段注释。
#      ★ 所以:架子留着(能容纳两种),但【只有一种被验证有效】。
RETRY_PLAN = {
    "分档排名漏了":     ("算出补上", "一次到位"),

    #  ★★★ 2026-09-22 扩:"编"那三类的动作 —— 都是【再生成一次】。
    #
    #     【为什么那可能有用】生成是【抽样的】:第 11 课量过,
    #       同一件事跑两次结果会不一样(题45 那次 20%、题47 那次 4/10 和 6/10)。
    #       所以"编了"再生成一次,可能就不编了。
    #     ★★ 而"有没有好"由【硬判据】说,不是它自己说 ——
    #        那就不是"自己给自己盖章"(那是这个项目一路反对的)。
    #     ★★★ 而它是【赌】:可能三次都还编。那说明这个动作对这三类没用 ——
    #        而那也是个结果,要如实报出来。
    "编了数字":     ("重新生成", "再来一轮"),
    "编了出处":     ("重新生成", "再来一轮"),
    "编了机场名":   ("重新生成", "再来一轮"),
    #  ⚠⚠ "说没有而材料里有" —— 【诊断留着,动作删了】。
    #
    #  为什么删(2026-09-22 实测):
    #    它原来的动作是"少给材料,再生成一次"。依据是第 10 课那个实验:
    #        给 1 页 答对 100%  /  给 5 页 答对 20%
    #      → 看起来是"材料太多,它看漏了"。
    #    ★ 但那个实验是在【旧提示词】下做的。加了"每句标出处"之后,
    #      位置效应没了 —— 也就是说,【那个依据已经作废了】。
    #    ★★ 拿当前提示词重新量(检索题,给 5 页 vs 给 2 页,各 5 次):
    #        9 道题:两边一模一样,没差别
    #        题48:给 5 页 5/5,给 2 页 0/5
    #        ★★★ 而那个 0/5 不是"少给更好",是【少给把答案页砍掉了】——
    #             它的材料里答案页排在【第 3 位】,砍到 2 页就没了。
    #
    #  ★★★★ 所以那个动作:依据作废 + 本身有风险 → 删。
    #
    #  ⚠ 但【诊断留着】—— 因为那类失败真的会发生(题45 发生过)。
    #    诊断出来而没有对策时,gen_with_retry 会把这一轮【记进 trace】然后停。
    #    **判不出看得见 —— 至少它出声了。**
}


def _brief(xs, n=2):
    """把判据报出来的东西压成一小段 —— trace 里只放得下这么点。

    ★ 为什么只留 2 个:那一行是给【跑分文件的过程栏】看的,
      太长会把「第几轮」「哪一类」这些真正要紧的字淹掉。
    ★★ 而假警报的教训在这儿:警报多了没人看 —— 记录也一样,长了没人看。
    """
    xs = [str(x) for x in (xs or [])]
    if not xs:
        return ""
    if len(xs) <= n:
        return "、".join(xs)
    return "、".join(xs[:n]) + f"…(共 {len(xs)} 个)"


def diagnose(a, q, kw, hits, airports=None):
    """这一轮【失败在哪一类】?返回 (类型名, 具体是什么),没失败就是 (None, "")。

    ★ 它只做【诊断】,不做动作 —— 诊断和动作分开,
      是因为同一类失败在不同情况下该有不同对策,而诊断的判据不变。

    ★★ 查的顺序有讲究:
       ① 先查"说没有"—— 如果它答了"材料里没有",那"漏了并列"也必然成立
          (什么都没答),那时该按【更根本】的那一类处理。
       ② 再查"漏了/编了" —— 那几类【互斥性不强】,
          但这个顺序让"漏"优先于"编"(漏更常见,而且动作更强)。

    ⚠ 它只跑【硬判据】那几道,不叫大模型 —— 见上面那两条业界结论:
      反馈信号锚在真值校验上,比模型自己的判断强得多。

    ═══ ★★★ 2026-09-22 扩:从 2 类扩到 5 类 ═══
        原来只认"说没有"和"漏了并列"两种 —— 而【能算的失败类型】还有三种:

            编了数字      audit_answer    能判
            编了出处      check_citations 能判
            编了机场名    check_entities  能判

        ★ 那三类的判据【早就写好了】,只是没给它们配动作 ——
          于是循环碰到它们的时候只会"停",不知道该做什么。
        ★★ 而"自主规划"最朴素的样子不是让它自己想,
           是【它能自己处理更多情况】。所以:把覆盖面接上。

    ═══ ★★★ 2026-09-22 加"具体是什么" ═══
        原来只返回类型名,于是 trace 里长这样:

            第1轮:材料5页 → ★ 编了机场名

        ★ 而【编的是哪一个机场】没记下来 —— 于是事后【分不清它是真编还是判据误报】。
        ★★ 实测踩到:第42题问的是"一级指标有哪些",和机场名毫无关系,
           却报了「编了机场名」。而那一轮的原文没留下 → **永远查不清**。
        ★★★ 一行改动,把每一次 trace 从"一条线索"变成"一份证据"。
    """
    m = check_missed(a, kw, hits)
    if m:
        return "说没有而材料里有", _brief(m)
    r = check_ranked_answer(a, q, hits)
    if r:
        return "分档排名漏了", _brief(r)
    #  下面三类是"编" —— 判据都是硬的。
    #  ⚠ airports 是可选的:不传就跳过机场名那一条(旧调用方还用不着它)。
    bad = audit_answer(a, hits)
    if bad:
        return "编了数字", _brief(sorted(bad))
    gc = check_citations(a, hits)
    if gc:
        return "编了出处", _brief(sorted(gc))
    if airports:
        ge = check_entities(a, hits, airports)
        if ge:
            return "编了机场名", _brief(ge)
    return None, ""


def gen_with_retry(q, kw, hits, airports=None, notes=None):
    """生成 → 诊断 → 做对应的动作 → 再看结果。★ 第 12 课。

    ★ 和"盲目重试"的区别:每一轮都先看【是哪类失败】,再做【对应的】动作。
    ★★ 返回 (最终答案, 过程记录) —— 过程要留着,不然看不出它试了什么。

    ⚠ 它【改不了】检索 —— 当前的动作只是"补"(把算出来的补进答案)。
      所以"换检索词""改材料量"那些动作这里做不了(要重走检索,另说)。
      ★ 而"改材料量"那一种【试过、删了】—— 见 RETRY_PLAN 里的注释。
    """
    h = list(hits)
    trace = []
    a = ""
    for attempt in range(1, MAX_RETRY + 1):
        a = gen_answer(q, h, notes=notes)
        kind, why = diagnose(a, q, kw, h, airports)
        #  ★ why 是"编的是哪一个"—— 有它,trace 才是一份证据而不是一条线索。
        trace.append(f"第{attempt}轮:材料{len(h)}页 → " +
                     (f"★ {kind}「{why}」" if kind else "通过"))
        if kind is None:
            break
        plan = RETRY_PLAN.get(kind)
        if plan is None:
            #  ★ 诊断出来了,但【这一类没有对策】→ 停。
            #    而 trace 里已经记下了它是哪一类 —— 至少它【看得见】。
            break
        action, _form = plan
        if action == "算出补上":
            #  ★ 一次到位:补完就结束,不进下一轮 ——
            #    因为它不是靠再赌一次,是靠算。
            a = supplement_ranked(a, q, h)
            trace.append("  └ 已【算出来补上】(不重试 —— 能算的别问大模型)")
            break
        if action == "重新生成":
            #  ★★ 什么都不做 —— 让循环继续,下一轮重新 gen_answer。
            #     而"有没有好"由硬判据在【下一轮的 diagnose】里说,
            #     不是它自己说 —— 那就不是"自己给自己盖章"。
            #  ⚠ 它有上限(MAX_RETRY):三次都还编,就带着【最后那一版】出去。
            trace.append("  └ 【重新生成】(赌一次 —— 生成是抽样的)")
            continue
        break
    return a, trace
    #  ⚠ 这一行被我删过一次(2026-09-22):删分支的时候,把函数末尾的 return
    #    一起删掉了。函数返回 None → 上层解包报错 → 【15 道检索题全挂,45/60】。
    #  ★ 而那个错被 except 抓走,没报出来 —— 我只看到分数掉了。
    #  ★★ 教训:改完函数【先冒烟测一道】,再跑全量。那次我没测就跑了。


def check_entities(ans, hits, airports):
    """回答里出现的【机场名】,是不是都在给它的材料里?返回材料里没有的那些。

    ═══ 它补的是哪个盲区 ═══
        audit_answer 只核【数字】,不核【名字】。
        ★ 所以"编了一个材料里没有的机场"这件事,之前【没有任何检查】。
        ★★ 而它比编数字更危险 —— 用户看到一个具体机场名,更容易信。

    ═══ 为什么只核机场名,不核所有专有名词 ═══
        "CAPSE""民航局""飞常准"这类机构名,回答里提到是【常识性提及】,
        它们不一定出现在那 5 页材料里。
        ★ 核它们会一路报假警报 —— 而"假警报多了,真警报就没人看了"。

    ═══ 实测(2026-09-22,15 道检索题)═══
        报 0/15 —— 不误报。但也没抓到东西,因为系统此刻没编。
        ★ 所以它是【兜底】:平时不响,出事才响。

    ⚠ 它抓不到"张冠李戴":把 A 机场的分数说成 B 机场的 ——
      两个名字都在材料里,所以这条判据看不见。

    ═══ ⚠⚠ 第一版有个【反直觉的洞】,实测踩到(2026-09-22)═══
        第一版的判据是:"拿【库里已知的机场名单】去核回答"。
        ★ 而它正好漏掉最危险的那种编:

            模型编了"桂林两江国际机场"(库里没有这个机场)
            → 核对名单里没有它 → 【永远抓不到】→ 报 []

        ★★ 也就是说:编一个【真实存在的机场】能抓到,
            编一个【根本不存在的】反而抓不到。
        ★★★ 又是"量具只覆盖它覆盖的地方" —— 而这次覆盖不到的那块,恰好最该抓。

    ═══ 现在改用的判据 ═══
        找回答里【形如"XX机场"的片段】,不管它在不在库里 —— 只问"在不在材料里"。
        ★ 那个正则项目里早就有了(AIRPORT_LIKE,unknown_airport 也在用)。
        ★★ 泛指要滤掉:"哪些机场""这个机场"那种不是具体名字。
    """
    材料 = "".join(h["文本"] for h in hits)
    out = []
    for m in AIRPORT_LIKE.finditer(ans or ""):
        w = m.group(0)
        if is_generic_airport(w):
            continue                      # 泛指,不是点名
        if w not in 材料:
            out.append(w)
    return out


def check_missed(ans, kw, hits):
    """它说"材料里没有" —— 可材料里【真的】没有吗?

    ═══ 为什么要有这一道 ═══
        第 10 课开头,#45 就是这样:它说"材料里没有",
        而 2025Q3-P11(答案页)【就在给它的 5 页里,排第 2 位】。

    ★ 这是"防漏",和 audit_answer/check_citations 那两个"防编"是两回事:
         防编 → 回答里有材料里【没有】的东西
         防漏 → 材料里【有】、而回答说没有
      **两个是不同的病,要两道检查。**

    ═══ 判据(纯代码,不调大模型)═══
        它说了"没有" + 检索词能在材料里找到  →  ★ 漏了,要出声

    ★★ 为什么用检索词搜、而不是逐字读材料:
       检索词是【系统自己为这个问题生成的】,拿它去搜材料是硬的、可复现的。
        而"材料里到底有没有答案"需要理解语义 —— 那又回到大模型,会自己给自己盖章。

    ★★★ 它保证的有限:搜得到不等于"答案一定在里面"(可能只是个同名词)。
        但【搜都搜不到 → 它说没有是对的】—— 这一半是硬的。
        所以它只会在"搜到了"时出声,那是【宁可误报,不可漏报】那一侧。
    """
    if not NONE_PAT.search(ans):
        return None                      # 它没说没有 → 这道检查不适用
    mat = "".join(h["文本"] for h in hits)
    found = [t for t in (kw or "").split() if len(t) >= 3 and t in mat]
    return found or None


def check_citations(ans, hits):
    """回答里标的出处,是不是【真的在给它的材料里】?返回编的那些。

    ★★ 这道检查和 audit_answer 不一样,而且更硬:
        audit_answer 核的是【数字】—— 数字可能恰好在别处出现过,它判不准。
        这一道核的是【出处编号】—— 那个编号是系统自己发的,
        ★ 材料里没有 = 它编的。**没有中间地带。**

    ★ 为什么这道检查值:
        没有出处时,"这句话对不对"只能靠字面匹配猜 —— 而生成层【本来就要重组材料】,
        重组过的句子字面上找不到,于是被误判成"没据"。
        ★★ 标了出处,校验就从【猜句子】变成【核对编号】—— 从模糊变硬。

    ⚠ 它保证的和 audit 一样有限:只保证"出处是真的",
      不保证"这句话真的来自那一页"。**它是把"完全没查"变成"查了一道"。**
    """
    have = {h["chunk_id"] for h in hits}
    bad = set()
    for m in CITE.finditer(ans):
        for cid in CID.findall(m.group(1)):
            if cid not in have:
                bad.add(cid)
    return bad


