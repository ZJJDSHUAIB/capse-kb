WHOLE = re.compile(r'综合得分|综合评分|综合分|总分|总评分|总得分|整体得分|整体分')
VAGUE = re.compile(r'(?<![\u4e00-\u9fff])得分|的得分|是多少分|多少分|分数')
RANK  = re.compile(r'排名|名次|第几|第\s*\d+\s*名|前\s*\d+')
CMP   = re.compile(r'哪[个家]|谁|相差|差距|变化')


class CannotAnswer(Exception):
    """认不出用户在问什么。

    ※ 它和"查不到"是两回事,必须分开:
        查不到  → 路走了,库里没这个数据      → 这是【库里没有】
        认不出  → 我压根不知道他在问哪个字段  → 这是【我不认识】
      改之前这两件事都不出声,而且都变成"答综合得分" —— 于是用户分不清。
      第 3 课那条:"查不了 ≠ 查了没有"。这里是它的第三次出场。
    """

# 「没说问什么」的问法:用户在问'整体',但没点名任何字段。
#   ※ 实测踩过:「2024Q3合肥新桥国际机场表现如何啊」被我的第一版关卡【拒了】,
#     而答案键写的是「综合得分:4.04」—— 也就是出题人认为这题该答综合得分。
#   → 「没说问什么」和「说了但我不认识」是【两件事】,第一版把它们当成了同一件:
#         「表现如何」    → 没说 → 给默认(综合得分),但要【说清这是默认】
#         「靠桥率得分」  → 说了,而我不认识 → 【拒答】
#     区别在【有没有点名一个字段】,不在'像不像在问分'。
VAGUE_ASK = re.compile(r'表现|如何|怎么样|怎样|情况')


# ══════════════════════════════════════════════════════════
#  ★ SQL 这条路的「认不出就出声」—— 挑战集 C1/C2 逼出来的
# ══════════════════════════════════════════════════════════
#  挑战集实测,这两类现在【一声不吭】:
#
#      C1  「2025Q4上海浦东国际机场的【靠桥率】排名第几」
#            → 答「综合得分 4.23,排名第 5/42」          用户以为那是靠桥率的排名
#      C2  「2025Q4【合肥骆岗机场】综合得分是多少」
#            → 答「前 5 名:北京大兴 4.28、深圳宝安 4.27…」 用户问一个机场,拿到一张榜
#
#  ★ 而这两类【都是静默的】:格式对、数字真、有出处,就是答的不是那个问题。
#
#  ★ 为什么"拒答"而不是"报警"(这是个判断,不是随手选的):
#       拒答  「不回答。『靠桥率』我这儿没有。」              → 用户什么都没拿到
#       报警  「综合得分 4.23,排名第 5/42」+ ★「靠桥率我没有」 → 拿到了,但可能不是他要的
#
#    「浦东的靠桥率排名第几」是【单一意图】—— 用户只要靠桥率。
#     给他综合得分排名不是"给了点能给的",是【给了别的东西】。
#     → 所以拒答。**宁可不答,不可答错。**
#
#  ⚠ 这两条判据【也是表,也会漏】—— 但它们和"兜底那一格"的区别是:
#     兜底的错是【有把握地答错】;这两条的错是【说不出声】(保守)。
#     同一课定的取舍:漏了 → 出声变少(看得见),而不是 → 答错变多(看不见)。
# ★ 第 2 版(题 57 逼出来的):定位词从「的」扩成「的|里|中|内」。
#   第 1 版要求必须先有一个「的」—— 而「2023Q3报告【里】有效样本量是多少」没有「的」,
#   于是那条检查【根本没跑】,题目一路走到兜底,答了一段概况。
#   **同一种病:判据写窄了,而漏掉的时候【静默】。**(这一课第五次)
NAMED_METRIC = re.compile(r'(?:的|里|中|内)\s*([\u4e00-\u9fff]{2,6})(率|度|值|量|务|保障|设施|得分|分数)')


def known_names(con, indicators):
    """系统能答的东西 = 一级指标 ∪ 库里所有表的【列名】。

    ★ 为什么不能只用 indicators(这是第 2 版才想明白的):
        「样本量」「机场数」「综合得分」—— 都【不在】一级指标表里,
        但系统【答得出】它们。
      用 indicators 当"已知",会把能答的题拒掉 —— **把"已知"定义得太窄,
      和把判据写窄是同一个病,只是换了个地方。**

    ★ 而从【列名】生成,不是手写一张表:
        库里有 meta(样本量/机场数/一级指标数/二级指标数)、
        综合得分(得分)、指标得分(指标/得分)、机场分档(档位/行业平均)…
      **列名就是"这个系统能说出名字的东西"的定义。它随库变,不用人维护。**
    """
    # ★ 加上系统的【固定答案名】——它们不是列名,但系统答得出。
    #   测过:「浦东的【综合得分】是多少」—— 有「的」→ 会被 NAMED_METRIC 抽到,
    #   而「综合得分」不在列名里(列名只有「得分」)→ 会误拒。上一版就差点搅乱。
    names = set(indicators) | {'综合得分', '综合评分', '综合分', '总分',
                              '总评分', '总得分', '整体得分', '整体分', '得分情况'}
    for (t,) in con.execute("SELECT name FROM sqlite_master WHERE type='table'"):
        try:
            names |= {r[1] for r in con.execute(f"PRAGMA table_info({t})")}
        except Exception:
            pass
    return names


# ★ 元问题:问的是【系统内部怎么处理的】,不是报告里写了什么。
#   题 57 的第二问「为什么第6页没进库」—— 这个系统答不了那个。
#   它只回答"报告里写了什么";**"我内部怎么切的"不是报告内容,是我的实现细节。**
META_Q = re.compile(r'进库|入库|切片|没进|未入库|不在库里|收录|没收录')
AIRPORT_LIKE = re.compile(r'([\u4e00-\u9fff]{2,6})机场')
#  泛指,不是具体机场名 —— 这些不该被当成"认不出的机场"
#  ⚠⚠ 2026-09-22:原来这里是一张【枚举表】,而枚举永远漏 ——
#     实测:答案里"这些机场综合得分前 5 名"的「这些机场」不在表里
#     → check_entities 把它当成"材料里没有的机场名"报了假警报。
#  ★ 改成【按特征认】,分头尾两类:
#       头:这/那/该/各/某/每/全/所(指示代词或量词开头 —— 真机场名不会这么开头)
#       尾:含疑问词
#  ★★ 而底下 unknown_airport 里抄了同一套判断 —— 现在【合成一个函数】。
#     那正是这个项目一路在治的病:"同一个判断写两遍,迟早不一致"。
GENERIC_AIR_HEAD = re.compile(r'^(?:这|那|该|各|某|每|全|所|几|多)')
GENERIC_AIR_ASK  = re.compile(r'哪些|什么|多少|几个|哪家|哪几|几家')

#  ⚠⚠ 第三条判据(2026-09-22 加):前缀里出现【虚词】的,不是地名,所以不是机场名。
#
#     实测踩到的假警报:
#         答案是「…一级指标6项,分别为机场交通、机场服务与设施、…」
#         而正则 ([一-鿿]{2,6})机场 从「分别为机场交通」里【切出了「分别为机场」】,
#         报成"编了一个材料里没有的机场"。
#         ★ 而「机场」在这里是【列表项的开头】,不是名字的结尾 —— 正则分不出来。
#         ★★ 实测代价:第42题三轮都被它拦住,白重试 3 次(用 rounds 数出来的)。
#
#     判据:**中国的机场名以地名开头,而地名不会以虚词结尾。**
#         分别为 → 含「为」 → 不是地名 → 跳过 ✅
#         桂林两江 → 无虚词 → 是地名 → 留着 ✅
#
#     ★★★ 而这条是【验过的】,不是拍的:
#         拿库里全部 43 个机场名逐个过,【零误伤】。
#         (第一版把「和」也放进去了 → 呼和浩特白塔国际机场被误伤 → 拿掉「和」。
#          所以这份字表里【没有「和」】—— 那个字在地名里太常见,当不了判据。)
#     ⚠ 它是【代理判据】,不完美:一个真叫"某某为"的地名会被它跳掉。
#       写在这里,是因为"跳过一个没人这么起名的"比"天天误报"划算得多。
GENERIC_AIR_FUNC = set('的了与及或为是在有从对把被而且也就还很更最等各该这那其之所以于由因但只又将总并则')


def is_generic_airport(w):
    """这个"XX机场"是【泛指】,还是在【点名一个具体机场】?

    ★ 泛指不该被当成"认不出的机场名",更不该被当成"编出来的机场名" ——
      否则满屏假警报,而【假警报多了,真警报就没人看了】。
    """
    return bool(GENERIC_AIR_HEAD.match(w) or GENERIC_AIR_ASK.search(w)
                or (set(w[:-2]) & GENERIC_AIR_FUNC))


# ══════════════════════════════════════════════════════════
#  ★ 「拒答也要有用」—— 张君杰的要求:"不要让系统太死板"
# ══════════════════════════════════════════════════════════
#  他的原话是在我刚加完 C1/C2 那两条"认不出就拒答"之后说的。
#  **而我那两条恰恰是最死板的:**
#
#      用户:「浦东的靠桥率排名第几」
#      回答:「不回答。你问的『靠桥率』不是这里的指标,我没有它的数据,不猜。」
#
#  两个"不回答"开头,一句解释,没了。**用户读完还得自己想办法。**
#
#  ★ 而"行李服务"那条尤其糟 —— 它在 2025Q1 之前【是有的】,被换成了出港/进港服务。
#    那件事【库里知道**(P07 的多版本就写着),而系统只说了"我没有"。
#
#  ═══ 底线(不能破)═══
#     给候选 ≠ 答那个候选。
#     **系统还是拒答** —— 只是说"我搜到了这些,你看是不是你要的"。
#
#    这一条守的是第 4 课那条:拒答是因为【回答不了】,不是因为【不想答】。
#    给提示不改变"回答不了"这个事实,只是让用户知道下一步往哪走。
#
#  ⚠ 提示里的每一条都是【搜出来的事实】,不是我猜的:
#      "在哪些期出现过"   → 从 chunk 里搜出来的
#      "看着最接近的"     → 字符串相似度,而且要够像才给
#    **不够像就不给** —— 不给候选好过给错候选。
NEAR_CUT = 0.45          # 相似度门槛。量出来的:「行李服务」对「出港服务」是 0.50,
                         # 「靠桥率」对任何指标是 0.00。门槛设在 0.45 ——
                         # 刚好放过有用的,挡掉"一个都不像"的。


def _ratio(a, b):
    import difflib
    return difflib.SequenceMatcher(None, a, b).ratio()


def hint_metric(con, word, indicators):
    """认不出的指标 → 给【事实性提示】。全是搜出来的,不猜。"""
    out = []
    rows = con.execute("SELECT DISTINCT 期次 FROM chunk WHERE 文本 LIKE ?",
                       (f'%{word}%',)).fetchall()
    if rows:
        pers = sorted(r[0] for r in rows)
        if len(pers) == 1:
            out.append(f"我搜到「{word}」在 {pers[0]} 的报告里出现过 —— 那你要的是那一期吗?")
        else:
            out.append(f"我搜到「{word}」在 {pers[0]}~{pers[-1]} 的报告里出现过 —— "
                       f"那你要的是那几期吗?")
    near = [x for r, x in sorted(((_ratio(word, x), x) for x in indicators),
                                 reverse=True)[:3] if r >= NEAR_CUT]
    if near:
        out.append(f"(要说最像的,是 {'、'.join(near)} —— 但那不是我该替你换的。)")
    if not out:
        out.append(f"库里现有的指标是:{'、'.join(sorted(indicators))}")
    return out


def hint_airport(con, word, airports):
    """认不出的机场 → 给【同城的机场】。同城是搜出来的,不是猜的。"""
    out = []
    #  取这个词里的前 2 字当地名(「合肥骆岗机场」→「合肥」)—— 够用,而且保守
    city = word[:2]
    same = sorted({v for v in set(airports.values()) if city in v})
    if same:
        out.append(f"库里{city}的机场有:{'、'.join(same)} —— 你要的是其中一个吗?")
    else:
        near = [x for r, x in sorted(((_ratio(word, x), x) for x in set(airports.values())),
                                     reverse=True)[:3] if r >= NEAR_CUT]
        if near:
            out.append(f"(要说最像的,是 {'、'.join(near)} —— 但那不是我该替你换的。)")
    if not out:
        out.append("(库里没有名字接近的机场 —— 那可能就是个没收录的机场。)")
    return out


def unknown_metric(q, known):
    """问句里有没有【点名了一个指标,而它不在这儿】?

    ※ 抽法:取「的」字后面的名词,要求它以度量词结尾(率/度/值/量/务/…)。
      「浦东国际机场的靠桥率排名第几」→ 抽「靠桥率」→ 不在指标表 → 认不出
      用贪婪匹配:「的旅客满意度」要抽成【旅客满意度】,不能抽成【旅客度】。
    """
    for m in NAMED_METRIC.finditer(q):
        full = m.group(1) + m.group(2)      # 抽出来的整个词,如「机场安检得分」
        if full in known:
            continue
        # ★ 去掉【尾部的度量词】再看一次(实测踩的坑):
        #     「机场安检得分」→ 去掉「得分」→「机场安检」→ 在已知里 ✅ → 不该拒
        #     「有效样本量」  → 去掉「量」  →「有效样本」→ 不在      → 该拒 ✅
        #     「靠桥率」      → 去掉「率」  →「靠桥」    → 不在      → 该拒 ✅
        #   **不这么做的话,「浦东的机场安检得分是多少」会被误拒** ——
        #   而那道题系统答得出来。这是这一课第一次出现【误拒】。
        if m.group(1) in known:
            continue
        return full
    return None


#  ★ 档位词:"4000万级" / "2500万-4000万级" / "1500万级以上"
TIER_Q = re.compile(r"(\d{4}万(?:-\d{4}万)?级(?:以上)?)")


def find_tier(q, tiers):
    """问句里的【档位词】,对应库里的哪一档?返回标准档位名,或 None。

    ═══ 为什么需要它(2026-09-22,挑战集逼出来的)═══
        挑战集里有四道【同一类】的问题:

            2025Q4里,4000万级以上是多少    → 路由判【SQL】→ ★ 拒答
            2025Q4里,2500万级是多少       → 路由判【SQL】→ ★ 拒答
            2025Q4里,4000万级是多少       → 路由判【SQL】→ ★ 拒答
            2025Q4的1500万级说的是什么     → 路由判【判不出】→ 走检索 → ✅ 答对

        ★ 同一类问题,只因为问法差一个字,走了两条路 ——
          而一条路认它、另一条不认。
        ★★ 而这正是这个项目的老毛病:「同一条规则只装在一条路上」。

    ═══ 判据:标准档位里,【以这个档位词结尾】的那个 ═══
        "1000万-1500万级".endswith("1500万级") → ✅
        "1500万-2500万级".endswith("2500万级") → ✅
        "2500万-4000万级".endswith("4000万级") → ✅
        "4000万级以上"   ==     "4000万级以上"  → ✅

    ★★ 为什么用"结尾"而不是"包含":挑战集用的是简称 ——
       "1500万级" 其实是 "1000万-1500万级",简称取的是后半截。

    ★★★ 而【必须唯一】才算认出来 —— 我逐个验过这四条,都唯一。
        如果哪天出现一个词对上两档,那就不猜(返回 None)。
        **宁可说认不出,不可猜一个。**
    """
    m = TIER_Q.search(q or "")
    if not m:
        return None
    w = m.group(1)
    hit = [t for t in tiers if t == w or t.endswith(w)]
    return hit[0] if len(hit) == 1 else None


def unknown_airport(q, airports_in_q, airports=None):
    """问句里有没有【像机场名、但一个都没认出来】的?

    ※ 判据:问句里有「XX机场」这样的片段,而 find_airports 一个都没认到。
      「合肥骆岗机场」→ 认不出 → 出声
      「哪些机场」  → 泛指,不算
    """
    if airports_in_q:
        return None                       # 认到了,这一层的问题就不存在
    for m in AIRPORT_LIKE.finditer(q):
        w = m.group(0)
        # ★ 泛指判断【和 check_entities 共用一个函数】—— 理由见那边的注释。
        #    「综合得分前 5 名是哪些机场」→ 正则贪婪,把「名是哪些机场」整个吃了
        #    → 报「『名是哪些机场』不在库里」,而那题系统答得出来。**误拒。**
        if is_generic_airport(w):
            continue
        # ★★ 最要紧的一道(实测踩过一次,误拒了 4 道正式题):
        #    「国际及港澳台地区机场」「4000万级以上机场」也会被抽出来,
        #    而它们是【泛指】—— 一个地区/一个吞吐量级里的所有机场。
        #    判据:**前 2 字必须是库里某个机场名的前 2 字。**
        #      合肥骆岗机场 → 「合肥」→ 库里有「合肥新桥」 ✅ 具体机场
        #      北京南苑机场 → 「北京」✅   上海龙华机场 → 「上海」✅
        #      及港澳台地区机场 → 「及港」❌   万级以上机场 → 「万级」❌
        #    理由:**中国的机场名几乎都以城市名开头,而"国际""万级"不是城市。**
        #    实测 7/7 全对(3 个该拒的全拒,3 个泛指的全不拒,1 个没抽到)。
        if airports and w[:2] not in {v[:2] for v in airports.values()}:
            continue
        return w
    return None


def _pdf(p):
    """把 `2025Q4-P09` 写成 `2025Q4 第9页`。

    ★ 为什么必须区分(第 8 课快收尾时查出来的):
        回填的那个编号【不是 chunk_id】,它是 **PDF 页码**。
        两者长得一模一样, 但含义不同:
            用户拿它翻 PDF      → ✅ 有效(页码是对的)
            程序拿它找 chunk    → ❌ 找不到(数据页没进库)
        实测:综合得分表里 9 个来源,**库里一个都没有**。

        ★★ **格式产生的歧义,比缺信息更危险** ——
           一个假的 chunk_id 会让人以为能程序化追溯。
        而这正是那条规矩的应用:「格式该迁就人,只要不产生歧义」
        —— 这里恰恰产生了歧义。
    """
    m = re.match(r"(\d{4}Q\d)-P(\d+)", str(p or ""))
    return f"{m.group(1)} 第{int(m.group(2))}页" if m else str(p or "")


def asks_overall(q, airport):
    """兜底那一格该不该收它?

    返回 None           → 不该收 → 调用方抛 CannotAnswer(拒答)
    返回 ''             → 该收,而且用户自己说清了,不用解释
    返回 '...'          → 该收,但这是【我替他选的默认】—— 这句要带给用户

    ※ 「几项指标」「指标最高」那种问法【不在这里判】—— 它们走上面那些分支,
      根本到不了这一步。这个方法只回答一件事:**兜底那一格该不该收它。**

    ⚠ 位置很关键:它在 answer_sql 的 else 上,不在 ask() 里 ——
      放 ask() 里会拦在所有分支前面,把 meta 能答的题也拒掉(实测踩过)。
    """
    if WHOLE.search(q) or VAGUE.search(q) or RANK.search(q):
        return ''                       # 用户自己说了:总分 / 名次
    if airport and CMP.search(q):
        return ''                       # 两个机场在比,比什么没说 → 默认综合得分
                                        #   (题 55「哪个好」走这里)
    if VAGUE_ASK.search(q):
        return '你没点名要哪个指标,我按【综合得分】答。'
    return None                         # 认不出 —— 不猜


def pair_period_airport(q, periods, airports_in_q):
    """把【期次】和【机场】按它们在问句里出现的先后配对。

    ★ 为什么必须配(题 9 逼出来的,而且是我修上一个 bug 时【修出来的新 bug】):

      改之前只认一个机场 → 答了"同一个机场两个期",丢了另一个机场。
      我把它改成"按所有机场各查一次" → 变成 2期次 × 2机场 = 4 个格子,然后跨格子比:

          问: 2023Q3南京禄口 和 2025Q2西安咸阳,谁综合得分高
          答: → 2025Q2 南京禄口 更高(4.21 vs 4.09)

      **用户问的是两个【对】:(2023Q3,南京禄口) 和 (2025Q2,西安咸阳)。**
      **我答了另外两个对角线。** 格式对、数字真、有出处 —— 就是答的不是那个问题。
      **又是一次静默。**

    ※ 什么时候才需要配:【两个维度都多于一个】的时候。
        - 2期次 × 1机场(#10 #14 #16 #55)→ 本来就是笛卡尔积,不用配
        - 1期次 × 2机场(#11 #13 #15 #59)→ 同上
        - 2期次 × 2机场(#9)→ **必须配**,否则会出现用户没问的组合
      所以这个函数只在两个都 >1 时才被调用。

    ※ 配对靠【位置】,不靠语义:每个机场,绑到它【前面最近的那个期次】。
      "2023Q3南京禄口国际机场和2025Q2西安咸阳国际机场" ——
      南京禄口前面最近的是 2023Q3,西安咸阳前面最近的是 2025Q2。
      这是中文里说"某一期的某个机场"最自然的写法,够用且不猜。
      ⚠ 边界:如果某个机场前面【一个期次都没有】(期次全写在后面),它绑不到,
        会返回 None —— 那时【不配对】,退回笛卡尔积。**绑不上就说绑不上,不硬猜。**
    """
    if len(periods) <= 1 or len(airports_in_q) <= 1:
        return None
    pp = []
    for per in periods:
        i = q.find(per)
        if i >= 0:
            pp.append((i, per))
    if len(pp) < 2:
        return None
    pairs = []
    for ap in airports_in_q:
        # 问句里可能是全名也可能是简称,都试一下
        i = q.find(ap)
        if i < 0:
            for suf in ("国际机场", "机场"):
                if ap.endswith(suf):
                    i = q.find(ap[: -len(suf)])
                    if i >= 0:
                        break
        if i < 0:
            return None                     # 定位不到 → 不配对,不硬猜
        before = [t for t in pp if t[0] < i]
        if not before:
            return None                     # 前面没有期次 → 绑不上
        pairs.append((max(before)[1], ap))
    # 配出来的对里如果有重复,说明是"一个机场配多个期"这一类 —— 那还是笛卡尔积
    return pairs if len({t for t in pairs}) == len(pairs) else None


#  ══════════════════════════════════════════════════════════════════
#  ★★★ 2026-09-23:「平均」这个量的两个小助手
#
#  ⚠⚠ 平均词 那一个【是临时的】,必须写清 ——
#      它是【一个最小词表】:只认"平均"和"均值"。
#      ★ 而换个说法("同档水平""这一类的均值")它就认不出 ——
#        那正是这个项目一路在治的"补语言现象永远补不完"。
#      ★★ 长久之计是【让改写那一层把说法归到这个量上】(大模型干这个)。
#          先通路,再让说法灵活 —— 因为★路不通时,说法对上了也没用。
#      ★★★ 所以这一条要能被替换掉,而不是越补越长。
# ══════════════════════════════════════════════════════════════════
平均词 = re.compile(r'平均|均值')

#  ══════════════════════════════════════════════════════════════════
#  ★★★ 2026-09-23:「表」那一段 —— 用户要的答案【少了一整段】
#
#  【怎么发现的 —— 用户一句话推翻了我自己标的真值】
#      我标的:«和同档平均比怎么样» = 一个数(档均)
#             «在它那一档里算是什么水平» = 缺路(库里没有)
#      ★ 用户说「我觉得没区别」,并选了答案形态:**先给数,再给表**。
#      ★★ 于是真相是:两句要的是【同一个东西】——
#         而 #1 看起来"答上了"(它给了【数】那段),#8 看起来"答不了"(一段都给不了)
#         ★★★ 其实是【同一句话少了一段】:系统只会给【数】,【表】那一段根本没有。
#      ★★★★ 所以"缺路"不是某一句话的毛病,是【这一类答案少了一段】。
#
#  【★★ 什么时候给表 —— 而这是量出来的】
#      有「多少 / 几」→ 只要数   «比同一档的平均高多少»
#      没有           → 数 + 表  «和同档平均比怎么样» / «算是什么水平»
#      ★ 7/7 —— 但那个真值只有 2 句是用户给的,另 5 句是 AI 推的。
#      ⚠⚠ 所以这条规则【只验了 2 句】,条件记在这。
#
#  【★★★ 表怎么给 —— 用户定的规矩:数据永远摆出来】
#      「这种差距很小的你就把数据摆出来让用户自己判断得了。
#        其他差距大的也就是把数据摆出来,只不过程序自己有判断。」
#      → 差值一律摆出来;★ 差距够大的才多说一句「强项/弱项」。
#      ⚠ 那个门槛(0.01)是【临时猜的】—— 用户说门槛不重要(数据都摆着),
#        但它是猜的,标着。
# ══════════════════════════════════════════════════════════════════
小差门槛 = 0.01


def 逐项同档表(con, 期次, 机场):
    """这个机场这一期，每个二级指标跟同档比 —— 返回要输出的几行。

    ★ 全是 SQL,不用大模型 —— "能算的地方别问大模型"。
    ⚠ 没有分档资料的期次返回 [] —— 那是【没有这条路】,不是算出来 0。
    """
    _t = con.execute("SELECT 档位 FROM 机场分档 WHERE 期次=? AND 机场=?",
                     (期次, 机场)).fetchone()
    if not _t:
        return []
    _档 = _t[0]
    同档 = [r[0] for r in con.execute(
        "SELECT 机场 FROM 机场分档 WHERE 期次=? AND 档位=?", (期次, _档))]
    if len(同档) < 2:
        return []                      # 同档只有它自己 → 没啥好比
    各 = []
    for (指,) in con.execute("SELECT DISTINCT 指标 FROM 指标得分 ORDER BY 指标"):
        自己 = con.execute("SELECT 得分 FROM 指标得分 WHERE 期次=? AND 机场=? AND 指标=?",
                          (期次, 机场, 指)).fetchone()
        if not 自己:
            continue
        _q = ",".join("?" * len(同档))
        均 = con.execute(
            f"SELECT AVG(得分) FROM 指标得分 "
            f"WHERE 期次=? AND 指标=? AND 机场 IN ({_q})",
            (期次, 指, *同档)).fetchone()[0]
        各.append((指, 自己[0], round(均, 3), round(自己[0] - 均, 3)))
    各.sort(key=lambda x: -x[3])
    行 = [f"  它跟同档 {len(同档)} 家逐项比:"]
    for 指, s, m, d in 各:
        if abs(d) < 小差门槛:
            判 = ""            # ★ 差距太小 → 只摆数据,【程序不给判断】
        else:
            判 = "★ 强项" if d > 0 else "弱项"
        行.append(f"    {指}:{s}(同档平均 {m},差 {d:+}){('  ' + 判) if 判 else ''}")
    return 行


def _问的是平均(q):
    """★ 临时的最小词表 —— 见上面那段注释。它该被"改写"那一层替换掉。"""
    return bool(平均词.search(q or ""))


def _档位词(con, q):
    """问句里有没有某个档位词 —— ★ 复用 find_tier,不另写判据。

    ⚠ 第一版写的是 `from route import find_tier` —— 而它【就在本文件里】
      (ask.py:889),于是 ImportError。★ 而这说明一件事:
      加一个新的东西时，要先确认【它是不是已经有了】——
      而"已经有了"和"在哪个文件里"，是两件不同的事。
    """
    档们 = [r[0] for r in con.execute(
        "SELECT DISTINCT 档位 FROM 机场分档 WHERE 档位 IS NOT NULL")]
    return find_tier(q, 档们)


def answer_sql(con, q, periods, airport, indicator, airports_in_q=None,
               indicators=None, airports=None):
    """数值型。返回 (答案行列表, 来源列表)。

    ※ 规则版只能认这几种问法,认不出的走最后的兜底。
      兜底撞墙的地方 = 规则版的边界,故意留着,不和稀泥。
    """
    ps = sorted(periods)
    lines, src = [], []

    # ── meta 类:样本量 ──────────────────────────────
    #  ⚠ 「机场数」也在这张表里(meta.机场数),和样本量同一行 —— 别把它当"不认识"的。
    #    题 8 问「2025Q1机场数是多少」被答成"前 5 名列表",就是因为它没进这个分支、
    #    掉进了下面那个兜底。**这不是"我不认识",是"我知道但没处理这个问法"** ——
    #    两种错要分开治:前者该拒答,后者该补分支。
    if re.search(r'样本量|样本数|机场数|多少家机场|几家机场', q):
        for p in ps:
            #  ⚠ 这张表里还有【一级指标数】【二级指标数】两列,改之前没 SELECT ——
            #    题 2 问"样本量、机场数、一级指标数、二级指标数各多少",
            #    系统只答了前两个。**不是库里有但查不到,是 SELECT 少写了两列。**
            row = con.execute(
                "SELECT 样本量, 机场数, 一级指标数, 二级指标数 FROM meta WHERE 期次=?",
                (p,)).fetchone()
            if row:
                lines.append(f"{p}:样本量 {row[0]:,} 份,覆盖 {row[1]} 家机场,"
                             f"一级指标 {row[2]} 项,二级指标 {row[3]} 项")
                src.append(f"capse.db / meta 表,期次={p}")
        return lines, src

    #  ═══ ★★★ 2026-09-22 加:「总分那类」不是指标,是另一张表 ═══
    #  【为什么 —— 实测改坏的,而且坏得很典型】
    #      第 15 课给 find_indicator 加了"固定答案名"之后,
    #      它开始把「综合得分」也抽出来 → 传到这里 → 查 指标得分 表
    #      ★ 而「综合得分」住在【综合得分表】里,不在 指标得分 表里 ——
    #        所以【查不到】。实测:Agent 评估从 16/19 掉到 13/19,
    #        掉的三道全是问综合得分的。
    #
    #  ★★ 根因:抽参数的那一层认了它,而执行的那一层不认 ——
    #      "参数不经过模型的嘴"还有另一面:【工具抽出的值,下游工具得认】。
    #
    #  ★★★ 所以:"总分那类"→ 当成【没点名指标】,走下面的默认路。
    #        用的判据是上面已经有的 WHOLE —— 不另写一份。
    #  ⚠⚠ 但要【记住这件事】—— 见下面兜底那一段用它的地方。
    #     第一版只是把它设成 None,于是兜底那一段【又从句子里认一遍指标】,
    #     而「那合肥新桥呢」这句里什么都没有 → 认不出 → 抛 CannotAnswer。
    #     ★ 实测症状:连续问时第二句答不出来,而参数里【明明已经有综合得分】。
    参数里点名了总分 = bool(indicator and WHOLE.fullmatch(indicator))
    if 参数里点名了总分:
        indicator = None

    # ── 指标级:只有 2025Q4 有 ────────────────────────
    if indicator:
        for p in ps:
            sql = "SELECT 机场, 得分, 来源 FROM 指标得分 WHERE 期次=? AND 指标=?"
            args = [p, indicator]
            if airport:
                sql += " AND 机场=?"
                args.append(airport)
            # ── ★ 方向(题 56 逼出来的)──────────────────────
            #   改之前【永远 ORDER BY 得分 DESC】,因为默认用户想看好的一面。
            #   但问"哪个机场…最差"时,降序前 5 名里【根本没有那个最低的】——
            #   实测 #56 答的是"航班不正常保障:北京大兴 3.52、上海浦东 3.46…",
            #   而答案是"兰州中川 2.88(最低)"。**数据在库里,只是取反了方向。**
            #   → 问句里有"最差/最低/倒数"这类词 → 升序。
            _asc = bool(re.search(r'最差|最低|最少|最末|倒数|垫底', q))
            _order = "ASC" if _asc else "DESC"
            rows = con.execute(sql + f" ORDER BY 得分 {_order}", args).fetchall()
            if rows:
                _lab = "最低的 5 个" if _asc else "最高的 5 个"
                lines.append(f"{p} {indicator}({_lab}):"
                             + "、".join(f"{r[0]} {r[1]}" for r in rows[:5]))
                _srcs = sorted({r[2] for r in rows[:5] if len(r) > 2 and r[2]})
                src.append(f"capse.db / 指标得分 表,期次={p},指标={indicator}"
                           + (f"  → PDF {'、'.join(_pdf(x) for x in _srcs)}" if _srcs else ""))

    # ── 问"哪项指标最高",但没点名是哪个指标 ────────────
    #    ※ 这一段是补的。补之前,这个问法【掉进了下面的综合得分分支】,
    #      答出来的是 4.23 —— 答案带着来源、格式漂亮、就是答非所问。
    #      静默答错,没人会看出来。这是第 6 个静默失败的样子。
    elif airport and re.search(r'指标', q):
        for p in ps:
            rows = con.execute(
                "SELECT 指标, 得分, 来源 FROM 指标得分 WHERE 期次=? AND 机场=? ORDER BY 得分 DESC",
                (p, airport)).fetchall()
            if rows:
                lines.append(f"{p} {airport} 各一级指标:" +
                             "、".join(f"{r[0]} {r[1]}" for r in rows))
                lines.append(f"  → 最高的是「{rows[0][0]}」{rows[0][1]},"
                             f"最低的是「{rows[-1][0]}」{rows[-1][1]}")
                _srcs = sorted({r[2] for r in rows if len(r) > 2 and r[2]})
                src.append(f"capse.db / 指标得分 表,期次={p},机场={airport},共 {len(rows)} 项"
                           + (f"  → PDF {'、'.join(_pdf(x) for x in _srcs)}" if _srcs else ""))

    # ── 前 N 名(没指定机场时才用) ─────────────────────
    elif not airport and re.search(r'前\s*(\d+)', q):
        k = int(re.search(r'前\s*(\d+)', q).group(1))
        for p in ps:
            rows = con.execute(
                "SELECT 排名, 机场, 得分 FROM 综合得分排名 WHERE 期次=? ORDER BY 排名 LIMIT ?",
                (p, k)).fetchall()
            if rows:
                lines.append(f"{p} 前 {k} 名:" + ";".join(f"第{r}名 {a} {s}" for r, a, s in rows))
                src.append(f"capse.db / 综合得分排名 视图,期次={p}(视图,不存数据)")

    #  ═══ ★★★ 2026-09-23:「平均」是一个【能查的量】,而它一直没接进来 ═══
    #
    #  【为什么加它 —— 实测出来的缺口】
    #      拿五种问法去问"同档平均",【0 种答对】:
    #        「浦东和同档平均比怎么样」  → 答了"浦东 4.23,排名 5/42"  ★ 答非所问
    #        「浦东所在档位的平均分是多少」→ 拒答(认不出指标)
    #        「4000万级以上档位平均分是多少」→ 答了"那一档所有机场的分数" ★ 答非所问
    #        「上海浦东比行业平均高多少」  → 拒答(没有期次)
    #        「哪些机场高于同档平均」      → 拒答(认不出指标)
    #
    #      ★ 而那个数【库里有】:机场分档.行业平均,四个档各一个值(4.05/4.09/4.11/4.13)。
    #      ★★ 所以根因是:【数据在,而没有一条路通向它】。
    #
    #  【为什么单独一条分支,而不是塞进档位那一条】
    #      档位那条答的是"这一档【有哪些机场】",而这条答的是"这一档【平均多少】"——
    #      ★ 两个不同的问题,不该走同一条。
    #
    #  ⚠ 判据(问的是不是"平均")【先用一个最小词表】——
    #     ★★ 而那【不是长久之计】:"均值""同档平均"这些说法会不断冒出来。
    #     长期的做法是【让改写那一层把说法归到这个量上】(见 docs/结论的条件.md)。
    #     先把路通了,再让说法灵活 —— 因为路不通时,说法对上了也没用。
    elif _问的是平均(q) and (airport or _档位词(con, q)):
        _t = None if airport is None else con.execute(
            "SELECT 档位 FROM 机场分档 WHERE 机场=? AND 期次=?",
            (airport, ps[0] if ps else "")).fetchone()
        if airport and not _t:
            raise CannotAnswer(
                f"「{airport}」在哪一档,库里没有 —— 机场分档表【只有 2025Q4 一期】。"
                f"(问句:{q})")
        if airport:
            _档 = _t[0]
        else:
            _档 = _档位词(con, q)
        for _p in ps:
            _r = con.execute(
                "SELECT 行业平均, 来源 FROM 机场分档 WHERE 期次=? AND 档位=? LIMIT 1",
                (_p, _档)).fetchone()
            if _r:
                _均, _来 = _r
                if airport:
                    _自己 = con.execute(
                        "SELECT 得分 FROM 综合得分 WHERE 期次=? AND 机场=?",
                        (_p, airport)).fetchone()
                    if _自己:
                        _差 = round(_自己[0] - _均, 2)
                        lines.append(
                            f"{_p} {airport}:综合得分 {_自己[0]};"
                            f"它所在的【{_档}】平均 {_均} —— "
                            f"比同档平均【{'高' if _差 > 0 else '低' if _差 < 0 else '持平'} "
                            f"{abs(_差)}】")
                        #  ★★★ 2026-09-23:「表」那一段 —— 见 逐项同档表 上面的注释。
                        #  ★ 什么时候给:问"多少/几"的只要数;问"怎么样/什么水平"的
                        #    要数 + 表。★ 7/7,但真值只有 2 句是用户给的。
                        if not re.search(r'多少|几', q):
                            lines.extend(逐项同档表(con, _p, airport))
                    else:
                        lines.append(f"{_p} {_档}的平均分是 {_均}")
                else:
                    lines.append(f"{_p} {_档}的平均分是 {_均}")
                src.append(f"capse.db / 机场分档 表,期次={_p},档位={_档}"
                           + (f"  → PDF {_pdf(_来)}" if _来 else ""))
        if not lines:
            raise CannotAnswer(
                f"「{_档}」这个档的平均分只有 2025Q4 有 —— 你问的期次没有。(问句:{q})")

    elif (_tier := find_tier(q, [r[0] for r in con.execute(
            "SELECT DISTINCT 档位 FROM 机场分档 WHERE 档位 IS NOT NULL")])):
        # ══ ★★★ 问「某档位是多少」(2026-09-22,挑战集逼出来的)═══════
        #
        #  【病根】挑战集里四道【同一类】问题,因为问法差一个字走了两条路:
        #      2025Q4里,4000万级以上是多少  → 路由判【SQL】→ 不认它 → ★ 拒答
        #      2025Q4的1500万级说的是什么    → 路由判【判不出】→ 走检索 → ✅ 答对
        #  ★ 而 SQL 那五个分支认的是:样本量 / 指标名 / 机场 / 前N / 综合得分兜底 ——
        #     【"档位词"不在其中】。
        #  ★★ 又是那个老毛病:「同一条规则只装在一条路上」。
        #
        #  【判据】见 find_tier():标准档位里【以它结尾】且【唯一】的那个。
        #
        #  【数据来源】两张现成的表 JOIN 起来:
        #      机场分档(机场→档位) + 综合得分(机场→得分)
        #    ★ 实测过:2025Q4「4000万级以上」JOIN 出来 11 家,
        #      顺序和 P18 原文那张表【完全一致】(4.28/4.27/4.25…)。
        #
        #  ⚠ 覆盖范围的限制,如实说:机场分档表【只有 2025Q4 一期】——
        #    问别的期次答不了,那就明说,不猜。
        for _p in ps:
            _rows = con.execute(
                "SELECT t.机场, s.得分, s.来源 FROM 机场分档 t "
                "JOIN 综合得分 s ON s.机场 = t.机场 AND s.期次 = t.期次 "
                "WHERE t.期次 = ? AND t.档位 = ? ORDER BY s.得分 DESC",
                (_p, _tier)).fetchall()
            if _rows:
                lines.append(
                    f"{_p} {_tier}(共 {len(_rows)} 家,按综合得分从高到低):"
                    + ";".join(f"{a} {s}" for a, s, _ in _rows))
                #  ★★ 来源要带页码 —— 项目那条"每个答案都带出处"。
                #     而两张表【本来就有"来源"列】(第 8 课回填的),
                #     我第一版只查了机场和得分、没查它 ——
                #     于是用户拿到答案却【核不回原文哪一页】。
                #  ★★★ 那正是挑战集照出来的:它拿"正确页在不在来源里"当判据,
                #     而我的来源里只有表名,没有页码 → 判"没取到"。
                #     系统其实答对了,是【出处没写全】。
                #  ⚠⚠ 这个变量【不能叫 _pdf】—— 那是模块级函数的名字。
                #    实测踩过(2026-09-22):函数里一旦出现 `_pdf = ...` 这种赋值,
                #    Python 就把 `_pdf` 当成【整个函数的局部变量】,
                #    于是前面那些 `_pdf(row[1])` 的调用全部报 UnboundLocalError
                #    —— 60 道里 32 道崩,分数从 60/60 掉到 27/60。
                #  ★★ 又是"同一个名字两个身份"。这个项目一路在治的就是这个。
                _pdfs = "、".join(
                    _pdf(s) for s in sorted({r[2] for r in _rows if r[2]}))
                src.append(f"capse.db / 机场分档 + 综合得分 表,"
                           f"期次={_p},档位={_tier}"
                           + (f"  → PDF {_pdfs}" if _pdfs else ""))
        if not lines:
            raise CannotAnswer(
                f"「{_tier}」这一档的分档数据【只有 2025Q4 一期】—— "
                f"你问的期次没有。(问句:{q})")

    # ── 综合得分:单机场按机场查,无机场则取全期排名 ────
    #
    #  ★★ 这一格原来是个【排除法】:前面都不匹配 → 答综合得分。
    #     它是个黑洞,不区分问题,只区分"前面匹不匹配" —— 实测六个问法全答同一句。
    #     现在先过【正面定义】:认不出就抛出去,由 ask() 变成拒答。
    #
    #  ⚠ 位置很关键:关卡【在这里】,不在 ask() 里 ——
    #    在这里,前面 4 个分支已经各自把该接的接走了;
    #    放 ask() 里会拦在所有分支前面,把 meta 能答的题也拒掉(实测踩过)。
    else:
        #  ★★★ 2026-09-22:如果【参数里已经点名了总分】—— 那是调用方给的确切信息,
        #     不该再从句子里认一遍。那句可能什么都没有(比如指代句「那合肥新桥呢」),
        #     从头认一遍只会认出"认不出",然后把一个【本来答得出的问题】拒掉。
        #     ★ 那正是"参数不经过模型的嘴"的反面:【已经拿到的东西,别再去猜】。
        _note = '' if 参数里点名了总分 else asks_overall(q, airport)
        if _note is None:
            raise CannotAnswer(
                "认不出这题在问哪个指标 —— 库里没有能对上的字段。"
                f"(问句:{q})")
        if _note:
            # ★ 出声:这是【我替用户选的默认】,不是他说出来的。
            #   一并不出声,用户就分不清'这是我问的'还是'系统自己挑的'。
            lines.append(f"★ {_note}")

        # ══ ★ 按【所有】机场各查一次 ═══════════════════════════
        #   改之前只查 airport(一个)。实测(题 9/11/13/15/59):
        #     问: 2023Q3南京禄口 和 2025Q2西安咸阳,谁分高
        #     答: 2023Q3 南京禄口 4.14
        #         2025Q2 南京禄口 4.21     ← 西安咸阳被丢了,拿南京禄口顶上了
        #   两个期次都抽对了、机场只抽了一个 → **答了一个用户根本没问的组合。**
        #   静默:格式对、数字真、有出处,就是答的不是那个问题。
        targets = airports_in_q or ([airport] if airport else [])
        # ★ 两个维度都多于一个时,按位置配对(见 pair_period_airport 的 docstring)
        _pairs = pair_period_airport(q, periods, targets)
        vals = []                      # (期次, 机场, 得分) —— 比较结论要用
        for p in ps:
            if targets:
                _loop = [ap for (pp, ap) in _pairs if pp == p] if _pairs else targets
                for ap in _loop:
                    row = con.execute(
                        "SELECT 得分, 来源 FROM 综合得分 WHERE 期次=? AND 机场=?",
                        (p, ap)).fetchone()
                    if not row:
                        continue
                    rank = con.execute(
                        "SELECT 排名, 本期机场数 FROM 综合得分排名 WHERE 期次=? AND 机场=?",
                        (p, ap)).fetchone()
                    lines.append(f"{p} {ap}:综合得分 {row[0]},排名第 {rank[0]}/{rank[1]}")
                    # ★ 第 8 课:这一栏原来只到表名 —— 用户拿 4.23 回不到 PDF 的哪一页。
                    #   表里现在有 来源 列了(回填的),把它报出来。
                    src.append(f"capse.db / 综合得分 表,期次={p},机场={ap}"
                               + (f"  → PDF {_pdf(row[1])}" if len(row) > 1 and row[1] else ""))
                    vals.append((p, ap, row[0]))
            else:
                rows = con.execute(
                    "SELECT 排名, 机场, 得分 FROM 综合得分排名 WHERE 期次=? ORDER BY 排名 LIMIT 5",
                    (p,)).fetchall()
                if rows:
                    lines.append(f"{p} 前 5 名:" + ";".join(f"第{r}名 {a} {s}" for r, a, s in rows))
                    src.append(f"capse.db / 综合得分排名 视图,期次={p}")

        # ══ ★ 比较结论:值都查到了,但用户要的是【比】 ═══════════
        #   实测(题 10/14/16/55):两个值都答了,就是没比。
        #   期望答案里有"2024Q4高""相差0.05"这些【结论项】——
        #   用户问"谁高"不是想自己比,是想让系统比。**把值给出来不算答了这道题。**
        if len(vals) >= 2:
            hi = max(vals, key=lambda v: v[2])
            lo = min(vals, key=lambda v: v[2])
            if re.search(r'相差|差距|差多少|变化', q):
                d = round(hi[2] - lo[2], 2)
                lines.append(f"  → 相差 {d}"
                             f"(最高 {hi[0]} {hi[1]} {hi[2]},最低 {lo[0]} {lo[1]} {lo[2]})")
                src.append("(相差 = 上两条相减,不是库里的字段)")
            elif re.search(r'哪[个家]|谁|高|低|好|差|并列', q):
                if abs(hi[2] - lo[2]) < 1e-9:
                    lines.append(f"  → 并列({hi[2]})")
                else:
                    lines.append(f"  → {hi[0]} {hi[1]} 更高({hi[2]} vs {lo[2]})")
    return lines, src


