def retrieve(con, kw, periods=None, k=5):
    """按【给定的检索词】检索一次,并把来源、多版本说明一起组装好。

    ═══ 为什么把它从 answer_search 里抽出来(第 12 课)═══
        循环要能"换个检索词重走一遍" —— 而重走那一段【和第一遍是同一件事】。
        ★ 复制一份 = 两处迟早不一致。这个项目为此栽过好几次
          (最典型的是 ask.py 那个 [:120]:同一段逻辑只在一处截断)。

    ★ 它【只认检索词】,不认问句 —— 所以调用方得先把问句改写好。
      这么分是为了让"换词重走"能直接复用:换的是词,别的都不动。
    """
    hits = (search_merged(con, kw, k=k, periods=periods) if USE_MERGE
            else search_multi(con, kw, k=k, periods=periods))
    src = [f"{h['chunk_id']} = {h['期次']} 第 {h['页码']} 页" for h in hits]

    from page_versions import versions, describe
    # ★★ 只在【问句没有指定期次】时才查多版本。
    #   为什么(我第一版忘了这个条件,分数从 91.7% 掉到 78.3%):
    #     用户说了期次(「2024Q2的变更说明」)就知道他要哪一期,
    #     版本说明对他是噪声;而「这个服务测评是什么情况」没期次,
    #     版本说明才是他要的。
    #   **同一件事,对一类问题是答案,对另一类是噪声。**
    notes = []
    for pg in (sorted({h["页码"] for h in hits}) if not periods else []):
        #  ★★ 页类型要一路传下去 —— 见 page_versions.versions() 的注释。
        #     实测:2025Q4 那份 PDF 页结构不同,它的 P12 是【数据页】(分数表),
        #     而别的期的 P12 是【叙述页】。不传页类型的话,
        #     那张分数表会被当成"P12 的另一个版本"混进说明里 —— 题39 因此从满分掉到 0。
        _hit = next((h for h in hits if h["页码"] == pg), None)
        _t = con.execute("SELECT 页类型 FROM chunk WHERE chunk_id=?",
                         (_hit["chunk_id"],)).fetchone() if _hit else None
        _pt = _t[0] if _t else None
        vs = versions(con, pg, _pt)
        if len(vs) <= 1:
            continue                      # 只有一版 → 不啰嗦
        notes.append(describe(con, pg, _pt))
        have = {s.split(" ")[0] for s in src}
        for pers, _, _ in vs:             # ★ 每个版本的代表期进来源
            cid = f"{pers[0]}-P{pg:02d}"
            if cid not in have:
                src.append(f"{cid} = {pers[0]} 第 {pg} 页")
                have.add(cid)
    return hits, src, notes


def answer_search(con, q, k=5, periods=None):
    """叙述型。返回 (命中的 chunk, 来源, 查询词, 多版本说明列表)。

    ═══ 这一路比第 5 课刚建时多做了一步「改写」 ═══
        不做改写时是【把整句问句丢进去搜】:"报告的测评指标为什么调整过" → 0 条
        看起来像"知识库没有",其实是"检索方式不对"。四个原因叠在一起:
            整句短语匹配 / 词不对(调整 vs 变更) / 2 字词搜不了 / k 太小
        现在:先让大模型把问句改写成关键词,再【按空格拆开分别搜】。
        改写结果一起返回 —— 不然"为什么搜出来是这几个"就又是一笔糊涂账。

    ═══ ★ periods 是从上面【传进来的】,不是在这里重新判的 ═══
        调用方 ask() 已经算好了 periods = find_periods(q)。
        这里再判一次 = 同一个判断写两遍 —— 两处迟早会不一致。

        ⚠ 传进来的 periods 可能是空集(题 39 就没有期次)。
          空集【不等于】"不过滤是错的",是【有意不过滤】,
          理由写在 build_search.search() 的 docstring 里,别改。

    ═══ ★★ 第 8 课挖出来的【根因】:同一页的多期 ═══
        见 tools/page_versions.py 的文件头。一句话:
            **库里 83% 的内容是"同一页在多个期"的重复,
              而检索把它们当成【互相独立的候选】。**

        后果(五个症状,一个根):
            #39 只取到 9 条里的 1 条      → 多版本不可见
            #42 取到两期的同一页拼在一起  → 跨期矛盾
            #48/#51/#52 P07 有 9 条,每条都在竞争 → 一页占 3 个名额,把真答案页挤掉
            期次污染 37%                 → 同一个根

        所以检索回来之后【多做一步】:命中的页码有没有多个版本?
        ⚠ 这一步【不靠大模型】—— 是查询 + 精确比对(page_versions),
          硬的、可核的、不会编的。而它补的正是"程序不知道有多页"这件事。

        ⚠ 多版本时,【每个版本的代表期也进来源】—— 因为系统确实用到了它们。
          不然"我知道有多个版本"这句话,在来源里找不到证据。
    """
    try:
        kw = rewrite_query(q)
    except LLMError:
        # 模型没连上,退回整句搜。会搜不到,但【是看得见的搜不到】,不是静默失败。
        kw = q
    #  ═══ ★★★ 2026-09-23:把【期次形态的词】从检索词里剔掉 ═══
    #  【为什么 —— 实测抓到的,而它让一整页挤不进来】
    #      问「2025Q4 报告里,测评指标为什么调整过」
    #      改写出来的词:「2025Q4 测评指标 调整 变更」
    #      ★ 分开搜:
    #          '2025Q4'   → 那一期的【前 5 页】(P07/P19/P20/P18/P21)
    #          '测评指标'  → 【只有 P04】  ← 它才是该被搜到的那页
    #      ★★ 而合并之后,那 5 个名额【被"2025Q4"占满了】—— P04 挤不进来。
    #      ★★★ 根因:「2025Q4」有【两个身份】——
    #             · 期次【过滤条件】:已经用在 periods 上了
    #             · 检索【关键词】:而它几乎命中那一期所有页
    #           两个身份打架,而"过滤"那个才是它该干的活。
    #
    #  ⚠ 剔掉是安全的:periods 过滤【已经保证了只查那一期】,
    #    所以期次作为检索词是多余的 —— 而且有害。
    #  ⚠⚠ 但如果剔完【一个词都不剩】,那就用原来的 —— 宁可多搜,不要搜不了。
    词 = [w for w in str(kw).split() if not re.fullmatch(r'\d{4}Q\d', w)]
    if 词 and len(词) < len(str(kw).split()):
        kw = " ".join(词)

    # ★ 第 9 课第二节的一行开关。关着 = 只用关键词(第 5 课以来一直的行为)。
    # ★★ 第 12 课:检索那一段抽成 retrieve() 了 —— 因为循环要能"换个词重走",
    #     而重走的那一段【和第一遍是同一件事】。复制一份 = 两处迟早不一致。
    hits, src, notes = retrieve(con, kw, periods=periods, k=k)
    return hits, src, kw, notes



def ask(con, q, airports, indicators):
    #  ★ 统一形状之后(第 15 课):期次取"值"这个集合,机场/指标取单值。
    periods = set(find_periods(con, q)["值"])
    airport = 单值(find_airport(con, q, airports))
    indicator = 单值(find_indicator(con, q, indicators))

    # ★★ 这三道检查【提到路由之前】—— 因为它们和走哪条路无关。
    #   第一版把它们装在 answer_sql 里(SQL 那条路),结果题 57 走的是检索,
    #   根本不进那个函数 → 检查没跑。
    #   ★ **同一条规则只装在一条路上 —— 这是这一课第三次了**
    #     (前两次:年度报告规则只装在数值那条路、check_eval 的 [:160] 只在一处截断)。
    #   放在这里 —— 两条路都盖到。
    _known = known_names(con, indicators)
    _um = unknown_metric(q, _known)
    _ua = unknown_airport(q, find_airports(con, q, airports), airports)
    _mq = META_Q.search(q)
    if _um or _ua or _mq:
        if _mq:
            _why = ("问题里询问的是【系统内部怎么处理的】—— "
                    "而我只能回答报告里写了什么,回答不了我自己怎么切的。"
                    "建议拆成两个问题。")
        elif _um:
            #  ⚠⚠ 这句话原来写的是:"2025Q4 没有「X」这个指标 —— …"
            #     实测(2026-09-22,题36)发现它有两处不对:
            #
            #     ① 期次是【写死的】,而用户可能问的是别的期。
            #        题36 问的是"2024Q1…的靠桥率得分",它答的是"2025Q4 没有"。
            #        ★ 而那道题的期望就是"拒答" —— 所以【判分给了对】,
            #          一个说错话的回答被判成了满分。
            #        ★★ 这是"用户看得见、判分看不见"的那一类错。
            #
            #     ② 说得像"别的期有,只是这期没有"。
            #        而真相往往是【库里压根没存这个指标的分数】(比如靠桥率)。
            #
            #     → 所以改成:不带期次的说法,并把用户问的期次【照原样回显】。
            _per = "/".join(sorted(periods)) if periods else ""
            _why = ("我没有「" + _um + "」的数据"
                    + ("(你问的是 " + _per + ")" if _per else "")
                    + " —— 库里没有这个指标的分数,我不猜。"
                    + "  ".join(hint_metric(con, _um, _known)))
        else:
            _why = (f"「{_ua}」不在库里 —— 我不拿别的机场替你答。"
                    + "  ".join(hint_airport(con, _ua, airports)))
        return {"问题": q, "去向": "拒答", "答案": [_why], "来源": [],
                "标注": [], "警告": [], "备注": []}

    where, flag, why = route(con, q, airports, indicators)

    out = {"问题": q, "去向": where, "答案": [], "来源": [], "标注": [],
           "警告": [], "备注": []}

    # 关键词表判不出 → 交给大模型重判一次,再走【同一条】后面的流程。
    #   ※ 不是"另起一条路",是"回到岔路口重新走" ——
    #     后面的可用性检查 / 跨口径检查,一个字都不用重写。
    if where == "判不出":
        try:
            a = judge_intent(q)
            if a in ("A", "B"):
                where, flag, why = route(con, q, airports, indicators, intent=a)
                out["去向"] = where
                out["备注"].append(
                    f"关键词表判不出 → 大模型判定「{'要数' if a == 'A' else '要话'}」")
            else:
                out["备注"].append("关键词表判不出 → 大模型也说拿不准")
        except LLMError as e:
            # 模型挂了,【保持判不出】,不猜。这是第 4 课那条:判不出看得见,判错看不见。
            out["备注"].append(f"★ 模型没连上({e}) —— 保持「判不出」,不猜")

    # 他定的规则②:跨口径必须说明
    if flag:
        out["标注"].append(why)

    if where == "拒答":
        out["答案"] = [f"不回答。{why}"]
        return out

    if where == "判不出":
        out["警告"].append("路由判不出这题要数还是要话 —— 不知道该查表还是翻文档")
        return out

    if where == "SQL":
        # ★ "认不出"由 answer_sql 抛出来,在这里变成【拒答】。
        #
        #   ⚠ 关卡【必须放在 answer_sql 里面原来的 else 位置上】,不能放这里:
        #     放这里会拦在【所有分支前面】—— 实测把「2025Q1机场数是多少」也拒了,
        #     而"机场数"是 meta 分支能答的(库里真有,在 meta.机场数)。
        #     **关卡该只守"兜底那一格",不是守整个函数。**
        try:
            out["答案"], out["来源"] = answer_sql(con, q, periods, airport, indicator,
                                              find_airports(con, q, airports),
                                              indicators, airports)
        except CannotAnswer as e:
            out["去向"] = "拒答"
            # ★ 去掉"不回答。"这个开头(张君杰:"不要让系统太死板")——
            #   去向字段已经写着"拒答"了,答案文本不必再重复一遍。
            #   那句话除了硬,什么信息都没有;而解释本身才是用户要的。
            #   **字段管"是什么",文本管"为什么"。**
            out["答案"] = [str(e)]
            return out
        if not out["答案"]:
            out["答案"] = ["库里没有匹配的数据(注意:这不同于'问得不对')"]
        return out

    # ── 检索 ────────────────────────────────────────
    hits, src, kw, page_notes = answer_search(con, q, periods=periods)

    # ══ ★★★ 第 12 课(下半):检索层循环 —— 0 条时换个词重走 ══════
    #  ★ 它和 gen_with_retry 是【两层】:
    #     那个改"给大模型多少材料"→ 材料池【不变】→ 治"材料里有、它没用上"
    #     这个改【检索词】        → 材料池【会变】→ 治"材料里根本没有"
    #  ★★ 真实案例:题51 走关键词那条路时只给出 1 条(2024Q2-P07),
    #     而答案页 2024Q2-P14 压根【没被取到】—— 生成层怎么挑都挑不出来。
    #  ★★★ 触发条件是【硬判据】:检索回来 0 条 —— len(hits)==0,代码一眼可查。
    #       别的"检索不够好"没有硬判据,所以不放进来。
    if USE_LOOP and not hits:
        tried = [kw]
        for _att in range(1, MAX_LOOP + 1):
            try:
                kw2 = rewrite_query_alt(q, tried)
            except LLMError:
                out["备注"].append("换词循环:模型没连上,停")
                break
            if not kw2 or kw2 in tried:
                out["备注"].append(f"换词第{_att}次:它又写出了「{kw2}」,停")
                break
            tried.append(kw2)
            h2, s2, n2 = retrieve(con, kw2, periods=periods, k=SEARCH_K)
            out["备注"].append(f"换词第{_att}次:「{kw2}」→ {len(h2)} 条")
            if h2:
                hits, src, page_notes, kw = h2, s2, n2, kw2
                break

    out["来源"] = src
    out["备注"].append(f"检索用词:{kw}")

    # ★ 0 条检索 ≠ 拒答 —— 两种不同的失败,不能共用一个去向。
    #
    #   口径(张君杰定的):"0 条检索属于检索失败;主动拒答属于模型在【有/无证据】条件下
    #   选择不回答。" 前者是"路走了没找到",后者是"我知道我不该答"。
    #
    #   ※ 为什么必须提成【字段】,不能只留在答案文本里:
    #     改之前它写作 ["没搜到相关内容"] —— 去向仍然是"检索"。
    #     于是任何按去向统计的东西,都会把【一次都没搜到】算进"检索成功"。
    #     文本不是字段,统计看不见它。这和"静默失败"是同一个病:
    #     出了事,但没有任何一个能被程序读到的地方记着它出过事。
    if not hits:
        out["去向"] = "检索·0条"
        out["答案"] = ["检索 0 条 —— 该走的路走了,没找到东西。这【不是】拒答,是检索失败。"]
    else:
        # ── ★ 答案【不截断】,截断只发生在显示层 ──────────────────
        #
        #   改之前这里是 [h["文本"][:120] + "…"],后果实测:
        #       #45 的答案在第 127 字(NPS)          → 被砍
        #       #49 的答案在第 214~245 字(注册/审核) → 被砍
        #       #50 的答案在第 465 字(物有所值)      → 被砍
        #   三道题全部判 0,而【检索都是对的】——#49/#50 的正确页 P12 早就在
        #   答案里排第二位。#45 命中的也是正确的 2025Q3-P11。
        #
        #   ※ 这个 120 的来历(查过 git,只有一次提交):
        #     第 5 课 ask.py 是个【演示工具】,render() 把答案打到终端给人看,
        #     421 字的原文打三遍会刷屏 —— 那是个【显示决定,当时是对的】。
        #     第 6 课 score_eval.py 拿【同一个字段】去判分 ——
        #     代码没变、位置没变、值没变,【变的是用途,而用途变了没有任何地方记着】。
        #
        #   → 病根不是"120 太小",是【同一个字段有两个身份】。
        #     所以修法不是把 120 改成 500(那只是把阈值挪个地方),
        #     是【把两个身份分开】:
        #         答案  ← 完整原文,给判分和下游用
        #         摘要  ← 截断的,只给终端显示用(见 render())
        #     这样以后 k 调大、切片变细,都不会再有人踩到它。
        # ★ 多版本说明放【最前】——
        #   用户一定会读第一行。而"这一页有三个版本"这件事,
        #   比那一条具体的原文重要得多。
        if USE_GEN:
            #  ★ 第 10 课:让大模型【作答】,而不是把材料拼起来。
            try:
                if USE_RETRY:
                    #  ★ 第 12 课:走循环 —— 生成 → 诊断 → 做对应的动作
                    #  ★★ airports 要传:diagnose 里有一条要核"编了机场名"
                    #  ★★★ notes 也要传:那是【多版本说明】——
                    #     不传的话模型看不见"这几段是同一页的三个版本",
                    #     它会从不同版本里各取一个数配成一句(实测踩到过)。
                    a, _trace = gen_with_retry(q, kw, hits, airports, page_notes)
                    out["备注"].extend(_trace)      # ★ 过程留着,不然看不出它试了什么
                else:
                    a = gen_answer(q, hits, notes=page_notes)
                bad = audit_answer(a, hits)
                ghost_cite = check_citations(a, hits)
                out["答案"] = list(page_notes) + [a]
                #  ═══ ★★★ 2026-09-22:把【模型写的那一段】单独存一份 ═══
                #  【为什么必须单独存 —— 这一节因为缺它栽了四次】
                #      out["答案"] = 多版本说明 + [模型那句]。
                #      而"多版本说明"是【代码算出来的】,里面本来就有页码、期数、
                #      「第 7 页在 9 期里有 3 个版本」这种话 —— 全是数字。
                #
                #      ★ 于是我每次离线复检,拿【整段答案】去审,判据就会:
                #          · 报出 4 个"编的数字" —— 其实全来自那段说明(题39)
                #          · 判不出"模型整段没提那一页" —— 因为说明里有那些数字
                #        **同一个坑踩了四次。**
                #
                #  ★★ 根因不是判据写得不好,是【信息没留下来】:
                #      事后想从拼好的东西里反推"哪句是模型的",只能靠正则猜。
                #  ★★★ 所以:在源头把它分开存。以后所有离线分析都该用 模型答。
                out["模型答"] = a
                if bad:
                    #  ★ 出声。这一层的价值有一半在这行 ——
                    #    没有它,生成层就变成一个"答得又干净又流畅、而没人知道是编的"东西。
                    out["警告"].append(
                        f"回答里有 {len(bad)} 个数在材料里找不到:{sorted(bad)[:5]} —— 可能是编的")
                if ghost_cite:
                    #  ★★ 这一道比上面那道【硬】:出处的编号是系统自己发的,
                    #     材料里没有 = 它编的,没有中间地带。
                    out["警告"].append(
                        f"回答里标了 {len(ghost_cite)} 个【材料里没有的出处】:"
                        f"{sorted(ghost_cite)} —— 出处是编的")
                missed = check_missed(a, kw, hits)
                if missed:
                    #  ★★★ 这一道是"防漏":它说"材料里没有",可检索词明明能在材料里搜到。
                    #      #45 那次就是这样 —— 材料就在它手里,它说没有。
                    #      而旧的那条告警(verify)问的是另一个问题,抓不到这个。
                    out["警告"].append(
                        f"回答说「材料里没有」,但检索词 {missed[:3]} 在材料里【搜得到】"
                        f" —— 可能是漏了,不是真的没有")
                missed_rank = check_ranked_answer(a, q, hits)
                if missed_rank:
                    #  ★★ 这一道是【算出来的】,不会抽样 —— 见函数注释。
                    #     实测抓到过:题48 加出处之后漏了并列的宁波栎社。
                    out["警告"].append(
                        f"回答说漏了:{missed_rank} —— 这是从材料里的得分表【算出来的】,"
                        f"不是猜的")
                ghost_ent = check_entities(a, hits, airports)
                if ghost_ent:
                    #  ★ 这一道补的是 audit_answer 的盲区:它只核数字,不核名字。
                    #     实测(15 道)报 0 次 —— 不误报,但也没病例。它是兜底。
                    out["警告"].append(
                        f"回答说到了材料里没有的机场:{ghost_ent} —— 可能是编的")
            except LLMError:
                #  模型没连上 → 退回【原样列出材料】。
                #  ★ 但要说清"这是材料,不是回答" ——
                #    悄悄退回 = 用户以为拿到的是答案。那是静默失败。
                out["答案"] = list(page_notes) + [h["文本"] for h in hits]
                out["警告"].append(
                    "生成层没连上,退回【原样列出材料】—— 这不是回答,是搬运。")
        else:
            out["答案"] = list(page_notes) + [h["文本"] for h in hits]

    # 第 4 课建的验证:走检索的题,回头看一眼这题真的该走检索吗
    warn = verify(con, q, periods, airport, hits)
    if warn:
        out["警告"].append(warn)
    return out


# ══════════════════════════════════════════════════════════
#  渲染层:把答案对象变成给人看的一段
# ══════════════════════════════════════════════════════════
def render(a):
    print(f"\n{'─' * 74}")
    print(f"问:{a['问题']}")
    print(f"〔去向〕{a['去向']}")
    if a["答案"]:
        print("〔答案〕")
        for line in a["答案"]:
            # 截断【只在这里】发生 —— 终端里看着舒服,不影响答案本身
            print(f"    {line[:120]}" + ("…" if len(line) > 120 else ""))
    if a["来源"]:
        print("〔来源〕")
        for s in a["来源"]:
            print(f"    · {s}")
    elif a["去向"] in ("SQL", "检索"):
        print("〔来源〕★ 空 —— 按规则,有答案就必须有来源,这个不该发出去")
    # ※ 拒答不要求来源 —— 它要的不是出处,是【理由】,理由在答案里。
    #   一开始我把拒答也标成"不该发出去",那是把规则用错了地方。
    for n in a["标注"]:
        print(f"〔标注〕{n}")
    for n in a["备注"]:
        print(f"〔过程〕{n}")
    for w in a["警告"]:
        print(f"〔警告〕★ {w}")


# ══ 验收用的一组问题 ═══════════════════════════════════
QUESTIONS = [
    "2025Q4 上海浦东国际机场的综合得分是多少",
    "2025Q4 的样本量是多少",
    "2025Q4 综合得分前 5 名是哪些机场",
    "2023Q3 和 2025Q4 的上海浦东,哪个分高",
    "2025Q4 上海浦东在 7 个一级指标里,哪项最高",
    "报告的测评指标为什么调整过",
    "2023 年删掉了哪些指标",
    "2024Q3 上海浦东国际机场的机场安检得分是多少",
    "2024年度报告里,全年得分最高的机场是哪个",
    "2025Q4上海浦东表现如何",
]


def main():
    #  ═══ ★★★ 2026-09-22 加命令行开关 ═══
    #  【为什么要加】写 README 的时候发现:上面那几个开关
    #  (USE_MERGE / USE_GEN / USE_RETRY)只能【改源码】才能开。
    #  ★ 后果:README 没法写出一条真的命令 —— 只能写"去把第 69 行改成 True",
    #    而那对第一次拿到项目的人是一道没必要的墙。
    #  ★★ 更糟的是,如果 README 写了 `--merge` 而这个脚本不认,
    #     那条命令会【静静地被忽略】—— 用户以为开了,其实没开。
    #     **那正是这个项目一路在打的东西。**
    import argparse
    ap = argparse.ArgumentParser(
        description="问几个问题,看看系统怎么答(默认全关 = 第 5 课以来的基线)")
    ap.add_argument("--merge", action="store_true",
                    help="开合并检索(关键词 + 向量)。★ 第一次跑会下载模型(约 100MB)")
    ap.add_argument("--gen", action="store_true", help="开生成层(让大模型作答,不是拼材料)")
    ap.add_argument("--retry", action="store_true", help="开重试循环(生成→诊断→动作)")
    ap.add_argument("--ask", default="", metavar="问题",
                    help="只问这一个问题,不跑下面那套演示")
    args = ap.parse_args()
    #  ★ 用 global 改模块级开关 —— ask() 读的就是它们。
    global USE_MERGE, USE_GEN, USE_RETRY
    if args.merge:
        USE_MERGE = True
    if args.gen:
        USE_GEN = True
    if args.retry:
        USE_RETRY = True
    if args.merge or args.gen or args.retry:
        print(f"  开关:合并检索={'开' if USE_MERGE else '关'} "
              f"生成层={'开' if USE_GEN else '关'} "
              f"重试循环={'开' if USE_RETRY else '关'}\n")

    con = sqlite3.connect(DB)
    airports = load_airports(con)
    indicators = load_indicators(con)

    if args.ask:
        #  ★ 只问一个就走 —— 这是"别人拿到项目后第一件想做的事"
        render(ask(con, args.ask, airports, indicators))
        con.close()
        return

    for q in QUESTIONS:
        render(ask(con, q, airports, indicators))

    # ── 把"来源够不够"单独拉出来看 ──────────────────
    print(f"\n\n{'═' * 74}")
    print("═══ 两条路的【来源】完整程度 ═══")
    n_src = n_nosrc = 0
    sql_with_pdf = []          # ★ SQL 路的来源里,有没有带 PDF 页码
    for q in QUESTIONS:
        a = ask(con, q, airports, indicators)
        if a["去向"] in ("SQL", "检索"):
            if a["来源"]:
                n_src += 1
                if a["去向"] == "SQL":
                    sql_with_pdf += [s for s in a["来源"] if "PDF" in str(s)]
            else:
                n_nosrc += 1
                print(f"  ★ 有答案但没有来源:{q}")
    #  ⚠⚠ 2026-09-22:两个数分开看待,它们【不是一回事】:
    #      无来源 N 题 —— ★ 这是【判据】,期望值是 0。有 >0 就是有答案缺来源,该报警。
    #      有来源 N 题 —— ★★ 这只是【这次跑出来的计数】,不是结论。
    #         实测:同一份代码跑两次,一次报 4 一次报 8 ——
    #         因为这里面有大模型参与的路由,同一个问题两次可能走不同的路。
    #      ★★★ 所以把"有来源"那个数【标明是这一次的】,别让它看起来像个定论。
    #           一个每次都可能不一样却印得像结论的数,和那三处过期结论是同一个病。
    print(f"\n  ★ 无来源 {n_nosrc} 题  ← 这个是判据,期望是 0")
    print(f"    有来源 {n_src} 题  ← ⚠ 这只是【这一次跑】的数,不是结论"
          f"(有大模型路由参与,两次跑可能不一样)")

    #  ═══ ★★★ 2026-09-22:这一段原来是【写死的文字】,现在改成【算出来的】 ═══
    #
    #  【为什么必须改 —— 张君杰跑这个脚本时撞上的】
    #      原来这里印的是一段固定的结论:
    #          "SQL 这一路的来源只能写到【表名】…回不到 PDF 的哪一页去核"
    #      那是【第 7 课当时】的结论,当时是对的。
    #
    #      ★ 而第 13 课把数据页收进库之后,那个缺口修好了 ——
    #        来源现在能到 "→ PDF 2025Q4 第9页"。而我【没回头改这段打印】。
    #      ★★ 于是:每次跑这个脚本,它都会宣布一个【已经不成立】的结论。
    #      ★★★ 最糟的是它和上面那行"有来源 N 题"印在一起,长得一模一样 ——
    #           读的人分不出【哪句是量的、哪句是写的】。
    #           **同一段输出,两个来源。这就是这个项目一路在打的病。**
    #
    #  → 所以改成算的:去看实际的来源里有没有 "PDF"。
    #    能算的地方别写死 —— 在这段打印里也一样成立。
    if sql_with_pdf:
        print(f"\n  ★ SQL 这一路的来源【能回到 PDF 页码】—— 实测 {len(sql_with_pdf)} 条,例如:")
        print(f"       {sql_with_pdf[0]}")
        print("\n  检索这一路也是完整的:")
        print("       2025Q4-P19 = 2025Q4 第 19 页")
    else:
        print("\n  ⚠ SQL 这一路的来源【回不到 PDF 页码】,只能到表名:")
        print("       capse.db / 综合得分 表,期次=2025Q4,机场=上海浦东国际机场")
        print("  用户拿着它,回不到 PDF 的哪一页去核。")
        print("\n  → 这不是代码写错了,是【第 1 课入库时没记页码】。")
    con.close()


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
    main()
