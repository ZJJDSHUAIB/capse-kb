def gen_answer(q, hits, max_tokens=300, notes=None):
    """把取回的材料变成一句回答。★ 这是全流程里【唯一】让大模型作答的地方。

    ⚠ 它只能减轻"搬运",不能保证"答对" ——
      所以下面必须再走一道 audit_answer(),否则它编了什么没人知道。

    ═══ ★★★ 2026-09-22 加 notes 参数(重要的一个修正)═══
        实测查出来的机制(不是猜的):

            第 39 题的材料是 9 页,其中【3 段长得几乎一样、只有数字不同】——
            它们是同一页(第 7 页)在三个时期的版本。

        ★ 而在这之前,模型【不知道】那三段是同一页的版本。
          因为版本信息在多版本说明(page_notes)里,
          而 page_notes 是在【答案拼装完之后】才贴到结果上的 —— 模型看不到。
        ★★ 于是它随手从不同版本里各取一个数,配成一句话:
              「一级指标7项、二级指标30项」← 没有哪一期是这么写的
           而这句错话,三条硬判据【全报空】(每个数都在库里出现过)。
        ★★★ 所以修法不是"再加一道判据",是【把已经算好的信息递给它】——
           能算的地方别问大模型;而【已经算出来的东西,别让它看不见】。
    """
    from llm import chat
    材料 = "\n\n".join(
        f"【{i+1}】{h['chunk_id']}({h['期次']} 第 {h['页码']} 页)\n{h['文本']}"
        for i, h in enumerate(hits))
    版本提醒 = ""
    if notes:
        版本提醒 = ("\n★ 这几页有【多个版本】—— 同一页在不同期次写的数字不一样。"
                    "引用时必须说清是【哪一期的那一版】,不许把两版的数混着说:\n"
                    + "\n".join(notes) + "\n")
    return chat(GEN_USER.format(n=len(hits), 材料=材料, q=q, 版本提醒=版本提醒),
                system=GEN_SYS, max_tokens=max_tokens).strip()


def audit_answer(ans, hits):
    """回答里的每个数字,在材料里找得到吗?返回【找不到的那些】。

    ★ 复用 report_gen.audit() —— 不重写。那套已经处理过两个坑:
        ① 表格/列表的编号(**1.** / 2. )
        ② 序数(第 1 名 / 第 3 位)
      不剔的话它们会被当成"材料里没有的数"报到人面前 ——
      **而那是假警报。假警报多了,真警报就没人看了。**
    ★★ 它保证的只有【数字有据】,不保证【用得对】——
       方向说反了(「比同档低」却写成高)、张冠李戴,它抓不住。
       **它不是安全保证,是把"完全没查"变成"查了一道"。**
    """
    from report_gen import audit
    材料 = "\n".join(h["文本"] for h in hits)
    #  ⚠ 先剔掉出处再核数 —— 出处里带页码(2025Q4-P23 里的 23),而页码不在正文里。
    #    不剔的话每一句带出处的回答都会报"材料里没有 23 这个数"。
    #    ★ 这是"数据里一半的数是写在字符串里的"那个坑的第五次 ——
    #      前四次见 report_gen.collect_numbers 的注释。
    return audit(CITE.sub(" ", ans), 材料)


#  ★ 出处长这样:(出处:2025Q4-P23) 或 (出处:2025Q4-P18 / 2025Q4-P19)
CITE = re.compile(r"[（(]\s*出处\s*[:：]\s*([^)）]+)[)）]")
CID = re.compile(r"\d{4}Q\d-P\d+")

#  ★ 它说"没有"时的那些说法
NONE_PAT = re.compile(r"材料里没有|材料中没有|材料里不包含|没有提到|未提及|无法确定|"
                      r"没有相关|未找到|没有找到")


#  ★ 问句里的档位和名次 —— 抽得出来,才说明这题属于"分档排名"那一类
GRADE_Q = re.compile(r"(\d{4}万(?:-\d{4}万)?级(?:以上)?)")
RANK_Q = [("前两名", 2), ("前三名", 3), ("前五名", 5), ("前五", 5), ("前二", 2),
          ("第二名", 2), ("第三名", 3), ("第一", 1)]


def ranked_expected(q, hits):
    """这类题的【完整答案】该有哪些?返回 [(分数, 机场), ...],或不适用时 None。

    ★ 抽出来单独放,是因为【检查和补写要用同一个算法】——
      检查说"缺了宁波",补写就得知道"宁波是什么分数"。
      两处各算一遍 = 迟早对不上(这个项目栽过好几次)。
    """
    from parse_table import parse

    g = GRADE_Q.search(q or "")
    if not g:
        return None
    grade = g.group(1)
    n = None
    for w, k in RANK_Q:
        if w in q:
            n = max(n or 0, k)
    if not n:
        return None

    for h in hits:
        pg, pairs = parse(h["文本"])
        if pg is None or pg != grade or not pairs:
            continue
        cut = min(n, len(pairs))
        best = pairs[cut - 1][0]                    # 第 n 名的分数
        #  ★ 并列:凡是分数 == 第 n 名的,都算进来 —— 那是【算出来的】,不是从答案抄的
        want = pairs[:cut] + [p for p in pairs[cut:] if p[0] == best]
        return want, h["chunk_id"]                  # ★ 连出处一起给 —— 补写要用
    return None


def check_ranked_answer(ans, q, hits):
    """问"某档位第 N 名是谁"的题 —— 用它手里的那张表【算一遍】,看答全了没有。

    ═══ 它补的是哪一块 ═══
        已有的检查都核不到"答漏了":
            audit_answer     核数字有没有据      → 漏掉的数字它不管
            check_citations  核出处真不真        → 出处是真的,只是答漏了
            check_missed     核"说没有而材料里有" → 它没"说没有",它答了一半

    ═══ ★★★ 为什么这一道【不会抽样】 ═══
        分档得分表能解析出【分数 ↔ 机场】的配对(见 parse_table)。
        于是"第一名有几个"是【算得出来的】——
        ★ 同一份材料,每次算出来都是同一个答案,不会这次说一个、下次说两个。
        ★★ 而这一点,是它和别的检查根本不同的地方:
           别的都得靠大模型(会抽样)或字面(会误判),只有它靠算。

    ═══ ⚠ 它只覆盖这一类题 ═══
        问句里同时有【档位】和【名次】的。抽不出来就返回 None —— 不硬凑。
        库里现在只有 3 道(#46 #47 #48)。

    ★★ 它核的是【说全了没有】,不是「说得对不对」。两件事,别混。

    ═══ ★★★ 返回值是三态,不是两态(第 11 课改的)═══
        不适用  →  None      这道题不是"分档排名",或者材料里没那张表
        对      →  []        答全了(空列表 —— 假值,所以 ask 里 if 不会响)
        错      →  [缺的]    漏了

      ⚠ 第一版我写的是 `return miss or None` —— 那把【没缺】和【不适用】
        混成了同一个 None。当时没出事,因为 ask 只判真假;
        ★★ 但第 11 课要拿它【当判分用】:判分必须能分清
           "这题我算得了、它答对了" 和 "这题我算不了、得交给大模型"。
        ★★★ 两件事混在一个值里 —— 这是这个项目的老病,又犯一次。
    """
    got = ranked_expected(q, hits)
    if got is None:
        return None
    want, _src = got
    return [f"{ap} {sc}" for sc, ap in want if ap not in ans]


def supplement_ranked(ans, q, hits):
    """把漏掉的并列/名次【算出来补上】。补不了就原样返回。

    ═══ 为什么这一类动作是"补"而不是"重试" ═══
        ★ 重试是【碰运气】:它这次漏了,下次可能不漏,也可能还漏。
        ★★ 而"这一档有几个并列第一"是【算得出来的】——
           算出来就确定,不需要再赌一次。
        ★★★ 项目一路的规矩:能算的地方,别问大模型。
            前两课在【判分】和【提问】上验过,这里是在【生成层】再验一次。

    ═══ 补的那句必须做到两件事 ═══
        ① 带出处(出处在材料里 —— 那是真的)
        ② ★★ 明确标注【这是代码算的】——
           不能让用户以为整句都是"读材料读出来的"。
           项目规矩:宁可没有,不可假有。
    """
    got = ranked_expected(q, hits)
    if got is None:
        return ans
    want, src = got
    miss = [(sc, ap) for sc, ap in want if ap not in ans]
    if not miss:
        return ans
    补 = "；".join(f"{ap} {sc}" for sc, ap in miss)
    return (ans.rstrip() +
            f"\n另:{补}(出处:{src})"
            f"【此句由代码从材料里的得分表算出,不是读出来的】")


