# -*- coding: utf-8 -*-
r"""
覆盖清单 —— 把用户问的【要件】列成一张清单,再逐条勾"答到了没有"。

═══ 为什么要有它（调研结论 + 实测,两边的证据指向同一件事）═══

    【实测:他随口造的两道复杂题】
        「浦东2025Q4和2025Q3比，哪一项指标下降最多」
          → 抽期次抽到了 2025Q3 和 2025Q4 ✓
          → ★ 而查表【只查了 2025Q4】—— 根本没比
          ★★ 而它没出声:格式正常、数字真实、有出处。

        「浦东2025Q4哪一项指标最弱，那一项和同档平均差多少」
          → 查逐项给出了七个指标和同档的对照表
          → ★ 而「最弱的是哪一项」这句话【根本没出现】

    【调研:自我审查治不了这一类,而原因是结构性的】
        有一篇专门量过(《Omission Blindness》,500 对样本、8 种 judge 设计):
            对「加了/改了内容」的区分度: 0.79–0.94   ← 很好
            对「遗漏了内容」的区分度:   ★ 0.50–0.63  ← 接近【抛硬币】
        ★ 换措辞、多数投票、优化提示词 —— 都没能造出可用的"遗漏检测"。

    ★★★ 而机制上的解释(另一篇 ACL 2024):
        给模型 2186 条标注了"第一个逻辑错在哪"的推理链,让它自己找错 ——
        最好的 GPT-4 也只有 52.87%。
        ★★ 但【一旦告诉它错在哪】,它的修正能力就很强。
        → 瓶颈在【检测】,不在【修正】。

═══ ★★★★★ 所以这里的做法是「对着清单勾」,而不是「审自己答得对不对」 ═══

    审自己:  看自己写的那段话 → ★ 它是完整、准确、有出处的 → 没理由打回
    勾清单:  看【从问题里抽出来的要件】→ 逐条对 → ★ 缺的那条【藏不住】

    ★ 而勾的动作【全部用规则】,不用模型判:
        期次对不上 → 数个数、比集合
        ★ 而这正是那个项目一路的规矩:能算的地方,别问大模型。

═══ ⚠ 而"清单"本身【第一刀只做一项】═══
    现在只有【期次】这一条 —— 因为它最能算。
    ★ 别的要件(比如"有没有给出 argmin 的结果")要一个一个接,
      而每一个都该先问:【它能不能用规则勾?】能,才接。

═══ 怎么用 ═══
    python tools/覆盖清单.py            # 拿内置例子跑一遍
    from 覆盖清单 import 数期次的差
    一句 = 数期次的差(用户说的期次, 实际查的期次)
"""
import sys
import io
import re
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))


#  ══════════════════════════════════════════════════════════════════
#  ① 期次 —— 用户说了几期,而实际查了哪几期
#
#  【为什么这条最先做】
#      它是所有要件里【最能算的】:数个数、比集合,一个模型都不用问。
#      ★ 而实测里它正好抓到了一道真错的题。
#  ══════════════════════════════════════════════════════════════════
def 数期次的差(说的, 查的, 库里有的=None):
    """用户【说了】的期次 vs 实际【查了】的期次 —— 对不上就返回一句话。

    ★ 返回 None 表示没问题（那就什么都不说）。

    ═══ ⚠⚠⚠ 2026-10-01 修:这一版【漏了一整类】—— 而它是当天就误报的 ═══
        【症状】
            「浦东2025Q4和2025Q3比，哪一项指标下降最多」
            → 它报:「你点名了 2 个期次,而这一轮只用了 2025Q4 —— 2025Q3 没被查到」
            ★★ 而真相:2025Q3 的【指标得分】库里【根本没有】
              (指标得分表只有 2025Q4 一期;综合得分表才有 9 期)
        【根因 —— 判据只看了两步,而它该看三步】
            说   → 用户点了几期
            查   → 我查了几期
            ★ 缺的第三步:那一期【有没有这个东西可查】
        ★★★ 而那正是这个项目的老区分:【「查不了」≠「查了没有」】。
        【修法】
            库里有的 这个参数由调用方给(那一轮【真的用过的那张表】的期次)。
            ★ 只报【那一类数据里真有的】期次被漏了;
            ★★ 而【那一类数据里没有的】要【另外说】—— 那是"没有这条路",
               不是"我漏查了"。两种都要说,但说成两句不同的话。

    ⚠ 判据是【集合包含】,不是相等:
      实际查的【多于】说的 → 不算错(比如"近两期"多查一期是合理的)
      ★ 实际查的【少了】说的 → 那才要分上面那两种。
    """
    说 = [str(x) for x in (说的 or [])]
    查 = {str(x) for x in (查的 or [])}
    if len(说) < 2:
        return None                      # ★ 只说了一期 —— 那这条检查不适用
    差 = [p for p in 说 if p not in 查]
    if not 差:
        return None

    #  ★ 分成两半 —— 而它们该说成两句不同的话
    if 库里有的 is None:
        漏, 没有 = 差, []                # 调用方没给 —— 只能按老样子报
    else:
        库 = {str(x) for x in 库里有的}
        漏 = [p for p in 差 if p in 库]
        没有 = [p for p in 差 if p not in 库]

    句 = []
    if len(查) == 0 and not 没有:
        句.append(f"⚠ 你这一句里点名了 {len(说)} 个期次({('、'.join(说))}),"
                  f"★ 而这一轮【一个期次都没用上】—— 所以上面的答案跟期次无关。")
    elif 漏:
        句.append(f"⚠ 你这一句里点名了 {len(说)} 个期次({('、'.join(说))}),"
                  f"★ 而这一轮【只用了 {'、'.join(sorted(查)) or '（一个都没用）'}】——"
                  f"【{('、'.join(漏))}】没被查到。"
                  f"★ 所以上面那个答案【没做你想的那个比较】。")
    if 没有:
        #  ★★ 这一句【必须和上面那句不一样】——
        #     "没有这条路"是【如实告知】,不是【我漏了】。
        句.append(f"★ 另外:【{('、'.join(没有))}】这一期,库里【没有这一类数据】——"
                  f"不是我没查,是【没有这条路】。"
                  f"★ 库里这一类数据只有:{('、'.join(sorted(库)))}。")
    return "\n".join(句) if 句 else None


#  ══════════════════════════════════════════════════════════════════
#  ② 歧义 —— 问句里的极值词有【两种读法】吗?
#
#  【★★ 它和"拒答"是两回事】
#      拒答:我【没有】那个数据              → 不该猜
#      反问:我【有】那些数据,而【你说的那句话有两种读法】→ 不该替你选
#
#  【★★★★★ 判据:两种读法,算出来一样吗】
#      「最弱」有两种读法:
#         ① 分数最低          ② 比同档平均差得最多
#      ★ 而这两种【代码都能算】—— 那就别问模型"这句话清不清楚"。
#          一样  → 不用问(怎么理解都对)
#          ★ 不同 → 歧义 → 反问
#
#  ⚠ 第一刀只做【极值词】——
#    因为它的两种读法是【有限可枚举的】。
#    别的歧义("表现怎么样"有几种读法?)没这个结构,留到以后。
#  ══════════════════════════════════════════════════════════════════
极值 = re.compile(r'(最弱|最差|最低|最烂|最强|最好|最高|最优)')


def 判歧义(q, 各):
    """极值词 + 两种读法答案不同 → 返回一句反问;否则 None。

    ★ 各 = [(指标, 自己分, 同档均, 差), …] —— 由调用方算好传进来。
      ⚠ 为什么不在这儿自己查库:那会和 ask.py 互相 import。
        ★★ 而"数据从哪来"和"怎么判"本来就该分开 —— 分开还能单独自检。
    """
    m = 极值.search(str(q or ""))
    if not m:
        return None
    弱向 = m.group(1) in ("最弱", "最差", "最低", "最烂")
    if not 各 or len(各) < 2:
        return None                      # ★ 少于两项,"最"就没意义

    挑 = min if 弱向 else max
    #  ★ 两种读法各挑一次 —— 一次按分数,一次按和同档的差
    按分 = 挑(各, key=lambda x: x[1])
    按差 = 挑(各, key=lambda x: x[3])
    if 按分[0] == 按差[0]:
        return None                      # ★ 同一个指标 → 不歧义,怎么理解都对

    分方向 = "最低" if 弱向 else "最高"
    return (f"你问的「{m.group(1)}」有两种读法,而它们的答案【不一样】:\n"
            f"  · 按【分数{分方向}】       :{按分[0]}（{按分[1]}）\n"
            f"  · 按【比同档平均差得最多】:{按差[0]}（差 {按差[3]:+}）\n"
            f"★ 你要哪一个?")


#  ══════════════════════════════════════════════════════════════════
#  ③ 自检 —— ★ 拿造好的例子撞它自己
#     ⚠ 为什么必须有:报告那条路的硬查【假报过三轮】,而它没自检。
#       被测量只有一套,尺子要"想清楚被测物该干什么"—— 那一层最容易错。
#  ══════════════════════════════════════════════════════════════════
歧义例子 = [
    #  (名字, 问句, 各, 该不该反问)
    #  ★ 数据取自 2025Q4 上海浦东的真值(见 逐项同档数据)
    ("★ 两种读法答案不同 —— 该反问",
     "浦东2025Q4哪一项指标最弱，那一项和同档平均差多少",
     [("航班不正常保障", 3.46, 3.313, 0.147),
      ("出港服务", 4.32, 4.354, -0.034),
      ("机场交通", 4.46, 4.429, 0.031)], True),

    ("两种读法同一个指标 —— 不反问",
     "哪一项最强",
     [("机场交通", 4.46, 4.429, 0.031),
      ("出港服务", 4.32, 4.354, -0.034)], False),

    ("没有极值词 —— 不反问",
     "浦东2025Q4综合得分多少",
     [("机场交通", 4.46, 4.4, 0.06)], False),

    ("只有一项 —— 不反问",
     "哪一项最弱",
     [("机场交通", 4.46, 4.4, 0.06)], False),
]

例子 = [
    #  (名字, 说的, 查的, 该不该报, 库里有的)
    ("只说了一期 —— 这条检查不适用", ["2025Q4"], {"2025Q4"}, False, {"2025Q4"}),

    ("★ 说了两期、只查了一期(库里两期都有) —— 该报【漏了】",
     ["2025Q3", "2025Q4"], {"2025Q4"}, True, {"2025Q3", "2025Q4"}),

    ("说了两期、都查了 —— 不报",
     ["2025Q3", "2025Q4"], {"2025Q3", "2025Q4"}, False, {"2025Q3", "2025Q4"}),

    ("说了两期、查了一期【多查的】—— 不该报",
     ["2025Q4"], {"2025Q3", "2025Q4"}, False, {"2025Q3", "2025Q4"}),

    ("★★ 说了三期、只查了一期 —— 该报",
     ["2025Q2", "2025Q3", "2025Q4"], {"2025Q4"}, True, {"2025Q2", "2025Q3", "2025Q4"}),

    ("说了两期、【一个都没查】—— 该报", ["2025Q3", "2025Q4"], set(), True,
     {"2025Q3", "2025Q4"}),

    #  ═══ ★★★★★ 而这一类【就是当天误报的那一类】 ═══
    ("★★★ 说了两期、而那一期【库里没有这类数据】—— 不能说'我漏查了'",
     ["2025Q3", "2025Q4"], {"2025Q4"}, True, {"2025Q4"}),

    ("★★★ 两期库里都没有 —— 也该报(但说的是'没有这条路')",
     ["2025Q1", "2025Q2"], set(), True, set()),
]


def 自检():
    print("=" * 74)
    print("  覆盖清单 · 自检")
    print("=" * 74)
    过 = 0
    for 名, 说, 查, 该, 库 in 例子:
        句 = 数期次的差(说, 查, 库)
        对 = (句 is not None) == 该
        过 += 对
        print(f"\n  {'✅' if 对 else '❌'} {名}")
        print(f"      说的={说}  查的={sorted(查)}  库里有的={sorted(库)}")
        print(f"      结果:{句 if 句 else '（不报）'}")
    #  ── ② 判歧义那一段 ──
    print("\n" + "=" * 74)
    print("  ② 判歧义 —— 极值词有两种读法吗")
    print("=" * 74)
    for 名, q, 各, 该 in 歧义例子:
        句 = 判歧义(q, 各)
        对 = (句 is not None) == 该
        过 += 对
        print(f"\n  {'✅' if 对 else '❌'} {名}")
        print(f"      问:{str(q)[:44]}")
        print(f"      结果:{句 if 句 else '（不反问）'}")
    总 = len(例子) + len(歧义例子)
    print("\n" + "=" * 74)
    print(f"  {过}/{总} 个对")
    print("=" * 74)
    return 过 == 总


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    sys.exit(0 if 自检() else 1)
