# -*- coding: utf-8 -*-
r"""
覆盖清单 —— 把用户问的【要件】列成一张清单,再逐条勾"答到了没有"。

═══ 为什么要有它（调研结论 + 实测,两边的证据指向同一件事）═══

    【实测:他随口造的两道复杂题】
        「浦东2025Q4和2025Q3比，哪一项指标下降最多」
          → 抽期次抽到了 2025Q3 和 2025Q4 ✓
          → ★ 而查表【只查了 2025Q4】—— 根本没比
          ★★ 而它没出声:格式正常、数字真实、有出处。

        「浦东2025Q4哪一项指标最弱，那一项和同档平均差多少」
          → 查逐项给出了七个指标和同档的对照表
          → ★ 而「最弱的是哪一项」这句话【根本没出现】

    【调研:自我审查治不了这一类,而原因是结构性的】
        有一篇专门量过(《Omission Blindness》,500 对样本、8 种 judge 设计):
            对「加了/改了内容」的区分度: 0.79–0.94   ← 很好
            对「遗漏了内容」的区分度:   ★ 0.50–0.63  ← 接近【抛硬币】
        ★ 换措辞、多数投票、优化提示词 —— 都没能造出可用的"遗漏检测"。

    ★★★ 而机制上的解释(另一篇 ACL 2024):
        给模型 2186 条标注了"第一个逻辑错在哪"的推理链,让它自己找错 ——
        最好的 GPT-4 也只有 52.87%。
        ★★ 但【一旦告诉它错在哪】,它的修正能力就很强。
        → 瓶颈在【检测】,不在【修正】。

═══ ★★★★★ 所以这里的做法是「对着清单勾」,而不是「审自己答得对不对」 ═══

    审自己:  看自己写的那段话 → ★ 它是完整、准确、有出处的 → 没理由打回
    勾清单:  看【从问题里抽出来的要件】→ 逐条对 → ★ 缺的那条【藏不住】

    ★ 而勾的动作【全部用规则】,不用模型判:
        期次对不上 → 数个数、比集合
        ★ 而这正是那个项目一路的规矩:能算的地方,别问大模型。

═══ ⚠ 而"清单"本身【第一刀只做一项】═══
    现在只有【期次】这一条 —— 因为它最能算。
    ★ 别的要件(比如"有没有给出 argmin 的结果")要一个一个接,
      而每一个都该先问:【它能不能用规则勾?】能,才接。

═══ 怎么用 ═══
    python tools/覆盖清单.py            # 拿内置例子跑一遍
    from 覆盖清单 import 数期次的差
    一句 = 数期次的差(用户说的期次, 实际查的期次)
"""
import sys
import io
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))


#  ══════════════════════════════════════════════════════════════════
#  ① 期次 —— 用户说了几期,而实际查了哪几期
#
#  【为什么这条最先做】
#      它是所有要件里【最能算的】:数个数、比集合,一个模型都不用问。
#      ★ 而实测里它正好抓到了一道真错的题。
#  ══════════════════════════════════════════════════════════════════
def 数期次的差(说的, 查的):
    """用户【说了】的期次 vs 实际【查了】的期次 —— 对不上就返回一句话。

    ★ 返回 None 表示没问题（那就什么都不说）。

    ⚠ 判据是【集合包含】,不是相等:
      实际查的【多于】说的 → 不算错(比如"近两期"多查一期是合理的)
      ★ 实际查的【少了】说的 → 那就是漏了。
    """
    说 = [str(x) for x in (说的 or [])]
    查 = {str(x) for x in (查的 or [])}
    if len(说) < 2:
        return None                      # ★ 只说了一期 —— 那这条检查不适用
    漏 = [p for p in 说 if p not in 查]
    if not 漏:
        return None
    if len(查) == 0:
        return (f"⚠ 你这一句里点名了 {len(说)} 个期次({('、'.join(说))}),"
                f"★ 而这一轮【一个期次都没用上】—— 所以上面的答案跟期次无关。")
    return (f"⚠ 你这一句里点名了 {len(说)} 个期次({('、'.join(说))}),"
            f"★ 而这一轮【只用了 {'、'.join(sorted(查))}】——"
            f"【{('、'.join(漏))}】没被查到。"
            f"★ 所以上面那个答案【没做你想的那个比较】。")


#  ══════════════════════════════════════════════════════════════════
#  ② 自检 —— ★ 拿造好的例子撞它自己
#     ⚠ 为什么必须有:报告那条路的硬查【假报过三轮】,而它没自检。
#       被测量只有一套,尺子要"想清楚被测物该干什么"—— 那一层最容易错。
#  ══════════════════════════════════════════════════════════════════
例子 = [
    #  (名字, 说的, 查的, 该不该报)
    ("只说了一期 —— 这条检查不适用", ["2025Q4"], {"2025Q4"}, False),

    ("★ 说了两期、只查了一期 —— 该报", ["2025Q3", "2025Q4"], {"2025Q4"}, True),

    ("说了两期、都查了 —— 不报", ["2025Q3", "2025Q4"], {"2025Q3", "2025Q4"}, False),

    ("说了两期、查了一期【多查的】—— 不该报",
     ["2025Q4"], {"2025Q3", "2025Q4"}, False),

    ("★★ 说了三期、只查了一期 —— 该报",
     ["2025Q2", "2025Q3", "2025Q4"], {"2025Q4"}, True),

    ("说了两期、【一个都没查】—— 该报", ["2025Q3", "2025Q4"], set(), True),
]


def 自检():
    print("=" * 74)
    print("  覆盖清单 · 自检")
    print("=" * 74)
    过 = 0
    for 名, 说, 查, 该 in 例子:
        句 = 数期次的差(说, 查)
        对 = (句 is not None) == 该
        过 += 对
        print(f"\n  {'✅' if 对 else '❌'} {名}")
        print(f"      说的={说}   查的={sorted(查)}")
        print(f"      结果:{句 if 句 else '（不报）'}")
    print(f"\n{'=' * 74}")
    print(f"  {过}/{len(例子)} 个对")
    print("=" * 74)
    return 过 == len(例子)


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    sys.exit(0 if 自检() else 1)
